function extractRows(response) {
  let output = response?.result?.output;
  if (typeof output === 'string') {
    try { output = JSON.parse(output); } catch { return []; }
  }
  if (Array.isArray(output?.rows)) return output.rows;
  if (Array.isArray(output?.result)) return output.result;
  if (Array.isArray(output)) return output;
  return [];
}

async function smoke(serverFunctionId, input = {}) {
  const response = await executeServerFunctionMitra({ projectId, serverFunctionId, input });
  const status = String(response?.result?.executionStatus || '');
  const error = String(response?.result?.error || '').trim();
  if ((status && status !== 'COMPLETED') || error) throw new Error(`SF ${serverFunctionId} falhou: ${error || status}`);
  return extractRows(response);
}

async function update(id, code, description) {
  const current = await readServerFunctionMitra({ projectId, serverFunctionId: id });
  await updateServerFunctionMitra({
    projectId,
    serverFunctionId: id,
    code,
    description: description || current?.result?.description || '',
  });
}

async function main() {
  await update(104, sf104, 'Calcula B/W semanal com faturamento liquido: vendas brutas menos devolucoes, usando a base de faturamento enviada.');
  await update(109, sf109, 'Detalha semanas do cliente com faturamento liquido: vendas brutas menos devolucoes.');
  await update(110, sf110, 'Detalha itens da semana com faturamento liquido por produto: vendas brutas menos devolucoes.');
  await update(111, sf111, 'Resume pedidos da semana com faturamento liquido por pedido: vendas brutas menos devolucoes.');

  const weeklyRows = await smoke(104, {});
  const sample = weeklyRows.find((row) => row.CLIENTE_ID && row.VALOR_SEMANA_ATUAL !== undefined) || weeklyRows[0];
  const detailInput = sample ? {
    ID_CLIENTE: String(sample.CLIENTE_ID),
    ANO: String(new Date().getFullYear()),
    MES: String(new Date().getMonth() + 1),
    SEMANA_NUMERO: '',
  } : { ID_CLIENTE: '0', ANO: '', MES: '', SEMANA_NUMERO: '' };

  const weeks = await smoke(109, detailInput);
  const week = weeks.find((row) => row.SEMANA_NUMERO) || weeks[0];
  const itemInput = {
    ...detailInput,
    ANO: String(week?.ANO || detailInput.ANO),
    MES: String(week?.MES || detailInput.MES),
    SEMANA_NUMERO: String(week?.SEMANA_NUMERO || 1),
  };

  await smoke(110, itemInput);
  await smoke(111, itemInput);
  console.log(JSON.stringify({ updated: [104, 109, 110, 111], sample: itemInput }, null, 2));
}

main().catch((error) => {
  console.error('Falha ao aplicar faturamento liquido pela query base:');
  console.error(error?.message || error);
  process.exit(1);
});
