const ESCOPO_CTE = `
ESCOPO AS (
  SELECT DISTINCT
    EC.ID_CLIENTE,
    EC.CODFILIAL,
    BV.BU_CODIGO AS CODEPTO,
    EC.ID_SECAO
  FROM EQUIPE_CLIENTE EC
  LEFT JOIN FUNCIONARIOS F ON F.ID = EC.ID_VENDEDOR
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = EC.ID_VENDEDOR
    AND BV.CODFILIAL = EC.CODFILIAL
    AND BV.ID_SECAO = EC.ID_SECAO
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE (EC.ID_VENDEDOR = :VAR_USER OR F.ID_SUBSTITUTO = :VAR_USER)
)`;

const DEVOLUCAO_ESCOPO_JOIN = `
JOIN CLIENTES CD ON CD.WINTHOR_CODCLI = D.CODCLI
JOIN ESCOPO E ON E.ID_CLIENTE = CD.ID
  AND E.CODFILIAL = TRIM(COALESCE(CAST(D.CODFILIAL AS CHAR), ''))
  AND E.CODEPTO = TRIM(CAST(D.CODEPTO AS CHAR))
  AND (
    E.ID_SECAO = CAST(D.CODSEC AS SIGNED)
    OR LPAD(TRIM(CAST(E.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(D.CODSEC AS CHAR))
  )`;

