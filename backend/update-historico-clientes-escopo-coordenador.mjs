const projectId = Number(process.env.MITRA_PROJECT_ID);

const BU_EFETIVA_SQL = `COALESCE(
  NULLIF(TRIM('{{idBu}}'), ''),
  (
    SELECT MIN(COALESCE(NULLIF(TRIM(BV_PARAM.BU_CODIGO), ''), 'PADRAO'))
    FROM BU_VENDEDOR BV_PARAM
    WHERE BV_PARAM.VENDEDOR_ID = :VAR_USER
      AND COALESCE(BV_PARAM.ATIVO, TRUE) = TRUE
  ),
  'PADRAO'
)`;

function ownerBuSql(ownerAlias) {
  return `COALESCE(
    (
      SELECT MIN(COALESCE(NULLIF(TRIM(BV_OWNER.BU_CODIGO), ''), 'PADRAO'))
      FROM BU_VENDEDOR BV_OWNER
      WHERE BV_OWNER.VENDEDOR_ID = ${ownerAlias}.ID_VENDEDOR
        AND COALESCE(BV_OWNER.ATIVO, TRUE) = TRUE
    ),
    'PADRAO'
  )`;
}

const TARGET_SCOPE_CTE = `INPUT_SCOPE AS (
  SELECT
    CASE WHEN '{{scopeMode}}' IN ('TEAM', 'SELLER') THEN '{{scopeMode}}' ELSE 'ME' END AS SCOPE_MODE,
    CASE WHEN '{{scopeUserId}}' = '' OR LOCATE('{', '{{scopeUserId}}') > 0 THEN NULL ELSE CAST('{{scopeUserId}}' AS UNSIGNED) END AS SCOPE_USER_ID,
    CASE WHEN '{{scopeCodRca}}' = '' OR LOCATE('{', '{{scopeCodRca}}') > 0 THEN NULL ELSE CAST('{{scopeCodRca}}' AS UNSIGNED) END AS SCOPE_COD_RCA,
    CASE WHEN '{{scopeCodFilial}}' = '' OR LOCATE('{', '{{scopeCodFilial}}') > 0 THEN NULL ELSE TRIM('{{scopeCodFilial}}') END AS SCOPE_CODFILIAL,
    CASE WHEN '{{scopeCodepto}}' = '' OR LOCATE('{', '{{scopeCodepto}}') > 0 THEN NULL ELSE TRIM('{{scopeCodepto}}') END AS SCOPE_CODEPTO,
    CASE WHEN '{{scopeIdSecao}}' = '' OR LOCATE('{', '{{scopeIdSecao}}') > 0 THEN NULL ELSE TRIM('{{scopeIdSecao}}') END AS SCOPE_ID_SECAO
),
TARGET_USERS AS (
  SELECT :VAR_USER AS USER_ID
  FROM INPUT_SCOPE I
  WHERE I.SCOPE_MODE = 'ME'

  UNION

  SELECT F.ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN FUNCIONARIOS F ON F.ID_SUBSTITUTO = :VAR_USER
  WHERE I.SCOPE_MODE = 'ME'

  UNION

  SELECT VR_DONO.USER_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN VENDEDOR_RCA VR_SUB ON VR_SUB.USER_ID = :VAR_USER
  JOIN FERIAS_VENDEDOR FV ON FV.COD_RCA_SUBSTITUTO = VR_SUB.COD_RCA
  JOIN VENDEDOR_RCA VR_DONO ON VR_DONO.COD_RCA = FV.COD_RCA
  WHERE I.SCOPE_MODE = 'ME'
    AND COALESCE(FV.ATIVO, TRUE) = TRUE
    AND CURRENT_DATE BETWEEN FV.DT_INICIO AND FV.DT_FIM

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  WHERE I.SCOPE_MODE = 'TEAM'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  LEFT JOIN VENDEDOR_RCA VR ON VR.USER_ID = BV.VENDEDOR_ID
  WHERE I.SCOPE_MODE = 'SELLER'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (BV.VENDEDOR_ID = I.SCOPE_USER_ID OR VR.COD_RCA = I.SCOPE_COD_RCA)
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
)`;

const CARTEIRA_SCOPE_CTE = `${TARGET_SCOPE_CTE},
CARTEIRA_SCOPE AS (
  SELECT DISTINCT
    EC.ID_CLIENTE,
    EC.ID_VENDEDOR AS VENDEDOR_DONO_CLIENTE
  FROM EQUIPE_CLIENTE EC
  JOIN TARGET_USERS TU ON TU.USER_ID = EC.ID_VENDEDOR
),
BU_SCOPE AS (
  SELECT DISTINCT
    CS.VENDEDOR_DONO_CLIENTE AS TARGET_USER_ID,
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL,
    TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO,
    BV.ID_SECAO
  FROM CARTEIRA_SCOPE CS
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = CS.VENDEDOR_DONO_CLIENTE
  JOIN INPUT_SCOPE I ON 1 = 1
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
)`;

const SQL_MINHA_CARTEIRA = `
WITH ${CARTEIRA_SCOPE_CTE}
SELECT
  C.ID,
  C.RAZAO_SOCIAL,
  C.NOME_FANTASIA,
  C.CNPJ,
  C.CIDADE,
  C.UF,
  C.SEGMENTO,
  C.STATUS,
  MIN(${ownerBuSql('EC')}) AS ID_BU,
  CASE WHEN SUM(CASE WHEN EC.ID_VENDEDOR = :VAR_USER THEN 1 ELSE 0 END) > 0 THEN 0 ELSE 1 END AS IS_COBERTURA,
  CASE WHEN SUM(CASE WHEN EC.ID_VENDEDOR = :VAR_USER THEN 1 ELSE 0 END) > 0 THEN '' ELSE 'COBERTURA' END AS TAG_COBERTURA,
  MIN(COALESCE(IA.DIAS_ULTIMA_COMPRA, 999)) AS DIAS_ULTIMA_COMPRA,
  MIN(COALESCE(VIA.DIAS_SEM_VISITA, 999)) AS DIAS_SEM_VISITA
FROM CLIENTES C
JOIN CARTEIRA_SCOPE CS ON CS.ID_CLIENTE = C.ID
JOIN EQUIPE_CLIENTE EC ON EC.ID_CLIENTE = C.ID AND EC.ID_VENDEDOR = CS.VENDEDOR_DONO_CLIENTE
JOIN BU_SCOPE BS ON BS.TARGET_USER_ID = CS.VENDEDOR_DONO_CLIENTE
LEFT JOIN (
  SELECT USER_ID, MIN(COD_RCA) AS COD_RCA
  FROM VENDEDOR_RCA
  GROUP BY USER_ID
) VR ON VR.USER_ID = CS.VENDEDOR_DONO_CLIENTE
LEFT JOIN (
  SELECT VT.CODCLI, VT.COD_RCA, DATEDIFF(CURRENT_DATE, MAX(SUBSTRING(VT.DTSAIDA, 1, 10))) AS DIAS_ULTIMA_COMPRA
  FROM IMP_VENDAS_DASHBOARD_TOTVS_RCA VT
  GROUP BY VT.CODCLI, VT.COD_RCA
) IA ON TRIM(CAST(IA.CODCLI AS CHAR)) = TRIM(CAST(COALESCE(C.WINTHOR_CODCLI, C.ID) AS CHAR)) AND IA.COD_RCA = VR.COD_RCA
LEFT JOIN (
  SELECT V.CLIENTE_ID, V.VENDEDOR_ID, DATEDIFF(CURRENT_DATE, MAX(CASE WHEN V.STATUS = 'CONCLUIDA' THEN SUBSTRING(V.DATA_AGENDADA, 1, 10) END)) AS DIAS_SEM_VISITA
  FROM VISITAS V
  GROUP BY V.CLIENTE_ID, V.VENDEDOR_ID
) VIA ON VIA.CLIENTE_ID = C.ID AND VIA.VENDEDOR_ID = CS.VENDEDOR_DONO_CLIENTE
WHERE ${ownerBuSql('EC')} = ${BU_EFETIVA_SQL}
  AND (
    '{{busca}}' = ''
    OR C.NOME_FANTASIA LIKE '%{{busca}}%'
    OR C.RAZAO_SOCIAL LIKE '%{{busca}}%'
    OR C.CNPJ LIKE '%{{busca}}%'
    OR CAST(C.ID AS CHAR) LIKE '%{{busca}}%'
  )
GROUP BY C.ID, C.RAZAO_SOCIAL, C.NOME_FANTASIA, C.CNPJ, C.CIDADE, C.UF, C.SEGMENTO, C.STATUS
ORDER BY C.NOME_FANTASIA
LIMIT {{limit}} OFFSET {{offset}}
`;

const SQL_HISTORICO_VISITAS = `
WITH ${CARTEIRA_SCOPE_CTE},
BASE AS (
  SELECT
    V.ID,
    V.DATA_AGENDADA,
    V.HORA_INICIO,
    COALESCE(V.TIPO, 'Visita') AS TIPO,
    V.STATUS,
    V.RELATO,
    'VISITA' AS TIPO_REGISTRO
  FROM VISITAS V
  JOIN CARTEIRA_SCOPE CS ON CS.ID_CLIENTE = V.CLIENTE_ID AND CS.VENDEDOR_DONO_CLIENTE = V.VENDEDOR_ID
  JOIN BU_SCOPE BS ON BS.TARGET_USER_ID = CS.VENDEDOR_DONO_CLIENTE
  WHERE V.CLIENTE_ID = {{clienteId}}

  UNION ALL

  SELECT
    T.ID,
    COALESCE(NULLIF(T.DATA_LIMITE, ''), SUBSTRING(T.CRIADO_EM, 1, 10)) AS DATA_AGENDADA,
    COALESCE(NULLIF(SUBSTRING(T.CRIADO_EM, 12, 5), ''), '--:--') AS HORA_INICIO,
    'Tarefa' AS TIPO,
    T.STATUS,
    COALESCE(NULLIF(T.DESCRICAO, ''), T.TITULO) AS RELATO,
    'TAREFA' AS TIPO_REGISTRO
  FROM TAREFAS T
  JOIN CARTEIRA_SCOPE CS ON CS.ID_CLIENTE = T.CLIENTE_ID AND CS.VENDEDOR_DONO_CLIENTE = T.VENDEDOR_ID
  JOIN BU_SCOPE BS ON BS.TARGET_USER_ID = CS.VENDEDOR_DONO_CLIENTE
  WHERE T.CLIENTE_ID = {{clienteId}}
), FILTRADO AS (
  SELECT *
  FROM BASE
  WHERE ('{{status}}' = '' OR STATUS = '{{status}}')
    AND ('{{dataInicio}}' = '' OR DATA_AGENDADA >= '{{dataInicio}}')
    AND ('{{dataFim}}' = '' OR DATA_AGENDADA <= '{{dataFim}}')
)
SELECT
  F.ID,
  F.DATA_AGENDADA,
  F.HORA_INICIO,
  F.TIPO,
  F.STATUS,
  F.RELATO,
  F.TIPO_REGISTRO,
  (SELECT COUNT(*) FROM FILTRADO FV WHERE FV.TIPO_REGISTRO = 'VISITA') AS TOTAL_VISITAS_PERIODO,
  (SELECT COUNT(*) FROM FILTRADO FT WHERE FT.TIPO_REGISTRO = 'TAREFA') AS TOTAL_TAREFAS_PERIODO
FROM FILTRADO F
ORDER BY F.DATA_AGENDADA DESC, F.HORA_INICIO DESC
LIMIT {{limit}} OFFSET {{offset}}
`;

const VENDAS_SCOPE_CTE = `${CARTEIRA_SCOPE_CTE},
BASE_VENDAS AS (
  SELECT
    V.*,
    CCLI.ID AS CLIENTE_ID_INTERNO,
    CS.VENDEDOR_DONO_CLIENTE
  FROM IMP_VENDAS_DASHBOARD_TOTVS_RCA V
  JOIN CLIENTES CCLI
    ON (CAST(CCLI.ID AS CHAR) = CAST(V.CODCLI AS CHAR) OR CAST(CCLI.WINTHOR_CODCLI AS CHAR) = CAST(V.CODCLI AS CHAR))
  JOIN CARTEIRA_SCOPE CS ON CS.ID_CLIENTE = CCLI.ID
  JOIN VENDEDOR_RCA VR_VENDA
    ON VR_VENDA.USER_ID = CS.VENDEDOR_DONO_CLIENTE
   AND CAST(VR_VENDA.COD_RCA AS CHAR) = CAST(V.COD_RCA AS CHAR)
  JOIN BU_SCOPE B
    ON B.TARGET_USER_ID = CS.VENDEDOR_DONO_CLIENTE
   AND B.CODFILIAL = TRIM(COALESCE(CAST(V.CODFILIAL AS CHAR), ''))
   AND B.CODEPTO = TRIM(CAST(V.CODEPTO AS CHAR))
   AND (
     (B.ID_SECAO IS NOT NULL AND (TRIM(CAST(B.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR)) OR LPAD(TRIM(CAST(B.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR))))
     OR (B.ID_SECAO IS NULL AND NOT EXISTS (
       SELECT 1
       FROM BU_SCOPE B2
       WHERE B2.TARGET_USER_ID = B.TARGET_USER_ID
         AND B2.CODFILIAL = B.CODFILIAL
         AND B2.CODEPTO = B.CODEPTO
         AND B2.ID_SECAO IS NOT NULL
         AND (TRIM(CAST(B2.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR)) OR LPAD(TRIM(CAST(B2.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR)))
     ))
   )
)`;

const SQL_HISTORICO_PEDIDOS = `
WITH ${VENDAS_SCOPE_CTE},
PEDIDOS_BASE AS (
  SELECT
    CAST(VT.NUMPED AS SIGNED) AS PEDIDO_ID,
    MAX(SUBSTRING(VT.DTSAIDA, 1, 10)) AS DATA_PEDIDO,
    'FATURADO' AS STATUS_PEDIDO,
    ROUND(SUM(COALESCE(VT.TOTAL, 0)), 2) AS VALOR_TOTAL,
    0 AS MARGEM_MEDIA,
    COUNT(*) AS TOTAL_ITENS,
    0 AS MIX_ENVIADO
  FROM BASE_VENDAS VT
  WHERE VT.CLIENTE_ID_INTERNO = {{clienteId}}
  GROUP BY VT.NUMPED
),
MIX_BASE AS (
  SELECT
    -M.ID AS PEDIDO_ID,
    SUBSTRING(COALESCE(M.DT_ENVIO_HISTORICO, M.DT_CRIACAO), 1, 10) AS DATA_PEDIDO,
    'MIX' AS STATUS_PEDIDO,
    ROUND(COALESCE(M.TOTAL_VENDA, 0), 2) AS VALOR_TOTAL,
    ROUND(COALESCE(M.MARGEM_MEDIA, 0), 2) AS MARGEM_MEDIA,
    COUNT(MI.ID) AS TOTAL_ITENS,
    1 AS MIX_ENVIADO
  FROM PRODUCT_MIX M
  LEFT JOIN PRODUCT_MIX_ITEMS MI ON MI.ID_MIX = M.ID
  WHERE M.ID_CLIENTE = {{clienteId}}
    AND COALESCE(M.ENVIADO_HISTORICO, FALSE) = TRUE
    AND EXISTS (SELECT 1 FROM CARTEIRA_SCOPE CS WHERE CS.ID_CLIENTE = M.ID_CLIENTE)
  GROUP BY M.ID, M.DT_ENVIO_HISTORICO, M.DT_CRIACAO, M.TOTAL_VENDA, M.MARGEM_MEDIA
),
UNIFICADO AS (
  SELECT * FROM PEDIDOS_BASE
  UNION ALL
  SELECT * FROM MIX_BASE
),
PAGINADO AS (
  SELECT U.*, ROW_NUMBER() OVER (ORDER BY U.DATA_PEDIDO DESC, ABS(U.PEDIDO_ID) DESC) AS RN
  FROM UNIFICADO U
)
SELECT PEDIDO_ID, DATA_PEDIDO, STATUS_PEDIDO, VALOR_TOTAL, MARGEM_MEDIA, TOTAL_ITENS, MIX_ENVIADO
FROM PAGINADO
WHERE RN > {{offset}}
  AND RN <= ({{offset}} + {{limit}})
ORDER BY RN
`;

const SQL_DETALHES_PEDIDO = `
WITH ${VENDAS_SCOPE_CTE}
SELECT *
FROM (
  SELECT
    ROW_NUMBER() OVER (ORDER BY VT.AUTO_ID) AS ITEM_ID,
    CAST(VT.NUMPED AS SIGNED) AS PEDIDO_ID,
    CAST(VT.CODPROD AS CHAR) AS PRODUTO_CODIGO,
    COALESCE(VT.DESCRICAO, CONCAT('Produto ', CAST(VT.CODPROD AS CHAR))) AS PRODUTO_NOME,
    COALESCE(VT.QT, 0) AS QUANTIDADE,
    ROUND(COALESCE(VT.VLUNIT, CASE WHEN COALESCE(VT.QT, 0) = 0 THEN VT.TOTAL ELSE VT.TOTAL / VT.QT END, 0), 2) AS PRECO_UNITARIO,
    0 AS DESCONTO_PERC,
    ROUND(COALESCE(VT.TOTAL, 0), 2) AS TOTAL_ITEM
  FROM BASE_VENDAS VT
  WHERE {{pedidoId}} > 0
    AND VT.CLIENTE_ID_INTERNO = {{clienteId}}
    AND VT.NUMPED = {{pedidoId}}

  UNION ALL

  SELECT
    ROW_NUMBER() OVER (ORDER BY MI.ID) AS ITEM_ID,
    -M.ID AS PEDIDO_ID,
    CAST(COALESCE(PC.CODPROD, P.CODIGO, MI.ID_PRODUTO) AS CHAR) AS PRODUTO_CODIGO,
    COALESCE(PC.NOME, P.NOME, CONCAT('Produto ', CAST(MI.ID_PRODUTO AS CHAR))) AS PRODUTO_NOME,
    MI.QUANTIDADE,
    ROUND(COALESCE(MI.PRECO_VENDA, 0), 2) AS PRECO_UNITARIO,
    0 AS DESCONTO_PERC,
    ROUND(COALESCE(MI.PRECO_VENDA, 0) * COALESCE(MI.QUANTIDADE, 0), 2) AS TOTAL_ITEM
  FROM PRODUCT_MIX M
  JOIN PRODUCT_MIX_ITEMS MI ON MI.ID_MIX = M.ID
  LEFT JOIN PRODUTOS_CUSTOS PC ON PC.CODPROD = MI.ID_PRODUTO
  LEFT JOIN PRODUTOS P ON P.ID = MI.ID_PRODUTO
  WHERE {{pedidoId}} < 0
    AND M.ID = ABS({{pedidoId}})
    AND M.ID_CLIENTE = {{clienteId}}
    AND COALESCE(M.ENVIADO_HISTORICO, FALSE) = TRUE
    AND EXISTS (SELECT 1 FROM CARTEIRA_SCOPE CS WHERE CS.ID_CLIENTE = M.ID_CLIENTE)
) ITENS
ORDER BY ITEM_ID
`;

const UPDATES = [
  ['minhaCarteiraClientes', SQL_MINHA_CARTEIRA, 'Lista clientes da carteira respeitando escopo de coordenador, vendedor e BU.'],
  ['historicoVisitasCliente', SQL_HISTORICO_VISITAS, 'Histórico de visitas e tarefas do cliente respeitando escopo de coordenador e vendedor.'],
  ['historicoPedidosCliente', SQL_HISTORICO_PEDIDOS, 'Histórico de pedidos e mixes do cliente respeitando escopo de coordenador, vendedor e BU.'],
  ['detalhesPedidoCliente', SQL_DETALHES_PEDIDO, 'Itens de pedido ou mix do cliente respeitando escopo de coordenador, vendedor e BU.'],
];

function normalizeArray(value) {
  if (Array.isArray(value)) return value;
  if (Array.isArray(value?.result)) return value.result;
  return [];
}

function extractRows(response) {
  let output = response?.result?.output;
  if (typeof output === 'string') {
    try { output = JSON.parse(output); } catch { return []; }
  }
  if (Array.isArray(output?.rows)) return output.rows;
  if (Array.isArray(output?.result)) return output.result;
  if (Array.isArray(output)) return output;
  return [];
}

async function updateByName(name, code, description) {
  const listed = normalizeArray(await listServerFunctionsMitra({ projectId }));
  const sf = listed.find((item) => item.name === name);
  if (!sf) throw new Error(`SF nao encontrada: ${name}`);
  await updateServerFunctionMitra({ projectId, serverFunctionId: sf.id, code, description });
  return sf.id;
}

async function smoke(serverFunctionId, input) {
  const response = await executeServerFunctionMitra({ projectId, serverFunctionId, input });
  const status = String(response?.result?.executionStatus || '');
  const error = String(response?.result?.error || '').trim();
  if ((status && status !== 'COMPLETED') || error) {
    throw new Error(error || `Execucao finalizada com status ${status}`);
  }
  return extractRows(response).length;
}

async function main() {
  const ids = {};
  for (const [name, code, description] of UPDATES) {
    ids[name] = await updateByName(name, code, description);
  }

  const baseInput = {
    scopeMode: 'ME',
    scopeUserId: '',
    scopeCodRca: '',
    scopeCodFilial: '',
    scopeCodepto: '',
    scopeIdSecao: '',
  };
  await smoke(ids.minhaCarteiraClientes, { busca: '', idBu: '', limit: '1', offset: '0', ...baseInput });
  await smoke(ids.historicoVisitasCliente, { clienteId: '1', status: '', dataInicio: '', dataFim: '', limit: '1', offset: '0', ...baseInput });
  await smoke(ids.historicoPedidosCliente, { clienteId: '1', limit: '1', offset: '0', ...baseInput });
  await smoke(ids.detalhesPedidoCliente, { clienteId: '1', pedidoId: '0', ...baseInput });

  console.log('Histórico de clientes atualizado para escopo de coordenador.');
  console.log(JSON.stringify(ids, null, 2));
}

main().catch((error) => {
  console.error('Falha ao atualizar histórico de clientes para escopo de coordenador:');
  console.error(error?.message || error);
  process.exit(1);
});
