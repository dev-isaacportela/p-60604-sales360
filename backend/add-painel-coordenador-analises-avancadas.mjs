async function upsertServerFunctions() {
  const listed = await listServerFunctionsMitra({ projectId });
  const existing = listed?.result || [];
  const ids = {};

  for (const definition of serverFunctions) {
    const found = existing.find((item) => item.name === definition.name);
    if (found) {
      await updateServerFunctionMitra({
        projectId,
        serverFunctionId: found.id,
        code: definition.code,
        description: definition.description,
      });
      ids[definition.name] = found.id;
      console.log(`${definition.name}: atualizado (${found.id})`);
      continue;
    }

    const created = await createServerFunctionMitra({
      projectId,
      name: definition.name,
      type: 'SQL',
      code: definition.code,
      description: definition.description,
    });
    ids[definition.name] = extractSfId(created);
    console.log(`${definition.name}: criado (${ids[definition.name]})`);
  }

  return ids;
}

async function smoke(ids) {
  const now = new Date();
  const input = { mes: String(now.getMonth() + 1), ano: String(now.getFullYear()) };

  for (const definition of serverFunctions) {
    const id = ids[definition.name];
    if (!id) throw new Error(`ID nao encontrado para ${definition.name}`);
    const result = await executeServerFunctionMitra({ projectId, serverFunctionId: id, input });
    const status = String(result?.result?.executionStatus || '');
    const error = String(result?.result?.error || '').trim();
    if ((status && status !== 'COMPLETED') || error) {
      throw new Error(`${definition.name} falhou: ${error || status}`);
    }
    console.log(`${definition.name}: smoke OK (${extractRows(result).length} linha(s))`);
  }
}

async function main() {
  const ids = await upsertServerFunctions();
  await smoke(ids);
  console.log('Analises avancadas do Painel Coordenador configuradas.');
  console.log(JSON.stringify(ids, null, 2));
}

main().catch((error) => {
  console.error('Erro ao configurar analises avancadas do Painel Coordenador:');
  console.error(error?.message || error);
  process.exit(1);
});
