WITH 
INPUT_SCOPE AS (
  SELECT
    CASE WHEN '{{scopeMode}}' IN ('TEAM', 'SELLER') THEN '{{scopeMode}}' ELSE 'ME' END AS SCOPE_MODE,
    CASE WHEN '{{scopeUserId}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeUserId}}' AS UNSIGNED) ELSE NULL END AS SCOPE_USER_ID,
    CASE WHEN '{{scopeCodRca}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeCodRca}}' AS UNSIGNED) ELSE NULL END AS SCOPE_COD_RCA,
    CASE WHEN '{{scopeCodFilial}}' = '' OR LOCATE('{', '{{scopeCodFilial}}') > 0 THEN NULL ELSE TRIM('{{scopeCodFilial}}') END AS SCOPE_CODFILIAL,
    CASE WHEN '{{scopeCodepto}}' = '' OR LOCATE('{', '{{scopeCodepto}}') > 0 THEN NULL ELSE TRIM('{{scopeCodepto}}') END AS SCOPE_CODEPTO,
    CASE WHEN '{{scopeIdSecao}}' = '' OR LOCATE('{', '{{scopeIdSecao}}') > 0 THEN NULL ELSE TRIM('{{scopeIdSecao}}') END AS SCOPE_ID_SECAO
),
TARGET_USERS AS (
  SELECT :VAR_USER AS USER_ID
  FROM INPUT_SCOPE I
  WHERE I.SCOPE_MODE = 'ME'

  UNION

  SELECT F.ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN FUNCIONARIOS F ON F.ID_SUBSTITUTO = :VAR_USER
  WHERE I.SCOPE_MODE = 'ME'

  UNION

  SELECT VR_DONO.USER_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN VENDEDOR_RCA VR_SUB ON VR_SUB.USER_ID = :VAR_USER
  JOIN FERIAS_VENDEDOR FV ON FV.COD_RCA_SUBSTITUTO = VR_SUB.COD_RCA
  JOIN VENDEDOR_RCA VR_DONO ON VR_DONO.COD_RCA = FV.COD_RCA
  WHERE I.SCOPE_MODE = 'ME'
    AND COALESCE(FV.ATIVO, TRUE) = TRUE
    AND CURRENT_DATE BETWEEN FV.DT_INICIO AND FV.DT_FIM

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  WHERE I.SCOPE_MODE = 'TEAM'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  LEFT JOIN VENDEDOR_RCA VR ON VR.USER_ID = BV.VENDEDOR_ID
  WHERE I.SCOPE_MODE = 'SELLER'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (BV.VENDEDOR_ID = I.SCOPE_USER_ID OR VR.COD_RCA = I.SCOPE_COD_RCA)
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
),
CARTEIRA_LOGADA_RAW AS (
  SELECT
    EC.ID_CLIENTE,
    EC.ID_VENDEDOR
  FROM EQUIPE_CLIENTE EC
  JOIN TARGET_USERS TU ON TU.USER_ID = EC.ID_VENDEDOR
),
CARTEIRA_LOGADA AS (
  SELECT
    BASE.ID_CLIENTE,
    BASE.ID_VENDEDOR AS VENDEDOR_DONO_CLIENTE
  FROM (
    SELECT
      CLR.ID_CLIENTE,
      CLR.ID_VENDEDOR,
      ROW_NUMBER() OVER (
        PARTITION BY CLR.ID_CLIENTE
        ORDER BY
          CASE WHEN CLR.ID_VENDEDOR = :VAR_USER THEN 0 ELSE 1 END,
          CLR.ID_VENDEDOR
      ) AS RN
    FROM CARTEIRA_LOGADA_RAW CLR
  ) BASE
  WHERE BASE.RN = 1
),
BU_SCOPE AS (
  SELECT DISTINCT
    CL.VENDEDOR_DONO_CLIENTE AS TARGET_USER_ID,
    BV.VENDEDOR_ID,
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL,
    TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO,
    BV.ID_SECAO
  FROM CARTEIRA_LOGADA CL
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = CL.VENDEDOR_DONO_CLIENTE
  JOIN INPUT_SCOPE I ON 1 = 1
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) <> ''
    AND TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) <> ''

    AND (
      I.SCOPE_MODE = 'ME'
      OR EXISTS (
        SELECT 1
        FROM COORDENADORES C_SCOPE
        JOIN COORDENADORES_BU CB_SCOPE ON CB_SCOPE.COD_SUPERVISOR = C_SCOPE.COD_SUPERVISOR
        WHERE C_SCOPE.USER_ID = :VAR_USER
          AND COALESCE(C_SCOPE.ATIVO, TRUE) = TRUE
          AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB_SCOPE.CODFILIAL AS CHAR)
          AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB_SCOPE.CODEPTO AS CHAR)
      )
    )
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
),
BASE_VENDAS AS (
  SELECT
    R.*,
    CL.VENDEDOR_DONO_CLIENTE
  FROM PEDIDOS_SEMANAIS_SYNC_RAW R
  JOIN CARTEIRA_LOGADA CL ON CL.ID_CLIENTE = R.CLIENTE_ID
  JOIN BU_SCOPE B ON B.TARGET_USER_ID = CL.VENDEDOR_DONO_CLIENTE AND 
  B.CODFILIAL = TRIM(COALESCE(CAST(R.CODFILIAL AS CHAR), ''))
  AND B.CODEPTO = TRIM(CAST(R.CODEPTO AS CHAR))
  AND (
    (
      B.ID_SECAO IS NOT NULL
      AND (
        TRIM(CAST(B.ID_SECAO AS CHAR)) = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
        OR LPAD(TRIM(CAST(B.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
      )
    )
    OR (
      B.ID_SECAO IS NULL
      AND NOT EXISTS (
        SELECT 1
        FROM BU_SCOPE B2
        WHERE B2.TARGET_USER_ID = B.TARGET_USER_ID
          AND B2.CODFILIAL = B.CODFILIAL
          AND B2.CODEPTO = B.CODEPTO
          AND B2.ID_SECAO IS NOT NULL
          AND (
            TRIM(CAST(B2.ID_SECAO AS CHAR)) = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
            OR LPAD(TRIM(CAST(B2.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
          )
      )
    )
  )

  WHERE R.ATIVO = TRUE
    AND R.STATUS_INGESTAO = 'ATIVO'
    AND R.CLIENTE_ID IS NOT NULL
)
,
    CURVA_MANUAL AS (
      SELECT CL.ID_CLIENTE, MAX(UPPER(TRIM(COALESCE(EC.CURVA_CLASSIFICACAO, '')))) AS CURVA_MANUAL
      FROM CARTEIRA_LOGADA CL
      JOIN EQUIPE_CLIENTE EC ON EC.ID_CLIENTE = CL.ID_CLIENTE AND EC.ID_VENDEDOR = CL.VENDEDOR_DONO_CLIENTE
      WHERE COALESCE(NULLIF(TRIM(EC.CURVA_CLASSIFICACAO), ''), '') <> ''
      GROUP BY CL.ID_CLIENTE
    ),
    HISTORICO_DIAS AS (
      SELECT DISTINCT BV.CLIENTE_ID, STR_TO_DATE(BV.DATA_SAIDA, '%Y-%m-%d') AS DATA_REF
      FROM BASE_VENDAS BV
      WHERE BV.DATA_SAIDA IS NOT NULL AND BV.DATA_SAIDA <> ''
    ),
    ULTIMA_COMPRA AS (
      SELECT HD.CLIENTE_ID, MAX(HD.DATA_REF) AS ULTIMA_COMPRA, DATEDIFF(CURRENT_DATE, MAX(HD.DATA_REF)) AS DIAS_SEM_COMPRAR
      FROM HISTORICO_DIAS HD
      GROUP BY HD.CLIENTE_ID
    ),
    INTERVALOS AS (
      SELECT HD.CLIENTE_ID, DATEDIFF(HD.DATA_REF, LAG(HD.DATA_REF) OVER (PARTITION BY HD.CLIENTE_ID ORDER BY HD.DATA_REF)) AS INTERVALO_DIAS
      FROM HISTORICO_DIAS HD
    ),
    CICLO_MEDIO AS (
      SELECT I.CLIENTE_ID, ROUND(AVG(I.INTERVALO_DIAS)) AS CICLO_MEDIO_DIAS
      FROM INTERVALOS I
      WHERE I.INTERVALO_DIAS IS NOT NULL AND I.INTERVALO_DIAS > 0
      GROUP BY I.CLIENTE_ID
    ),
    TENDENCIA_BASE AS (
      SELECT
        BV.CLIENTE_ID,
        ROUND(SUM(CASE WHEN STR_TO_DATE(BV.DATA_SAIDA, '%Y-%m-%d') >= DATE_SUB(DATE_FORMAT(CURRENT_DATE, '%Y-%m-01'), INTERVAL 2 MONTH) THEN COALESCE(BV.TOTAL, 0) ELSE 0 END), 2) AS VALOR_ULTIMOS_2_MESES,
        ROUND(SUM(CASE WHEN STR_TO_DATE(BV.DATA_SAIDA, '%Y-%m-%d') >= DATE_SUB(DATE_FORMAT(CURRENT_DATE, '%Y-%m-01'), INTERVAL 4 MONTH) AND STR_TO_DATE(BV.DATA_SAIDA, '%Y-%m-%d') < DATE_SUB(DATE_FORMAT(CURRENT_DATE, '%Y-%m-01'), INTERVAL 2 MONTH) THEN COALESCE(BV.TOTAL, 0) ELSE 0 END), 2) AS VALOR_2_MESES_ANTERIORES
      FROM BASE_VENDAS BV
      GROUP BY BV.CLIENTE_ID
    ),
    TENDENCIA AS (
      SELECT
        TB.CLIENTE_ID,
        TB.VALOR_ULTIMOS_2_MESES,
        TB.VALOR_2_MESES_ANTERIORES,
        CASE
          WHEN TB.VALOR_2_MESES_ANTERIORES > 0 THEN ROUND(((TB.VALOR_ULTIMOS_2_MESES - TB.VALOR_2_MESES_ANTERIORES) / TB.VALOR_2_MESES_ANTERIORES) * 100, 2)
          WHEN TB.VALOR_ULTIMOS_2_MESES > 0 THEN 100
          ELSE 0
        END AS VARIACAO_PERCENTUAL
      FROM TENDENCIA_BASE TB
    ),
    ULTIMA_VISITA AS (
      SELECT V.CLIENTE_ID, MAX(STR_TO_DATE(V.DATA_AGENDADA, '%Y-%m-%d')) AS ULTIMA_VISITA
      FROM VISITAS V
      WHERE V.VENDEDOR_ID = :VAR_USER
        AND V.STATUS <> 'CANCELADA'
        AND V.DATA_AGENDADA IS NOT NULL
        AND V.DATA_AGENDADA <> ''
        AND STR_TO_DATE(V.DATA_AGENDADA, '%Y-%m-%d') <= CURRENT_DATE
      GROUP BY V.CLIENTE_ID
    ),
    BASE AS (
      SELECT
        CL.ID_CLIENTE,
        COALESCE(C.NOME_FANTASIA, C.RAZAO_SOCIAL, CONCAT('Cliente ', CL.ID_CLIENTE)) AS NOME_CLIENTE,
        COALESCE(CM.CURVA_MANUAL, CASE WHEN COALESCE(PC.TICKET_MEDIO_3M, 0) >= 15000 THEN 'A' WHEN COALESCE(PC.TICKET_MEDIO_3M, 0) >= 7000 THEN 'B' ELSE 'C' END) AS CURVA,
        COALESCE(NULLIF(C.SEGMENTO, ''), 'Sem segmento') AS SEGMENTO,
        UC.ULTIMA_COMPRA,
        UV.ULTIMA_VISITA,
        COALESCE(UC.DIAS_SEM_COMPRAR, 9999) AS DIAS_SEM_COMPRAR,
        COALESCE(CM2.CICLO_MEDIO_DIAS, 0) AS CICLO_MEDIO_DIAS,
        COALESCE(T.VALOR_ULTIMOS_2_MESES, 0) AS VALOR_ULTIMOS_2_MESES,
        COALESCE(T.VALOR_2_MESES_ANTERIORES, 0) AS VALOR_2_MESES_ANTERIORES,
        COALESCE(T.VARIACAO_PERCENTUAL, 0) AS VARIACAO_PERCENTUAL
      FROM CARTEIRA_LOGADA CL
      LEFT JOIN CLIENTES C ON C.ID = CL.ID_CLIENTE
      LEFT JOIN PERFIL_COMPRA_CLIENTE PC ON PC.CLIENTE_ID = CL.ID_CLIENTE
      LEFT JOIN CURVA_MANUAL CM ON CM.ID_CLIENTE = CL.ID_CLIENTE
      LEFT JOIN ULTIMA_COMPRA UC ON UC.CLIENTE_ID = CL.ID_CLIENTE
      LEFT JOIN CICLO_MEDIO CM2 ON CM2.CLIENTE_ID = CL.ID_CLIENTE
      LEFT JOIN TENDENCIA T ON T.CLIENTE_ID = CL.ID_CLIENTE
      LEFT JOIN ULTIMA_VISITA UV ON UV.CLIENTE_ID = CL.ID_CLIENTE
    ),
    PONTOS AS (
      SELECT
        B.*,
        CASE WHEN B.DIAS_SEM_COMPRAR < 30 THEN 30 WHEN B.DIAS_SEM_COMPRAR < 60 THEN 20 WHEN B.DIAS_SEM_COMPRAR < 90 THEN 10 ELSE 0 END AS PONTOS_RECENCIA,
        CASE WHEN B.CICLO_MEDIO_DIAS <= 0 THEN 0 WHEN B.DIAS_SEM_COMPRAR <= (B.CICLO_MEDIO_DIAS * 1.1) THEN 25 WHEN B.DIAS_SEM_COMPRAR <= (B.CICLO_MEDIO_DIAS * 1.3) THEN 15 WHEN B.DIAS_SEM_COMPRAR <= (B.CICLO_MEDIO_DIAS * 1.6) THEN 5 ELSE 0 END AS PONTOS_FREQUENCIA,
        CASE WHEN B.VARIACAO_PERCENTUAL > 10 THEN 25 WHEN B.VARIACAO_PERCENTUAL >= -10 THEN 15 WHEN B.VARIACAO_PERCENTUAL >= -30 THEN 5 ELSE 0 END AS PONTOS_TENDENCIA,
        CASE WHEN B.ULTIMA_VISITA IS NULL THEN 0 WHEN DATEDIFF(CURRENT_DATE, B.ULTIMA_VISITA) < 30 THEN 20 WHEN DATEDIFF(CURRENT_DATE, B.ULTIMA_VISITA) < 60 THEN 12 WHEN DATEDIFF(CURRENT_DATE, B.ULTIMA_VISITA) < 90 THEN 5 ELSE 0 END AS PONTOS_VISITAS
      FROM BASE B
    )
    SELECT
      P.ID_CLIENTE,
      P.NOME_CLIENTE,
      P.CURVA,
      P.SEGMENTO,
      (P.PONTOS_RECENCIA + P.PONTOS_FREQUENCIA + P.PONTOS_TENDENCIA + P.PONTOS_VISITAS) AS SCORE_TOTAL,
      CASE WHEN (P.PONTOS_RECENCIA + P.PONTOS_FREQUENCIA + P.PONTOS_TENDENCIA + P.PONTOS_VISITAS) >= 70 THEN 'Quente' WHEN (P.PONTOS_RECENCIA + P.PONTOS_FREQUENCIA + P.PONTOS_TENDENCIA + P.PONTOS_VISITAS) >= 40 THEN 'Morno' ELSE 'Frio' END AS TEMPERATURA,
      CASE WHEN P.ULTIMA_COMPRA IS NULL THEN '' ELSE DATE_FORMAT(P.ULTIMA_COMPRA, '%Y-%m-%d') END AS ULTIMA_COMPRA,
      CASE WHEN P.ULTIMA_VISITA IS NULL THEN '' ELSE DATE_FORMAT(P.ULTIMA_VISITA, '%Y-%m-%d') END AS ULTIMA_VISITA,
      P.CICLO_MEDIO_DIAS,
      CASE WHEN P.DIAS_SEM_COMPRAR >= 9999 THEN 0 ELSE P.DIAS_SEM_COMPRAR END AS DIAS_SEM_COMPRAR
    FROM PONTOS P
    ORDER BY SCORE_TOTAL DESC, NOME_CLIENTE