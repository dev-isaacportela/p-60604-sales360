WITH

TITULARES_NORM AS (
  SELECT TRIM(CAST(C_TIT.WINTHOR_CODCLI AS CHAR)) AS CODCLI, T_TIT.CODFILIAL, T_TIT.CODEPTO,
         TRIM(CAST(T_TIT.ID_SECAO AS CHAR)) AS SEC, T_TIT.VENDEDOR_ID
  FROM CLIENTE_TITULAR_DEPTO T_TIT
  JOIN CLIENTES C_TIT ON C_TIT.ID = T_TIT.ID_CLIENTE
  WHERE COALESCE(T_TIT.ATIVO, TRUE) = TRUE
    AND T_TIT.ORIGEM = 'MANUAL'
    AND C_TIT.WINTHOR_CODCLI IS NOT NULL
    AND T_TIT.VENDEDOR_ID NOT IN (
    SELECT UB_EXC.USER_ID FROM USUARIO_BLOQUEIO UB_EXC WHERE UB_EXC.BLOQUEADO = 1
    UNION
    SELECT UI_EXC.ID FROM INT_USER UI_EXC WHERE LOWER(TRIM(UI_EXC.DESCR)) IN ('comunicacao@benenutri.com')
  )
  UNION
  SELECT TRIM(CAST(C_TIT.WINTHOR_CODCLI AS CHAR)), T_TIT.CODFILIAL, T_TIT.CODEPTO,
         LPAD(TRIM(CAST(T_TIT.ID_SECAO AS CHAR)), 2, '0'), T_TIT.VENDEDOR_ID
  FROM CLIENTE_TITULAR_DEPTO T_TIT
  JOIN CLIENTES C_TIT ON C_TIT.ID = T_TIT.ID_CLIENTE
  WHERE COALESCE(T_TIT.ATIVO, TRUE) = TRUE
    AND T_TIT.ORIGEM = 'MANUAL'
    AND C_TIT.WINTHOR_CODCLI IS NOT NULL
    AND T_TIT.VENDEDOR_ID NOT IN (
    SELECT UB_EXC.USER_ID FROM USUARIO_BLOQUEIO UB_EXC WHERE UB_EXC.BLOQUEADO = 1
    UNION
    SELECT UI_EXC.ID FROM INT_USER UI_EXC WHERE LOWER(TRIM(UI_EXC.DESCR)) IN ('comunicacao@benenutri.com')
  )

),
EMPATES_CAND AS (
  SELECT DISTINCT EC_EMP.ID_CLIENTE, TRIM(CAST(C_EMP.WINTHOR_CODCLI AS CHAR)) AS CODCLI,
         TRIM(CAST(BV_EMP.CODFILIAL AS CHAR)) AS CODFILIAL, TRIM(CAST(BV_EMP.BU_CODIGO AS CHAR)) AS CODEPTO,
         BV_EMP.ID_SECAO, BV_EMP.VENDEDOR_ID
  FROM EQUIPE_CLIENTE EC_EMP
  JOIN CLIENTES C_EMP ON C_EMP.ID = EC_EMP.ID_CLIENTE
  JOIN BU_VENDEDOR BV_EMP ON BV_EMP.VENDEDOR_ID = EC_EMP.ID_VENDEDOR AND COALESCE(BV_EMP.ATIVO, TRUE) = TRUE
  WHERE BV_EMP.ID_SECAO IS NOT NULL
    AND C_EMP.WINTHOR_CODCLI IS NOT NULL
    AND BV_EMP.VENDEDOR_ID NOT IN (
    SELECT UB_EXC.USER_ID FROM USUARIO_BLOQUEIO UB_EXC WHERE UB_EXC.BLOQUEADO = 1
    UNION
    SELECT UI_EXC.ID FROM INT_USER UI_EXC WHERE LOWER(TRIM(UI_EXC.DESCR)) IN ('comunicacao@benenutri.com')
  )
),
EMPATES_PEND AS (
  SELECT EC1.CODCLI, EC1.CODFILIAL, EC1.CODEPTO, EC1.ID_SECAO, EC1.VENDEDOR_ID
  FROM EMPATES_CAND EC1
  JOIN (
    SELECT ID_CLIENTE, CODFILIAL, CODEPTO, ID_SECAO
    FROM EMPATES_CAND
    GROUP BY ID_CLIENTE, CODFILIAL, CODEPTO, ID_SECAO
    HAVING COUNT(DISTINCT VENDEDOR_ID) > 1
  ) K ON K.ID_CLIENTE = EC1.ID_CLIENTE AND K.CODFILIAL = EC1.CODFILIAL
     AND K.CODEPTO = EC1.CODEPTO AND K.ID_SECAO = EC1.ID_SECAO
  LEFT JOIN CLIENTE_TITULAR_DEPTO T_EMP
    ON T_EMP.ID_CLIENTE = EC1.ID_CLIENTE AND T_EMP.CODFILIAL = EC1.CODFILIAL
   AND T_EMP.CODEPTO = EC1.CODEPTO AND T_EMP.ID_SECAO = EC1.ID_SECAO
   AND T_EMP.ORIGEM = 'MANUAL' AND COALESCE(T_EMP.ATIVO, TRUE) = TRUE
   AND T_EMP.VENDEDOR_ID NOT IN (
    SELECT UB_EXC.USER_ID FROM USUARIO_BLOQUEIO UB_EXC WHERE UB_EXC.BLOQUEADO = 1
    UNION
    SELECT UI_EXC.ID FROM INT_USER UI_EXC WHERE LOWER(TRIM(UI_EXC.DESCR)) IN ('comunicacao@benenutri.com')
  )
  WHERE T_EMP.ID IS NULL
),
EMPATES_NORM AS (
  SELECT CODCLI, CODFILIAL, CODEPTO, TRIM(CAST(ID_SECAO AS CHAR)) AS SEC, VENDEDOR_ID FROM EMPATES_PEND
  UNION
  SELECT CODCLI, CODFILIAL, CODEPTO, LPAD(TRIM(CAST(ID_SECAO AS CHAR)), 2, '0'), VENDEDOR_ID FROM EMPATES_PEND
),
INPUT_SCOPE AS (
  SELECT
    CASE WHEN '{{scopeMode}}' IN ('TEAM', 'SELLER', 'GLOBAL') THEN '{{scopeMode}}' ELSE 'ME' END AS SCOPE_MODE,
    CASE WHEN '{{scopeUserId}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeUserId}}' AS UNSIGNED) ELSE NULL END AS SCOPE_USER_ID,
    CASE WHEN '{{scopeCodRca}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeCodRca}}' AS UNSIGNED) ELSE NULL END AS SCOPE_COD_RCA,
    CASE WHEN '{{scopeCodFilial}}' = '' OR LOCATE('{', '{{scopeCodFilial}}') > 0 THEN NULL ELSE TRIM('{{scopeCodFilial}}') END AS SCOPE_CODFILIAL,
    CASE WHEN '{{scopeCodepto}}' = '' OR LOCATE('{', '{{scopeCodepto}}') > 0 THEN NULL ELSE TRIM('{{scopeCodepto}}') END AS SCOPE_CODEPTO,
    CASE WHEN '{{scopeIdSecao}}' = '' OR LOCATE('{', '{{scopeIdSecao}}') > 0 THEN NULL ELSE TRIM('{{scopeIdSecao}}') END AS SCOPE_ID_SECAO,
    CASE WHEN '{{scopeCodSupervisor}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeCodSupervisor}}' AS UNSIGNED) ELSE NULL END AS SCOPE_COD_SUPERVISOR
),
TARGET_USERS AS (
  SELECT :VAR_USER AS USER_ID
  FROM INPUT_SCOPE I
  WHERE I.SCOPE_MODE = 'ME'
  UNION
  SELECT F.ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN FUNCIONARIOS F ON F.ID_SUBSTITUTO = :VAR_USER
  WHERE I.SCOPE_MODE = 'ME'
  UNION
  SELECT VR_DONO.USER_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN VENDEDOR_RCA VR_SUB ON VR_SUB.USER_ID = :VAR_USER
  JOIN FERIAS_VENDEDOR FV ON FV.COD_RCA_SUBSTITUTO = VR_SUB.COD_RCA
  JOIN VENDEDOR_RCA VR_DONO ON VR_DONO.COD_RCA = FV.COD_RCA
  WHERE I.SCOPE_MODE = 'ME'
    AND COALESCE(FV.ATIVO, TRUE) = TRUE
    AND CURRENT_DATE BETWEEN FV.DT_INICIO AND FV.DT_FIM
  UNION
  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  WHERE I.SCOPE_MODE = 'TEAM'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND NOT EXISTS (
      SELECT 1
      FROM COORDENADORES C_COORD_ALVO
      WHERE C_COORD_ALVO.USER_ID = BV.VENDEDOR_ID
        AND COALESCE(C_COORD_ALVO.ATIVO, TRUE) = TRUE
        AND C_COORD_ALVO.USER_ID <> :VAR_USER
    )
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
  UNION
  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN INT_USER U ON U.ID = :VAR_USER
  LEFT JOIN USUARIO_CARGO UC ON UC.USER_ID = U.ID
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  LEFT JOIN VENDEDOR_RCA VR ON VR.USER_ID = BV.VENDEDOR_ID
  WHERE I.SCOPE_MODE = 'SELLER'
    AND (BV.VENDEDOR_ID = I.SCOPE_USER_ID OR VR.COD_RCA = I.SCOPE_COD_RCA)
    AND (
      UPPER(COALESCE(UC.CARGO, '')) IN ('ADMIN', 'DIRETORIA')
      OR LOWER(COALESCE(U.DESCR, '')) = 'ti@benenutri.com'
      OR EXISTS (
        SELECT 1
        FROM COORDENADORES C
        JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
        WHERE C.USER_ID = :VAR_USER
          AND COALESCE(C.ATIVO, TRUE) = TRUE
          AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
          AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
      )
    )
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
  UNION
  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN INT_USER U ON U.ID = :VAR_USER
  LEFT JOIN USUARIO_CARGO UC ON UC.USER_ID = U.ID
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE I.SCOPE_MODE = 'GLOBAL'
    AND (
      UPPER(COALESCE(UC.CARGO, '')) IN ('ADMIN', 'DIRETORIA')
      OR LOWER(COALESCE(U.DESCR, '')) = 'ti@benenutri.com'
    )
    AND (
      I.SCOPE_COD_SUPERVISOR IS NULL
      OR EXISTS (
        SELECT 1
        FROM COORDENADORES C_GLOBAL_SELF
        WHERE C_GLOBAL_SELF.USER_ID = BV.VENDEDOR_ID
          AND COALESCE(C_GLOBAL_SELF.ATIVO, TRUE) = TRUE
          AND C_GLOBAL_SELF.COD_SUPERVISOR = I.SCOPE_COD_SUPERVISOR
      )
      OR (
        NOT EXISTS (
          SELECT 1
          FROM COORDENADORES C_GLOBAL_OTHER_COORD
          WHERE C_GLOBAL_OTHER_COORD.USER_ID = BV.VENDEDOR_ID
            AND COALESCE(C_GLOBAL_OTHER_COORD.ATIVO, TRUE) = TRUE
        )
        AND EXISTS (
          SELECT 1
          FROM COORDENADORES_BU CB_GLOBAL
          WHERE CB_GLOBAL.COD_SUPERVISOR = I.SCOPE_COD_SUPERVISOR
            AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB_GLOBAL.CODFILIAL AS CHAR)
            AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB_GLOBAL.CODEPTO AS CHAR)
        )
      )
    )
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
),
BU_SCOPE AS (
  SELECT DISTINCT
    TU.USER_ID AS USER_ID,
    BV.VENDEDOR_ID,
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL,
    TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS ID_BU,
    BV.ID_SECAO
  FROM TARGET_USERS TU
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = TU.USER_ID
  JOIN INPUT_SCOPE I ON 1 = 1
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) <> ''
    AND TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) <> ''
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
),
CARTEIRA_SCOPE AS (
  SELECT DISTINCT
    TU.USER_ID,
    C.ID AS CLIENTE_ID,
    COALESCE(C.WINTHOR_CODCLI, C.ID) AS CODCLI
  FROM EQUIPE_CLIENTE EC
  JOIN TARGET_USERS TU ON TU.USER_ID = EC.ID_VENDEDOR
  JOIN CLIENTES C ON C.ID = EC.ID_CLIENTE
  WHERE C.ID IS NOT NULL
),
INPUTS AS (
  SELECT
    CASE
      WHEN '{{dataInicio}}' REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN '{{dataInicio}}'
      ELSE DATE_FORMAT(CURRENT_DATE, '%Y-%m-01')
    END AS DATA_INICIO,
    CASE
      WHEN '{{dataFim}}' REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN '{{dataFim}}'
      ELSE DATE_FORMAT(LAST_DAY(CURRENT_DATE), '%Y-%m-%d')
    END AS DATA_FIM,
    CASE
      WHEN '{{departamentos}}' = '' OR LOCATE('{', '{{departamentos}}') > 0 THEN NULL
      ELSE TRIM('{{departamentos}}')
    END AS DEPARTAMENTOS_PARAM,
    CASE
      WHEN '{{ramos}}' = '' OR LOCATE('{', '{{ramos}}') > 0 THEN NULL
      ELSE TRIM('{{ramos}}')
    END AS RAMOS_PARAM,
    CASE
      WHEN '{{cliente}}' = '' OR LOCATE('{', '{{cliente}}') > 0 THEN NULL
      ELSE REPLACE(TRIM('{{cliente}}'), '|', ',')
    END AS CLIENTE_PARAM,
    CASE WHEN '{{limit}}' REGEXP '^[0-9]+$' THEN CAST('{{limit}}' AS UNSIGNED) ELSE 100 END AS LIMIT_PARAM,
    CASE WHEN '{{offset}}' REGEXP '^[0-9]+$' THEN CAST('{{offset}}' AS UNSIGNED) ELSE 0 END AS OFFSET_PARAM
),
PERIODO_BASE AS (
  SELECT
    I.*,
    STR_TO_DATE(I.DATA_INICIO, '%Y-%m-%d') AS DT_INICIO,
    STR_TO_DATE(I.DATA_FIM, '%Y-%m-%d') AS DT_FIM
  FROM INPUTS I
),
PERIODO AS (
  SELECT
    PB.*,
    GREATEST(DATEDIFF(PB.DT_FIM, PB.DT_INICIO) + 1, 1) AS DIAS_PERIODO,
    DATE_SUB(PB.DT_INICIO, INTERVAL GREATEST(DATEDIFF(PB.DT_FIM, PB.DT_INICIO) + 1, 1) DAY) AS DT_INICIO_ANTERIOR,
    DATE_SUB(PB.DT_INICIO, INTERVAL 1 DAY) AS DT_FIM_ANTERIOR
  FROM PERIODO_BASE PB
)
,
VENDAS AS (
  SELECT
    ROUND(COALESCE(SUM(COALESCE(V.TOTAL, 0)), 0), 2) AS FATURAMENTO_BRUTO,
    COUNT(DISTINCT V.NUMPED) AS QTD_PEDIDOS,
    COUNT(DISTINCT V.CODCLI) AS CLIENTES_COM_COMPRA
  FROM (SELECT V_SRC.* FROM IMP_VENDAS_DASHBOARD_TOTVS_RCA V_SRC WHERE NOT EXISTS (
      SELECT 1 FROM TITULARES_NORM TF
      WHERE TF.CODCLI = TRIM(CAST(V_SRC.CODCLI AS CHAR)) AND TF.CODFILIAL = TRIM(COALESCE(CAST(V_SRC.CODFILIAL AS CHAR), ''))
        AND TF.CODEPTO = TRIM(CAST(V_SRC.CODEPTO AS CHAR)) AND TF.SEC = TRIM(CAST(V_SRC.CODSEC AS CHAR))
        AND TF.VENDEDOR_ID NOT IN (SELECT TU_TIT.USER_ID FROM TARGET_USERS TU_TIT)
    )) V

    JOIN BU_SCOPE BS
      ON BS.CODFILIAL = TRIM(COALESCE(CAST(V.CODFILIAL AS CHAR), ''))
     AND BS.ID_BU = TRIM(CAST(V.CODEPTO AS CHAR))
     AND (
       BS.ID_SECAO IS NULL
       OR TRIM(CAST(BS.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR))
       OR LPAD(TRIM(CAST(BS.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR))
     )

    JOIN CARTEIRA_SCOPE CS
      ON TRIM(CAST(CS.CODCLI AS CHAR)) = TRIM(CAST(V.CODCLI AS CHAR))
     AND CS.USER_ID = BS.USER_ID
  AND NOT EXISTS (
      SELECT 1 FROM TITULARES_NORM TN_ROW
      WHERE TN_ROW.CODCLI = TRIM(CAST(V.CODCLI AS CHAR)) AND TN_ROW.CODFILIAL = TRIM(COALESCE(CAST(V.CODFILIAL AS CHAR), ''))
        AND TN_ROW.CODEPTO = TRIM(CAST(V.CODEPTO AS CHAR)) AND TN_ROW.SEC = TRIM(CAST(V.CODSEC AS CHAR))
        AND TN_ROW.VENDEDOR_ID <> BS.USER_ID
    )
  AND NOT EXISTS (
      SELECT 1 FROM EMPATES_NORM EN_ROW
      WHERE EN_ROW.CODCLI = TRIM(CAST(V.CODCLI AS CHAR)) AND EN_ROW.CODFILIAL = TRIM(COALESCE(CAST(V.CODFILIAL AS CHAR), ''))
        AND EN_ROW.CODEPTO = TRIM(CAST(V.CODEPTO AS CHAR)) AND EN_ROW.SEC = TRIM(CAST(V.CODSEC AS CHAR))
        AND EN_ROW.VENDEDOR_ID < BS.USER_ID
        AND EN_ROW.VENDEDOR_ID IN (SELECT TU_EMP.USER_ID FROM TARGET_USERS TU_EMP)
    )

  JOIN PERIODO P ON 1 = 1
  WHERE 1 = 1

    AND V.DTSAIDA >= DATE_FORMAT(P.DT_INICIO, '%Y-%m-%d')
    AND V.DTSAIDA <= DATE_FORMAT(P.DT_FIM, '%Y-%m-%d')
    AND (
      P.DEPARTAMENTOS_PARAM IS NULL
      OR INSTR(CONCAT('|', P.DEPARTAMENTOS_PARAM, '|'), CONCAT('|', TRIM(CAST(V.CODEPTO AS CHAR)), '|')) > 0
    )
    AND (
      P.RAMOS_PARAM IS NULL
      OR INSTR(
        CONCAT('|', P.RAMOS_PARAM, '|'),
        CONCAT('|', REPLACE(COALESCE(NULLIF(TRIM(CAST(V.RAMO_CLIENTE AS CHAR)), ''), 'Sem ramo'), '''', ''), '|')
      ) > 0
    )
    AND (
      P.CLIENTE_PARAM IS NULL
      OR FIND_IN_SET(TRIM(CAST(V.CODCLI AS CHAR)), P.CLIENTE_PARAM) > 0
    )

),
DEVOLUCOES AS (
  SELECT ROUND(COALESCE(SUM(COALESCE(D.VALOR_DEVOLVIDO, 0)), 0), 2) AS TOTAL_DEVOLVIDO
  FROM (SELECT D_SRC.* FROM IMP_DEVOLUCOES_TOTVS D_SRC WHERE NOT EXISTS (
      SELECT 1 FROM TITULARES_NORM TF
      WHERE TF.CODCLI = TRIM(CAST(D_SRC.CODCLI AS CHAR)) AND TF.CODFILIAL = TRIM(COALESCE(CAST(D_SRC.CODFILIAL AS CHAR), ''))
        AND TF.CODEPTO = TRIM(CAST(D_SRC.CODEPTO AS CHAR)) AND TF.SEC = TRIM(CAST(D_SRC.CODSEC AS CHAR))
        AND TF.VENDEDOR_ID NOT IN (SELECT TU_TIT.USER_ID FROM TARGET_USERS TU_TIT)
    )) D

    JOIN BU_SCOPE BS
      ON BS.CODFILIAL = TRIM(COALESCE(CAST(D.CODFILIAL AS CHAR), ''))
     AND BS.ID_BU = TRIM(CAST(D.CODEPTO AS CHAR))
     AND (
       BS.ID_SECAO IS NULL
       OR TRIM(CAST(BS.ID_SECAO AS CHAR)) = TRIM(CAST(D.CODSEC AS CHAR))
       OR LPAD(TRIM(CAST(BS.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(D.CODSEC AS CHAR))
     )

    JOIN CARTEIRA_SCOPE CS
      ON TRIM(CAST(CS.CODCLI AS CHAR)) = TRIM(CAST(D.CODCLI AS CHAR))
     AND CS.USER_ID = BS.USER_ID
  AND NOT EXISTS (
      SELECT 1 FROM TITULARES_NORM TN_ROW
      WHERE TN_ROW.CODCLI = TRIM(CAST(D.CODCLI AS CHAR)) AND TN_ROW.CODFILIAL = TRIM(COALESCE(CAST(D.CODFILIAL AS CHAR), ''))
        AND TN_ROW.CODEPTO = TRIM(CAST(D.CODEPTO AS CHAR)) AND TN_ROW.SEC = TRIM(CAST(D.CODSEC AS CHAR))
        AND TN_ROW.VENDEDOR_ID <> BS.USER_ID
    )
  AND NOT EXISTS (
      SELECT 1 FROM EMPATES_NORM EN_ROW
      WHERE EN_ROW.CODCLI = TRIM(CAST(D.CODCLI AS CHAR)) AND EN_ROW.CODFILIAL = TRIM(COALESCE(CAST(D.CODFILIAL AS CHAR), ''))
        AND EN_ROW.CODEPTO = TRIM(CAST(D.CODEPTO AS CHAR)) AND EN_ROW.SEC = TRIM(CAST(D.CODSEC AS CHAR))
        AND EN_ROW.VENDEDOR_ID < BS.USER_ID
        AND EN_ROW.VENDEDOR_ID IN (SELECT TU_EMP.USER_ID FROM TARGET_USERS TU_EMP)
    )

  JOIN PERIODO P ON 1 = 1
  WHERE 1 = 1

    AND D.DATA_DEVOLUCAO >= DATE_FORMAT(P.DT_INICIO, '%Y-%m-%d')
    AND D.DATA_DEVOLUCAO <= DATE_FORMAT(P.DT_FIM, '%Y-%m-%d')
    AND (
      P.DEPARTAMENTOS_PARAM IS NULL
      OR INSTR(CONCAT('|', P.DEPARTAMENTOS_PARAM, '|'), CONCAT('|', TRIM(CAST(D.CODEPTO AS CHAR)), '|')) > 0
    )
    AND (
      P.RAMOS_PARAM IS NULL
      OR INSTR(
        CONCAT('|', P.RAMOS_PARAM, '|'),
        CONCAT('|', REPLACE(COALESCE(NULLIF(TRIM(CAST(D.RAMO_CLIENTE AS CHAR)), ''), 'Sem ramo'), '''', ''), '|')
      ) > 0
    )
    AND (
      P.CLIENTE_PARAM IS NULL
      OR FIND_IN_SET(TRIM(CAST(D.CODCLI AS CHAR)), P.CLIENTE_PARAM) > 0
    )

),
METAS_PERIODO AS (
  SELECT ROUND(COALESCE(SUM(MBV.META_VALOR), 0), 2) AS VALOR_META
  FROM METAS_BU_VENDEDOR MBV
  JOIN PERIODO P ON 1 = 1
  JOIN INPUT_SCOPE I ON 1 = 1
  WHERE MBV.VENDEDOR_ID IN (SELECT USER_ID FROM TARGET_USERS)
    AND STR_TO_DATE(CONCAT(MBV.ANO, '-', LPAD(MBV.MES, 2, '0'), '-01'), '%Y-%m-%d')
        BETWEEN DATE_FORMAT(P.DT_INICIO, '%Y-%m-01') AND DATE_FORMAT(P.DT_FIM, '%Y-%m-01')
    -- CORRECAO: meta tambem respeita o depto selecionado na tela (scopeCodepto),
    -- alem do parametro explicito {{departamentos}}, para ficar consistente com a venda.
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(MBV.CODEPTO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      P.DEPARTAMENTOS_PARAM IS NULL
      OR INSTR(CONCAT('|', P.DEPARTAMENTOS_PARAM, '|'), CONCAT('|', TRIM(CAST(MBV.CODEPTO AS CHAR)), '|')) > 0
    )
)
SELECT
  P.DATA_INICIO,
  P.DATA_FIM,
  P.DIAS_PERIODO,
  COALESCE(M.VALOR_META, 0) AS VALOR_META,
  COALESCE(V.FATURAMENTO_BRUTO, 0) AS FATURAMENTO_BRUTO,
  COALESCE(D.TOTAL_DEVOLVIDO, 0) AS TOTAL_DEVOLVIDO,
  ROUND(GREATEST(COALESCE(V.FATURAMENTO_BRUTO, 0) - COALESCE(D.TOTAL_DEVOLVIDO, 0), 0), 2) AS FATURAMENTO_LIQUIDO,
  ROUND(GREATEST(COALESCE(M.VALOR_META, 0) - GREATEST(COALESCE(V.FATURAMENTO_BRUTO, 0) - COALESCE(D.TOTAL_DEVOLVIDO, 0), 0), 0), 2) AS VALOR_FALTANTE,
  CASE
    WHEN COALESCE(M.VALOR_META, 0) <= 0 THEN 0
    ELSE ROUND((GREATEST(COALESCE(V.FATURAMENTO_BRUTO, 0) - COALESCE(D.TOTAL_DEVOLVIDO, 0), 0) / M.VALOR_META) * 100, 2)
  END AS PERCENTUAL_META,
  CASE
    WHEN COALESCE(V.FATURAMENTO_BRUTO, 0) <= 0 THEN 0
    ELSE ROUND((COALESCE(D.TOTAL_DEVOLVIDO, 0) / V.FATURAMENTO_BRUTO) * 100, 2)
  END AS PERCENTUAL_DEVOLVIDO,
  COALESCE(V.QTD_PEDIDOS, 0) AS QTD_PEDIDOS,
  COALESCE(V.CLIENTES_COM_COMPRA, 0) AS CLIENTES_COM_COMPRA
FROM PERIODO P
JOIN VENDAS V ON 1 = 1
JOIN DEVOLUCOES D ON 1 = 1
JOIN METAS_PERIODO M ON 1 = 1
LIMIT 1
