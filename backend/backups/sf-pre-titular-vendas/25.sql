
WITH INPUT_SCOPE AS (
  SELECT
    CASE WHEN '{{scopeMode}}' IN ('TEAM', 'SELLER') THEN '{{scopeMode}}' ELSE 'ME' END AS SCOPE_MODE,
    CASE WHEN '{{scopeUserId}}' = '' OR LOCATE('{', '{{scopeUserId}}') > 0 THEN NULL ELSE CAST('{{scopeUserId}}' AS UNSIGNED) END AS SCOPE_USER_ID,
    CASE WHEN '{{scopeCodRca}}' = '' OR LOCATE('{', '{{scopeCodRca}}') > 0 THEN NULL ELSE CAST('{{scopeCodRca}}' AS UNSIGNED) END AS SCOPE_COD_RCA,
    CASE WHEN '{{scopeCodFilial}}' = '' OR LOCATE('{', '{{scopeCodFilial}}') > 0 THEN NULL ELSE TRIM('{{scopeCodFilial}}') END AS SCOPE_CODFILIAL,
    CASE WHEN '{{scopeCodepto}}' = '' OR LOCATE('{', '{{scopeCodepto}}') > 0 THEN NULL ELSE TRIM('{{scopeCodepto}}') END AS SCOPE_CODEPTO,
    CASE WHEN '{{scopeIdSecao}}' = '' OR LOCATE('{', '{{scopeIdSecao}}') > 0 THEN NULL ELSE TRIM('{{scopeIdSecao}}') END AS SCOPE_ID_SECAO
),
TARGET_USERS AS (
  SELECT :VAR_USER AS USER_ID
  FROM INPUT_SCOPE I
  WHERE I.SCOPE_MODE = 'ME'

  UNION

  SELECT F.ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN FUNCIONARIOS F ON F.ID_SUBSTITUTO = :VAR_USER
  WHERE I.SCOPE_MODE = 'ME'

  UNION

  SELECT VR_DONO.USER_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN VENDEDOR_RCA VR_SUB ON VR_SUB.USER_ID = :VAR_USER
  JOIN FERIAS_VENDEDOR FV ON FV.COD_RCA_SUBSTITUTO = VR_SUB.COD_RCA
  JOIN VENDEDOR_RCA VR_DONO ON VR_DONO.COD_RCA = FV.COD_RCA
  WHERE I.SCOPE_MODE = 'ME'
    AND COALESCE(FV.ATIVO, TRUE) = TRUE
    AND CURRENT_DATE BETWEEN FV.DT_INICIO AND FV.DT_FIM

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  WHERE I.SCOPE_MODE = 'TEAM'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  LEFT JOIN VENDEDOR_RCA VR ON VR.USER_ID = BV.VENDEDOR_ID
  WHERE I.SCOPE_MODE = 'SELLER'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (BV.VENDEDOR_ID = I.SCOPE_USER_ID OR VR.COD_RCA = I.SCOPE_COD_RCA)
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
),
CARTEIRA_SCOPE AS (
  SELECT DISTINCT
    EC.ID_CLIENTE,
    EC.ID_VENDEDOR AS VENDEDOR_DONO_CLIENTE
  FROM EQUIPE_CLIENTE EC
  JOIN TARGET_USERS TU ON TU.USER_ID = EC.ID_VENDEDOR
),
BU_SCOPE AS (
  SELECT DISTINCT
    CS.VENDEDOR_DONO_CLIENTE AS TARGET_USER_ID,
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL,
    TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO,
    BV.ID_SECAO
  FROM CARTEIRA_SCOPE CS
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = CS.VENDEDOR_DONO_CLIENTE
  JOIN INPUT_SCOPE I ON 1 = 1
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
),
BASE_VENDAS AS (
  SELECT
    V.*,
    CCLI.ID AS CLIENTE_ID_INTERNO,
    CS.VENDEDOR_DONO_CLIENTE
  FROM IMP_VENDAS_DASHBOARD_TOTVS_RCA V
  JOIN CLIENTES CCLI
    ON (CAST(CCLI.ID AS CHAR) = CAST(V.CODCLI AS CHAR) OR CAST(CCLI.WINTHOR_CODCLI AS CHAR) = CAST(V.CODCLI AS CHAR))
  JOIN CARTEIRA_SCOPE CS ON CS.ID_CLIENTE = CCLI.ID
  JOIN BU_SCOPE B
    ON B.TARGET_USER_ID = CS.VENDEDOR_DONO_CLIENTE
   AND B.CODFILIAL = TRIM(COALESCE(CAST(V.CODFILIAL AS CHAR), ''))
   AND B.CODEPTO = TRIM(CAST(V.CODEPTO AS CHAR))
   AND (
     (B.ID_SECAO IS NOT NULL AND (TRIM(CAST(B.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR)) OR LPAD(TRIM(CAST(B.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR))))
     OR (B.ID_SECAO IS NULL AND NOT EXISTS (
       SELECT 1
       FROM BU_SCOPE B2
       WHERE B2.TARGET_USER_ID = B.TARGET_USER_ID
         AND B2.CODFILIAL = B.CODFILIAL
         AND B2.CODEPTO = B.CODEPTO
         AND B2.ID_SECAO IS NOT NULL
         AND (TRIM(CAST(B2.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR)) OR LPAD(TRIM(CAST(B2.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR)))
     ))
   )
),
PEDIDOS_BASE AS (
  SELECT
    CAST(VT.NUMPED AS SIGNED) AS PEDIDO_ID,
    MAX(SUBSTRING(VT.DTSAIDA, 1, 10)) AS DATA_PEDIDO,
    'FATURADO' AS STATUS_PEDIDO,
    ROUND(SUM(COALESCE(VT.TOTAL, 0)), 2) AS VALOR_TOTAL,
    0 AS MARGEM_MEDIA,
    COUNT(*) AS TOTAL_ITENS,
    0 AS MIX_ENVIADO
  FROM BASE_VENDAS VT
  WHERE VT.CLIENTE_ID_INTERNO = {{clienteId}}
  GROUP BY VT.NUMPED
),
MIX_BASE AS (
  SELECT
    -M.ID AS PEDIDO_ID,
    SUBSTRING(COALESCE(M.DT_ENVIO_HISTORICO, M.DT_CRIACAO), 1, 10) AS DATA_PEDIDO,
    'MIX' AS STATUS_PEDIDO,
    ROUND(COALESCE(M.TOTAL_VENDA, 0), 2) AS VALOR_TOTAL,
    ROUND(COALESCE(M.MARGEM_MEDIA, 0), 2) AS MARGEM_MEDIA,
    COUNT(MI.ID) AS TOTAL_ITENS,
    1 AS MIX_ENVIADO
  FROM PRODUCT_MIX M
  LEFT JOIN PRODUCT_MIX_ITEMS MI ON MI.ID_MIX = M.ID
  WHERE M.ID_CLIENTE = {{clienteId}}
    AND COALESCE(M.ENVIADO_HISTORICO, FALSE) = TRUE
    AND EXISTS (SELECT 1 FROM CARTEIRA_SCOPE CS WHERE CS.ID_CLIENTE = M.ID_CLIENTE)
  GROUP BY M.ID, M.DT_ENVIO_HISTORICO, M.DT_CRIACAO, M.TOTAL_VENDA, M.MARGEM_MEDIA
),
UNIFICADO AS (
  SELECT * FROM PEDIDOS_BASE
  UNION ALL
  SELECT * FROM MIX_BASE
),
PAGINADO AS (
  SELECT U.*, ROW_NUMBER() OVER (ORDER BY U.DATA_PEDIDO DESC, ABS(U.PEDIDO_ID) DESC) AS RN
  FROM UNIFICADO U
)
SELECT PEDIDO_ID, DATA_PEDIDO, STATUS_PEDIDO, VALOR_TOTAL, MARGEM_MEDIA, TOTAL_ITENS, MIX_ENVIADO
FROM PAGINADO
WHERE RN > {{offset}}
  AND RN <= ({{offset}} + {{limit}})
ORDER BY RN
