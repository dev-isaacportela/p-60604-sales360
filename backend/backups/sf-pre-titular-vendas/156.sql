    D.*,
    VR.USER_ID AS VENDEDOR_ATRIBUIDO
  FROM DEVOLUCOES_PERIODO D
  JOIN VENDEDOR_RCA VR
    ON TRIM(CAST(VR.COD_RCA AS CHAR)) = TRIM(CAST(D.COD_RCA AS CHAR))
  JOIN VENDEDORES_COORDENADOR VC ON VC.VENDEDOR_ID = VR.USER_ID
  WHERE NOT EXISTS (
    SELECT 1
    FROM DEVOLUCOES_ATRIBUIDAS DA
    WHERE DA.AUTO_ID = D.AUTO_ID
  )
    AND EXISTS (
      SELECT 1
      FROM BU_VENDEDOR BV
      JOIN ESCOPO_BU E
        ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(E.CODFILIAL AS CHAR)
       AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(E.CODEPTO AS CHAR)
      WHERE BV.VENDEDOR_ID = VR.USER_ID
        AND COALESCE(BV.ATIVO, TRUE) = TRUE
        AND 
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = D.CODFILIAL
    AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = TRIM(CAST(D.CODEPTO AS CHAR))
    AND (
      (
        BV.ID_SECAO IS NOT NULL
        AND (
          TRIM(CAST(BV.ID_SECAO AS CHAR)) = TRIM(CAST(D.CODSEC AS CHAR))
          OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(D.CODSEC AS CHAR))
        )
      )
      OR (
        BV.ID_SECAO IS NULL
        AND NOT EXISTS (
          SELECT 1
          FROM BU_VENDEDOR BV2
          WHERE BV2.VENDEDOR_ID = BV.VENDEDOR_ID
            AND COALESCE(BV2.ATIVO, TRUE) = TRUE
            AND TRIM(COALESCE(CAST(BV2.CODFILIAL AS CHAR), '')) = TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), ''))
            AND TRIM(CAST(BV2.BU_CODIGO AS CHAR)) = TRIM(CAST(BV.BU_CODIGO AS CHAR))
            AND BV2.ID_SECAO IS NOT NULL
            AND (
              TRIM(CAST(BV2.ID_SECAO AS CHAR)) = TRIM(CAST(D.CODSEC AS CHAR))
              OR LPAD(TRIM(CAST(BV2.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(D.CODSEC AS CHAR))
            )
        )
      )
    )
  
    )
),
DEVOLUCOES_SEM_CARTEIRA AS (
  SELECT
    D.*,
    NULL AS VENDEDOR_ATRIBUIDO
  FROM DEVOLUCOES_PERIODO D
  JOIN ESCOPO_BU E
    ON D.CODFILIAL = CAST(E.CODFILIAL AS CHAR)
   AND D.CODEPTO = E.CODEPTO
  LEFT JOIN CLIENTES_COM_CARTEIRA CCG ON CCG.ID_CLIENTE = D.ID_CLIENTE_INTERNO
  WHERE CCG.ID_CLIENTE IS NULL
    AND NOT EXISTS (SELECT 1 FROM DEVOLUCOES_ATRIBUIDAS_RCA DAR WHERE DAR.AUTO_ID = D.AUTO_ID)
),
DEVOLUCOES_BASE AS (
  SELECT * FROM DEVOLUCOES_ATRIBUIDAS
  UNION ALL
  SELECT * FROM DEVOLUCOES_ATRIBUIDAS_RCA
  UNION ALL
  SELECT * FROM DEVOLUCOES_SEM_CARTEIRA
)

      SELECT
        NOTA_DEVOLUCAO,
        NOTA_VENDA_ORIGINAL,
        NUMPED,
        DATA_VENDA,
        DATA_DEVOLUCAO,
        CASE
          WHEN DATA_VENDA IS NULL OR DATA_DEVOLUCAO IS NULL THEN 0
          ELSE DATEDIFF(STR_TO_DATE(DATA_DEVOLUCAO, '%Y-%m-%d'), STR_TO_DATE(DATA_VENDA, '%Y-%m-%d'))
        END AS DIAS_ATE_DEVOLUCAO,
        CODFILIAL,
        CODEPTO,
        COD_RCA,
        RCA,
        CODCLI,
        CLIENTE,
        VALOR_DEVOLVIDO,
        QT_DEVOLVIDA,
        TIPODESCARGA
      FROM DEVOLUCOES_BASE
      ORDER BY DATA_DEVOLUCAO DESC, AUTO_ID DESC
