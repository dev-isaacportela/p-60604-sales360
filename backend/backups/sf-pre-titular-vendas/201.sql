
    WITH
    
PERMISSAO AS (
  SELECT
    CASE
      WHEN COALESCE(UC.CARGO, '') IN ('DIRETORIA', 'ADMIN') THEN 1
      WHEN LOWER(COALESCE(U.DESCR, '')) = 'ti@benenutri.com' THEN 1
      ELSE 0
    END AS PODE_ACESSAR,
    COALESCE(UC.CARGO, 'NAO_DEFINIDO') AS CARGO_ATUAL,
    U.DESCR AS EMAIL
  FROM INT_USER U
  LEFT JOIN USUARIO_CARGO UC ON UC.USER_ID = U.ID
  WHERE U.ID = :VAR_USER
)
,
    
PARAMS AS (
  SELECT
    CASE WHEN '{{mes}}' REGEXP '^[0-9]{1,2}$' THEN CAST('{{mes}}' AS UNSIGNED) ELSE MONTH(CURRENT_DATE) END AS MES_REF,
    CASE WHEN '{{ano}}' REGEXP '^[0-9]{4}$' THEN CAST('{{ano}}' AS UNSIGNED) ELSE YEAR(CURRENT_DATE) END AS ANO_REF,
    CASE WHEN '{{codSupervisor}}' REGEXP '^[0-9]+$' THEN CAST('{{codSupervisor}}' AS UNSIGNED) ELSE NULL END AS COD_SUPERVISOR_PARAM,
    CASE WHEN '{{codfilial}}' REGEXP '^[0-9]+$' THEN CAST('{{codfilial}}' AS UNSIGNED) ELSE NULL END AS CODFILIAL_PARAM,
    CASE WHEN '{{codepto}}' REGEXP '^[0-9]+$' THEN CAST('{{codepto}}' AS UNSIGNED) ELSE NULL END AS CODEPTO_PARAM
),
PERIODO AS (
  SELECT
    P.MES_REF,
    P.ANO_REF,
    DATE_FORMAT(STR_TO_DATE(CONCAT(P.ANO_REF, '-', LPAD(P.MES_REF, 2, '0'), '-01'), '%Y-%m-%d'), '%Y-%m-%d') AS DATA_INICIO,
    DATE_FORMAT(DATE_ADD(STR_TO_DATE(CONCAT(P.ANO_REF, '-', LPAD(P.MES_REF, 2, '0'), '-01'), '%Y-%m-%d'), INTERVAL 1 MONTH), '%Y-%m-%d') AS DATA_FIM
  FROM PARAMS P
)
,
    
BU_RAW AS (
  SELECT
    CAST(TRIM(CAST(V.CODFILIAL AS CHAR)) AS UNSIGNED) AS CODFILIAL,
    V.CODEPTO,
    COALESCE(NULLIF(TRIM(CAST(V.DEPARTAMENTO AS CHAR)), ''), CONCAT('Departamento ', V.CODEPTO)) AS DEPARTAMENTO
  FROM IMP_VENDAS_DASHBOARD_TOTVS_RCA V
  WHERE TRIM(COALESCE(CAST(V.CODFILIAL AS CHAR), '')) REGEXP '^[0-9]+$'
    AND V.CODEPTO IS NOT NULL

  UNION ALL

  SELECT M.CODFILIAL, M.CODEPTO, CONCAT('Departamento ', M.CODEPTO) AS DEPARTAMENTO
  FROM METAS_BU M

  UNION ALL

  SELECT CB.CODFILIAL, CB.CODEPTO, CONCAT('Departamento ', CB.CODEPTO) AS DEPARTAMENTO
  FROM COORDENADORES_BU CB
),
BU_BASE AS (
  SELECT CODFILIAL, CODEPTO, MAX(DEPARTAMENTO) AS DEPARTAMENTO
  FROM BU_RAW
  GROUP BY CODFILIAL, CODEPTO
),
COORD_BU AS (
  SELECT CB.CODFILIAL, CB.CODEPTO, MIN(CB.COD_SUPERVISOR) AS COD_SUPERVISOR
  FROM COORDENADORES_BU CB
  JOIN COORDENADORES C ON C.COD_SUPERVISOR = CB.COD_SUPERVISOR AND COALESCE(C.ATIVO, TRUE) = TRUE
  GROUP BY CB.CODFILIAL, CB.CODEPTO
),
ESCOPO_BU AS (
  SELECT
    B.CODFILIAL,
    B.CODEPTO,
    B.DEPARTAMENTO,
    COALESCE(C.COD_SUPERVISOR, 0) AS COD_SUPERVISOR,
    COALESCE(NULLIF(TRIM(U.NOME), ''), NULLIF(TRIM(U.DESCR), ''), 'Sem coordenador') AS COORDENADOR,
    COALESCE(U.DESCR, C.EMAIL, '') AS EMAIL_COORDENADOR
  FROM BU_BASE B
  JOIN PERMISSAO PX ON PX.PODE_ACESSAR = 1
  JOIN PARAMS F ON 1 = 1
  LEFT JOIN COORD_BU CB ON CB.CODFILIAL = B.CODFILIAL AND CB.CODEPTO = B.CODEPTO
  LEFT JOIN COORDENADORES C ON C.COD_SUPERVISOR = CB.COD_SUPERVISOR
  LEFT JOIN INT_USER U ON U.ID = C.USER_ID
  WHERE (F.COD_SUPERVISOR_PARAM IS NULL OR COALESCE(C.COD_SUPERVISOR, 0) = F.COD_SUPERVISOR_PARAM)
    AND (F.CODFILIAL_PARAM IS NULL OR B.CODFILIAL = F.CODFILIAL_PARAM)
    AND (F.CODEPTO_PARAM IS NULL OR B.CODEPTO = F.CODEPTO_PARAM)
)
,
    
METAS AS (
  SELECT M.CODFILIAL, M.CODEPTO, ROUND(SUM(COALESCE(M.META_VALOR, 0)), 2) AS META_VALOR
  FROM METAS_BU M
  JOIN PERIODO P ON P.MES_REF = M.MES AND P.ANO_REF = M.ANO
  GROUP BY M.CODFILIAL, M.CODEPTO
),
ESCOPO_CARTEIRA AS (
  SELECT DISTINCT
    EC.ID_VENDEDOR,
    CAST(COALESCE(CL.WINTHOR_CODCLI, CL.ID, EC.ID_CLIENTE) AS UNSIGNED) AS CODCLI
  FROM EQUIPE_CLIENTE EC
  JOIN CLIENTES CL ON CL.ID = EC.ID_CLIENTE
  WHERE COALESCE(CL.WINTHOR_CODCLI, CL.ID, EC.ID_CLIENTE) IS NOT NULL
),
VENDAS AS (
  SELECT
    CAST(TRIM(CAST(V.CODFILIAL AS CHAR)) AS UNSIGNED) AS CODFILIAL,
    CAST(COALESCE(V.CODEPTO, 0) AS UNSIGNED) AS CODEPTO,
    ROUND(SUM(COALESCE(V.TOTAL, 0)), 2) AS FATURAMENTO_BRUTO,
    COUNT(DISTINCT V.NUMPED) AS QTD_PEDIDOS,
    COUNT(DISTINCT V.CODCLI) AS CLIENTES_COM_COMPRA
  FROM IMP_VENDAS_DASHBOARD_TOTVS_RCA V
  JOIN PERIODO P ON 1 = 1
  JOIN ESCOPO_CARTEIRA EC
    ON EC.CODCLI = CAST(COALESCE(V.CODCLI, 0) AS UNSIGNED)
  JOIN BU_VENDEDOR BV_SCOPE
    ON BV_SCOPE.VENDEDOR_ID = EC.ID_VENDEDOR
   AND COALESCE(BV_SCOPE.ATIVO, TRUE) = TRUE
   AND TRIM(CAST(BV_SCOPE.CODFILIAL AS CHAR)) = TRIM(CAST(V.CODFILIAL AS CHAR))
   AND TRIM(CAST(BV_SCOPE.BU_CODIGO AS CHAR)) = TRIM(CAST(V.CODEPTO AS CHAR))
   AND (
     BV_SCOPE.ID_SECAO IS NULL
     OR TRIM(CAST(BV_SCOPE.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR))
     OR LPAD(TRIM(CAST(BV_SCOPE.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR))
   )
  WHERE TRIM(COALESCE(CAST(V.CODFILIAL AS CHAR), '')) REGEXP '^[0-9]+$'
    AND SUBSTRING(CAST(V.DTSAIDA AS CHAR), 1, 10) >= P.DATA_INICIO
    AND SUBSTRING(CAST(V.DTSAIDA AS CHAR), 1, 10) < P.DATA_FIM
  GROUP BY CAST(TRIM(CAST(V.CODFILIAL AS CHAR)) AS UNSIGNED), CAST(COALESCE(V.CODEPTO, 0) AS UNSIGNED)
),
DEVOLUCOES AS (
  SELECT
    CAST(TRIM(CAST(D.CODFILIAL AS CHAR)) AS UNSIGNED) AS CODFILIAL,
    D.CODEPTO,
    ROUND(SUM(COALESCE(D.VALOR_DEVOLVIDO, 0)), 2) AS DEVOLVIDO,
    COUNT(DISTINCT D.NOTA_DEVOLUCAO) AS QTD_DEVOLUCOES
  FROM IMP_DEVOLUCOES_TOTVS D
  JOIN PERIODO P ON 1 = 1
  WHERE TRIM(COALESCE(CAST(D.CODFILIAL AS CHAR), '')) REGEXP '^[0-9]+$'
    AND SUBSTRING(CAST(D.DATA_DEVOLUCAO AS CHAR), 1, 10) >= P.DATA_INICIO
    AND SUBSTRING(CAST(D.DATA_DEVOLUCAO AS CHAR), 1, 10) < P.DATA_FIM
  GROUP BY CAST(TRIM(CAST(D.CODFILIAL AS CHAR)) AS UNSIGNED), D.CODEPTO
),
BU_METRICS AS (
  SELECT
    E.CODFILIAL,
    E.CODEPTO,
    E.DEPARTAMENTO,
    E.COD_SUPERVISOR,
    E.COORDENADOR,
    E.EMAIL_COORDENADOR,
    COALESCE(M.META_VALOR, 0) AS META_VALOR,
    COALESCE(V.FATURAMENTO_BRUTO, 0) AS FATURAMENTO_BRUTO,
    COALESCE(D.DEVOLVIDO, 0) AS DEVOLVIDO,
    ROUND(COALESCE(V.FATURAMENTO_BRUTO, 0) - COALESCE(D.DEVOLVIDO, 0), 2) AS REALIZADO_LIQUIDO,
    COALESCE(V.QTD_PEDIDOS, 0) AS QTD_PEDIDOS,
    COALESCE(V.CLIENTES_COM_COMPRA, 0) AS CLIENTES_COM_COMPRA,
    COALESCE(D.QTD_DEVOLUCOES, 0) AS QTD_DEVOLUCOES,
    CASE WHEN COALESCE(M.META_VALOR, 0) <= 0 THEN 0 ELSE ROUND(((COALESCE(V.FATURAMENTO_BRUTO, 0) - COALESCE(D.DEVOLVIDO, 0)) / M.META_VALOR) * 100, 2) END AS PERCENTUAL_META,
    CASE WHEN COALESCE(V.FATURAMENTO_BRUTO, 0) <= 0 THEN 0 ELSE ROUND((COALESCE(D.DEVOLVIDO, 0) / V.FATURAMENTO_BRUTO) * 100, 2) END AS PERCENTUAL_DEVOLUCAO
  FROM ESCOPO_BU E
  LEFT JOIN METAS M ON M.CODFILIAL = E.CODFILIAL AND M.CODEPTO = E.CODEPTO
  LEFT JOIN VENDAS V ON V.CODFILIAL = E.CODFILIAL AND V.CODEPTO = E.CODEPTO
  LEFT JOIN DEVOLUCOES D ON D.CODFILIAL = E.CODFILIAL AND D.CODEPTO = E.CODEPTO
)

    
    
      SELECT
        BM.COD_SUPERVISOR,
        BM.COORDENADOR,
        ROUND(SUM(BM.META_VALOR), 2) AS META_VALOR,
        ROUND(SUM(BM.FATURAMENTO_BRUTO), 2) AS FATURAMENTO_BRUTO,
        ROUND(SUM(BM.DEVOLVIDO), 2) AS DEVOLVIDO,
        ROUND(SUM(BM.REALIZADO_LIQUIDO), 2) AS REALIZADO_LIQUIDO,
        ROUND(SUM(BM.META_VALOR) - SUM(BM.REALIZADO_LIQUIDO), 2) AS GAP_META,
        CASE WHEN SUM(BM.META_VALOR) <= 0 THEN 0 ELSE ROUND((SUM(BM.REALIZADO_LIQUIDO) / SUM(BM.META_VALOR)) * 100, 2) END AS PERCENTUAL_META,
        CASE WHEN SUM(BM.FATURAMENTO_BRUTO) <= 0 THEN 0 ELSE ROUND((SUM(BM.DEVOLVIDO) / SUM(BM.FATURAMENTO_BRUTO)) * 100, 2) END AS PERCENTUAL_DEVOLUCAO,
        SUM(BM.QTD_PEDIDOS) AS QTD_PEDIDOS,
        SUM(BM.CLIENTES_COM_COMPRA) AS CLIENTES_COM_COMPRA,
        COUNT(*) AS TOTAL_BUS,
        SUM(CASE WHEN BM.META_VALOR > 0 AND BM.PERCENTUAL_META < 80 THEN 1 ELSE 0 END) AS BUS_CRITICAS
      FROM BU_METRICS BM
      GROUP BY BM.COD_SUPERVISOR, BM.COORDENADOR
      ORDER BY REALIZADO_LIQUIDO DESC
      LIMIT 80
    
  