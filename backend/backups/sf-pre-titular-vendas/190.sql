
      WITH
      
PARAMS AS (
  SELECT
    CASE WHEN '{{mes}}' REGEXP '^[0-9]{1,2}$' THEN CAST('{{mes}}' AS UNSIGNED) ELSE MONTH(CURRENT_DATE) END AS MES_REF,
    CASE WHEN '{{ano}}' REGEXP '^[0-9]{4}$' THEN CAST('{{ano}}' AS UNSIGNED) ELSE YEAR(CURRENT_DATE) END AS ANO_REF
),
PERIODO AS (
  SELECT
    P.MES_REF,
    P.ANO_REF,
    DATE_FORMAT(STR_TO_DATE(CONCAT(P.ANO_REF, '-', LPAD(P.MES_REF, 2, '0'), '-01'), '%Y-%m-%d'), '%Y-%m-%d') AS DATA_INICIO,
    DATE_FORMAT(DATE_ADD(STR_TO_DATE(CONCAT(P.ANO_REF, '-', LPAD(P.MES_REF, 2, '0'), '-01'), '%Y-%m-%d'), INTERVAL 1 MONTH), '%Y-%m-%d') AS DATA_FIM
  FROM PARAMS P
),
COORD AS (
  SELECT
    C.COD_SUPERVISOR,
    C.NOME,
    C.EMAIL,
    C.USER_ID
  FROM COORDENADORES C
  WHERE C.USER_ID = :VAR_USER
    AND COALESCE(C.ATIVO, TRUE) = TRUE
  LIMIT 1
),
ESCOPO_BU AS (
  SELECT DISTINCT
    CB.COD_SUPERVISOR,
    CB.CODFILIAL,
    CB.CODEPTO
  FROM COORDENADORES_BU CB
  JOIN COORD C ON C.COD_SUPERVISOR = CB.COD_SUPERVISOR
),
VENDEDORES_COORDENADOR AS (
  SELECT DISTINCT BV.VENDEDOR_ID
  FROM BU_VENDEDOR BV
  JOIN ESCOPO_BU E
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(E.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(E.CODEPTO AS CHAR)
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND NOT EXISTS (
      SELECT 1
      FROM COORDENADORES C_COORD_ALVO
      WHERE C_COORD_ALVO.USER_ID = BV.VENDEDOR_ID
        AND COALESCE(C_COORD_ALVO.ATIVO, TRUE) = TRUE
        AND C_COORD_ALVO.USER_ID <> :VAR_USER
    )
),
CLIENTE_MAP AS (
  SELECT
    MIN(C.ID) AS ID,
    TRIM(CAST(COALESCE(C.WINTHOR_CODCLI, C.ID) AS CHAR)) AS CODCLI
  FROM CLIENTES C
  WHERE COALESCE(C.WINTHOR_CODCLI, C.ID) IS NOT NULL
  GROUP BY TRIM(CAST(COALESCE(C.WINTHOR_CODCLI, C.ID) AS CHAR))
),
CLIENTES_CARTEIRA_COORDENADOR AS (
  SELECT DISTINCT
    EC.ID_CLIENTE,
    EC.ID_VENDEDOR
  FROM EQUIPE_CLIENTE EC
  JOIN VENDEDORES_COORDENADOR VC ON VC.VENDEDOR_ID = EC.ID_VENDEDOR
  JOIN BU_VENDEDOR BV_SCOPE
    ON BV_SCOPE.VENDEDOR_ID = EC.ID_VENDEDOR
   AND COALESCE(BV_SCOPE.ATIVO, TRUE) = TRUE
  JOIN ESCOPO_BU E_SCOPE
    ON TRIM(COALESCE(CAST(BV_SCOPE.CODFILIAL AS CHAR), '')) = CAST(E_SCOPE.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV_SCOPE.BU_CODIGO AS CHAR)) = CAST(E_SCOPE.CODEPTO AS CHAR)
  WHERE (
      EC.CODFILIAL IS NULL
      OR TRIM(COALESCE(CAST(EC.CODFILIAL AS CHAR), '')) = ''
      OR TRIM(COALESCE(CAST(EC.CODFILIAL AS CHAR), '')) = TRIM(COALESCE(CAST(BV_SCOPE.CODFILIAL AS CHAR), ''))
    )
    AND (
      EC.ID_SECAO IS NULL
      OR TRIM(COALESCE(CAST(EC.ID_SECAO AS CHAR), '')) = ''
      OR TRIM(CAST(EC.ID_SECAO AS CHAR)) = TRIM(CAST(BV_SCOPE.ID_SECAO AS CHAR))
      OR LPAD(TRIM(CAST(EC.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(BV_SCOPE.ID_SECAO AS CHAR))
    )
),
CLIENTES_COM_CARTEIRA AS (
  SELECT DISTINCT EC.ID_CLIENTE
  FROM EQUIPE_CLIENTE EC
),
VENDAS_PERIODO AS (
  SELECT
    V.AUTO_ID,
    V.NUMPED,
    SUBSTRING(CAST(V.DTSAIDA AS CHAR), 1, 10) AS DATA_VENDA,
    TRIM(CAST(V.CODFILIAL AS CHAR)) AS CODFILIAL,
    V.CODEPTO,
    V.CODSEC,
    V.COD_RCA,
    COALESCE(NULLIF(TRIM(CAST(V.RCA AS CHAR)), ''), CONCAT('RCA ', V.COD_RCA)) AS RCA,
    V.CODCLI,
    COALESCE(NULLIF(TRIM(CAST(V.CLIENTE AS CHAR)), ''), CONCAT('Cliente ', V.CODCLI)) AS CLIENTE,
    COALESCE(V.TOTAL, 0) AS TOTAL,
    CCLI.ID AS ID_CLIENTE_INTERNO
  FROM IMP_VENDAS_DASHBOARD_TOTVS_RCA V
  JOIN PERIODO P ON 1 = 1
  LEFT JOIN CLIENTE_MAP CCLI ON CCLI.CODCLI = TRIM(CAST(V.CODCLI AS CHAR))
  WHERE SUBSTRING(CAST(V.DTSAIDA AS CHAR), 1, 10) >= P.DATA_INICIO
    AND SUBSTRING(CAST(V.DTSAIDA AS CHAR), 1, 10) < P.DATA_FIM
),
VENDAS_ATRIBUIDAS AS (
  SELECT
    V.*,
    CCC.ID_VENDEDOR AS VENDEDOR_ATRIBUIDO
  FROM VENDAS_PERIODO V
  JOIN CLIENTES_CARTEIRA_COORDENADOR CCC ON CCC.ID_CLIENTE = V.ID_CLIENTE_INTERNO
  WHERE EXISTS (
    SELECT 1
    FROM BU_VENDEDOR BV
    JOIN ESCOPO_BU E
      ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(E.CODFILIAL AS CHAR)
     AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(E.CODEPTO AS CHAR)
    WHERE BV.VENDEDOR_ID = CCC.ID_VENDEDOR
      AND COALESCE(BV.ATIVO, TRUE) = TRUE
      AND 
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = V.CODFILIAL
    AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = TRIM(CAST(V.CODEPTO AS CHAR))
    AND (
      (
        BV.ID_SECAO IS NOT NULL
        AND (
          TRIM(CAST(BV.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR))
          OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR))
        )
      )
      OR (
        BV.ID_SECAO IS NULL
        AND NOT EXISTS (
          SELECT 1
          FROM BU_VENDEDOR BV2
          WHERE BV2.VENDEDOR_ID = BV.VENDEDOR_ID
            AND TRIM(COALESCE(CAST(BV2.CODFILIAL AS CHAR), '')) = TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), ''))
            AND TRIM(CAST(BV2.BU_CODIGO AS CHAR)) = TRIM(CAST(BV.BU_CODIGO AS CHAR))
            AND BV2.ID_SECAO IS NOT NULL
            AND (
              TRIM(CAST(BV2.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR))
              OR LPAD(TRIM(CAST(BV2.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR))
            )
        )
      )
    )
  
  )
),
VENDAS_ATRIBUIDAS_RCA AS (
  SELECT
    V.*,
    VR.USER_ID AS VENDEDOR_ATRIBUIDO
  FROM VENDAS_PERIODO V
  JOIN VENDEDOR_RCA VR
    ON TRIM(CAST(VR.COD_RCA AS CHAR)) = TRIM(CAST(V.COD_RCA AS CHAR))
  JOIN VENDEDORES_COORDENADOR VC ON VC.VENDEDOR_ID = VR.USER_ID
  WHERE NOT EXISTS (
    SELECT 1
    FROM VENDAS_ATRIBUIDAS VA
    WHERE VA.AUTO_ID = V.AUTO_ID
  )
    AND EXISTS (
      SELECT 1
      FROM BU_VENDEDOR BV
      JOIN ESCOPO_BU E
        ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(E.CODFILIAL AS CHAR)
       AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(E.CODEPTO AS CHAR)
      WHERE BV.VENDEDOR_ID = VR.USER_ID
        AND COALESCE(BV.ATIVO, TRUE) = TRUE
        AND 
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = V.CODFILIAL
    AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = TRIM(CAST(V.CODEPTO AS CHAR))
    AND (
      (
        BV.ID_SECAO IS NOT NULL
        AND (
          TRIM(CAST(BV.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR))
          OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR))
        )
      )
      OR (
        BV.ID_SECAO IS NULL
        AND NOT EXISTS (
          SELECT 1
          FROM BU_VENDEDOR BV2
          WHERE BV2.VENDEDOR_ID = BV.VENDEDOR_ID
            AND COALESCE(BV2.ATIVO, TRUE) = TRUE
            AND TRIM(COALESCE(CAST(BV2.CODFILIAL AS CHAR), '')) = TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), ''))
            AND TRIM(CAST(BV2.BU_CODIGO AS CHAR)) = TRIM(CAST(BV.BU_CODIGO AS CHAR))
            AND BV2.ID_SECAO IS NOT NULL
            AND (
              TRIM(CAST(BV2.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR))
              OR LPAD(TRIM(CAST(BV2.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR))
            )
        )
      )
    )
  
    )
),
VENDAS_SEM_CARTEIRA AS (
  SELECT
    V.*,
    NULL AS VENDEDOR_ATRIBUIDO
  FROM VENDAS_PERIODO V
  JOIN ESCOPO_BU E
    ON V.CODFILIAL = CAST(E.CODFILIAL AS CHAR)
   AND V.CODEPTO = E.CODEPTO
  LEFT JOIN CLIENTES_COM_CARTEIRA CCG ON CCG.ID_CLIENTE = V.ID_CLIENTE_INTERNO
  WHERE CCG.ID_CLIENTE IS NULL
    AND NOT EXISTS (SELECT 1 FROM VENDAS_ATRIBUIDAS_RCA VAR WHERE VAR.AUTO_ID = V.AUTO_ID)
),
VENDAS_BASE AS (
  SELECT * FROM VENDAS_ATRIBUIDAS
  UNION ALL
  SELECT * FROM VENDAS_ATRIBUIDAS_RCA
  UNION ALL
  SELECT * FROM VENDAS_SEM_CARTEIRA
),
