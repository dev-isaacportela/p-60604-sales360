
WITH 
INPUT_SCOPE AS (
  SELECT
    CASE WHEN '{{scopeMode}}' IN ('TEAM', 'SELLER', 'GLOBAL') THEN '{{scopeMode}}' ELSE 'ME' END AS SCOPE_MODE,
    CASE WHEN '{{scopeUserId}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeUserId}}' AS UNSIGNED) ELSE NULL END AS SCOPE_USER_ID,
    CASE WHEN '{{scopeCodRca}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeCodRca}}' AS UNSIGNED) ELSE NULL END AS SCOPE_COD_RCA,
    CASE WHEN '{{scopeCodFilial}}' = '' OR LOCATE('{', '{{scopeCodFilial}}') > 0 THEN NULL ELSE TRIM('{{scopeCodFilial}}') END AS SCOPE_CODFILIAL,
    CASE WHEN '{{scopeCodepto}}' = '' OR LOCATE('{', '{{scopeCodepto}}') > 0 THEN NULL ELSE TRIM('{{scopeCodepto}}') END AS SCOPE_CODEPTO,
    CASE WHEN '{{scopeIdSecao}}' = '' OR LOCATE('{', '{{scopeIdSecao}}') > 0 THEN NULL ELSE TRIM('{{scopeIdSecao}}') END AS SCOPE_ID_SECAO,
    CASE WHEN '{{scopeCodSupervisor}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeCodSupervisor}}' AS UNSIGNED) ELSE NULL END AS SCOPE_COD_SUPERVISOR
),
TARGET_USERS AS (
  SELECT :VAR_USER AS USER_ID
  FROM INPUT_SCOPE I
  WHERE I.SCOPE_MODE = 'ME'

  UNION

  SELECT F.ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN FUNCIONARIOS F ON F.ID_SUBSTITUTO = :VAR_USER
  WHERE I.SCOPE_MODE = 'ME'

  UNION

  SELECT VR_DONO.USER_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN VENDEDOR_RCA VR_SUB ON VR_SUB.USER_ID = :VAR_USER
  JOIN FERIAS_VENDEDOR FV ON FV.COD_RCA_SUBSTITUTO = VR_SUB.COD_RCA
  JOIN VENDEDOR_RCA VR_DONO ON VR_DONO.COD_RCA = FV.COD_RCA
  WHERE I.SCOPE_MODE = 'ME'
    AND COALESCE(FV.ATIVO, TRUE) = TRUE
    AND CURRENT_DATE BETWEEN FV.DT_INICIO AND FV.DT_FIM

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  WHERE I.SCOPE_MODE = 'TEAM'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND NOT EXISTS (
      SELECT 1
      FROM COORDENADORES C_COORD_ALVO
      WHERE C_COORD_ALVO.USER_ID = BV.VENDEDOR_ID
        AND COALESCE(C_COORD_ALVO.ATIVO, TRUE) = TRUE
        AND C_COORD_ALVO.USER_ID <> :VAR_USER
    )
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  LEFT JOIN VENDEDOR_RCA VR ON VR.USER_ID = BV.VENDEDOR_ID
  WHERE I.SCOPE_MODE = 'SELLER'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (BV.VENDEDOR_ID = I.SCOPE_USER_ID OR VR.COD_RCA = I.SCOPE_COD_RCA)
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )


  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN INT_USER U ON U.ID = :VAR_USER
  LEFT JOIN USUARIO_CARGO UC ON UC.USER_ID = U.ID
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE I.SCOPE_MODE = 'GLOBAL'
    AND (
      UPPER(COALESCE(UC.CARGO, '')) IN ('ADMIN', 'DIRETORIA')
      OR LOWER(COALESCE(U.DESCR, '')) = 'ti@benenutri.com'
    )
    AND (
      I.SCOPE_COD_SUPERVISOR IS NULL
      OR EXISTS (
        SELECT 1
        FROM COORDENADORES C_GLOBAL_SELF
        WHERE C_GLOBAL_SELF.USER_ID = BV.VENDEDOR_ID
          AND COALESCE(C_GLOBAL_SELF.ATIVO, TRUE) = TRUE
          AND C_GLOBAL_SELF.COD_SUPERVISOR = I.SCOPE_COD_SUPERVISOR
      )
      OR (
        NOT EXISTS (
          SELECT 1
          FROM COORDENADORES C_GLOBAL_OTHER_COORD
          WHERE C_GLOBAL_OTHER_COORD.USER_ID = BV.VENDEDOR_ID
            AND COALESCE(C_GLOBAL_OTHER_COORD.ATIVO, TRUE) = TRUE
        )
        AND EXISTS (
          SELECT 1
          FROM COORDENADORES_BU CB_GLOBAL
          WHERE CB_GLOBAL.COD_SUPERVISOR = I.SCOPE_COD_SUPERVISOR
            AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB_GLOBAL.CODFILIAL AS CHAR)
            AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB_GLOBAL.CODEPTO AS CHAR)
        )
      )
    )
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
),
BU_SCOPE AS (
  SELECT DISTINCT
    TU.USER_ID AS USER_ID,
    BV.VENDEDOR_ID,
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL,
    TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS ID_BU,
    BV.ID_SECAO
  FROM TARGET_USERS TU
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = TU.USER_ID
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) <> ''
    AND TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) <> ''
),
CARTEIRA_SCOPE AS (
  SELECT DISTINCT
    TU.USER_ID,
    C.ID AS CLIENTE_ID,
    COALESCE(C.WINTHOR_CODCLI, C.ID) AS CODCLI
  FROM EQUIPE_CLIENTE EC
  JOIN TARGET_USERS TU ON TU.USER_ID = EC.ID_VENDEDOR
  JOIN CLIENTES C ON C.ID = EC.ID_CLIENTE
  WHERE C.ID IS NOT NULL
),
INPUTS AS (
  SELECT
    CASE
      WHEN '{{dataInicio}}' REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN '{{dataInicio}}'
      ELSE DATE_FORMAT(CURRENT_DATE, '%Y-%m-01')
    END AS DATA_INICIO,
    CASE
      WHEN '{{dataFim}}' REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN '{{dataFim}}'
      ELSE DATE_FORMAT(LAST_DAY(CURRENT_DATE), '%Y-%m-%d')
    END AS DATA_FIM,
    CASE
      WHEN '{{departamentos}}' = '' OR LOCATE('{', '{{departamentos}}') > 0 THEN NULL
      ELSE TRIM('{{departamentos}}')
    END AS DEPARTAMENTOS_PARAM,
    CASE
      WHEN '{{ramos}}' = '' OR LOCATE('{', '{{ramos}}') > 0 THEN NULL
      ELSE TRIM('{{ramos}}')
    END AS RAMOS_PARAM,
    CASE
      WHEN '{{cliente}}' = '' OR LOCATE('{', '{{cliente}}') > 0 THEN NULL
      ELSE REPLACE(TRIM('{{cliente}}'), '|', ',')
    END AS CLIENTE_PARAM,
    CASE WHEN '{{limit}}' REGEXP '^[0-9]+$' THEN CAST('{{limit}}' AS UNSIGNED) ELSE 100 END AS LIMIT_PARAM,
    CASE WHEN '{{offset}}' REGEXP '^[0-9]+$' THEN CAST('{{offset}}' AS UNSIGNED) ELSE 0 END AS OFFSET_PARAM
),
PERIODO_BASE AS (
  SELECT
    I.*,
    STR_TO_DATE(I.DATA_INICIO, '%Y-%m-%d') AS DT_INICIO,
    STR_TO_DATE(I.DATA_FIM, '%Y-%m-%d') AS DT_FIM
  FROM INPUTS I
),
PERIODO AS (
  SELECT
    PB.*,
    GREATEST(DATEDIFF(PB.DT_FIM, PB.DT_INICIO) + 1, 1) AS DIAS_PERIODO,
    DATE_SUB(PB.DT_INICIO, INTERVAL GREATEST(DATEDIFF(PB.DT_FIM, PB.DT_INICIO) + 1, 1) DAY) AS DT_INICIO_ANTERIOR,
    DATE_SUB(PB.DT_INICIO, INTERVAL 1 DAY) AS DT_FIM_ANTERIOR
  FROM PERIODO_BASE PB
)
,
VENDAS_CLIENTE AS (
  SELECT
    V.CODCLI,
    COALESCE(NULLIF(TRIM(CAST(MAX(V.CLIENTE) AS CHAR)), ''), CONCAT('Cliente ', V.CODCLI)) AS CLIENTE,
    COALESCE(NULLIF(TRIM(CAST(MAX(V.RAMO_CLIENTE) AS CHAR)), ''), 'Sem ramo') AS RAMO,
    ROUND(SUM(COALESCE(V.TOTAL, 0)), 2) AS FATURAMENTO_BRUTO,
    COUNT(DISTINCT V.NUMPED) AS QTD_PEDIDOS
  FROM IMP_VENDAS_DASHBOARD_TOTVS_RCA V
  
    JOIN BU_SCOPE BS
      ON BS.CODFILIAL = TRIM(COALESCE(CAST(V.CODFILIAL AS CHAR), ''))
     AND BS.ID_BU = TRIM(CAST(V.CODEPTO AS CHAR))
     AND (
       BS.ID_SECAO IS NULL
       OR TRIM(CAST(BS.ID_SECAO AS CHAR)) = TRIM(CAST(V.CODSEC AS CHAR))
       OR LPAD(TRIM(CAST(BS.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(V.CODSEC AS CHAR))
     )
  
  
    JOIN CARTEIRA_SCOPE CS
      ON TRIM(CAST(CS.CODCLI AS CHAR)) = TRIM(CAST(V.CODCLI AS CHAR))
     AND CS.USER_ID = BS.USER_ID
  
  JOIN PERIODO P ON 1 = 1
  WHERE V.CODCLI IS NOT NULL
  
    AND V.DTSAIDA >= DATE_FORMAT(P.DT_INICIO, '%Y-%m-%d')
    AND V.DTSAIDA <= DATE_FORMAT(P.DT_FIM, '%Y-%m-%d')
    AND (
      P.DEPARTAMENTOS_PARAM IS NULL
      OR INSTR(CONCAT('|', P.DEPARTAMENTOS_PARAM, '|'), CONCAT('|', TRIM(CAST(V.CODEPTO AS CHAR)), '|')) > 0
    )
    AND (
      P.RAMOS_PARAM IS NULL
      OR INSTR(
        CONCAT('|', P.RAMOS_PARAM, '|'),
        CONCAT('|', REPLACE(COALESCE(NULLIF(TRIM(CAST(V.RAMO_CLIENTE AS CHAR)), ''), 'Sem ramo'), '''', ''), '|')
      ) > 0
    )
    AND (
      P.CLIENTE_PARAM IS NULL
      OR FIND_IN_SET(TRIM(CAST(V.CODCLI AS CHAR)), P.CLIENTE_PARAM) > 0
    )
  
  GROUP BY V.CODCLI
),
DEVOLUCOES_CLIENTE AS (
  SELECT D.CODCLI, ROUND(SUM(COALESCE(D.VALOR_DEVOLVIDO, 0)), 2) AS DEVOLVIDO
  FROM IMP_DEVOLUCOES_TOTVS D
  
    JOIN BU_SCOPE BS
      ON BS.CODFILIAL = TRIM(COALESCE(CAST(D.CODFILIAL AS CHAR), ''))
     AND BS.ID_BU = TRIM(CAST(D.CODEPTO AS CHAR))
     AND (
       BS.ID_SECAO IS NULL
       OR TRIM(CAST(BS.ID_SECAO AS CHAR)) = TRIM(CAST(D.CODSEC AS CHAR))
       OR LPAD(TRIM(CAST(BS.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(D.CODSEC AS CHAR))
     )
  
  
    JOIN CARTEIRA_SCOPE CS
      ON TRIM(CAST(CS.CODCLI AS CHAR)) = TRIM(CAST(D.CODCLI AS CHAR))
     AND CS.USER_ID = BS.USER_ID
  
  JOIN PERIODO P ON 1 = 1
  WHERE D.CODCLI IS NOT NULL
  
    AND D.DATA_DEVOLUCAO >= DATE_FORMAT(P.DT_INICIO, '%Y-%m-%d')
    AND D.DATA_DEVOLUCAO <= DATE_FORMAT(P.DT_FIM, '%Y-%m-%d')
    AND (
      P.DEPARTAMENTOS_PARAM IS NULL
      OR INSTR(CONCAT('|', P.DEPARTAMENTOS_PARAM, '|'), CONCAT('|', TRIM(CAST(D.CODEPTO AS CHAR)), '|')) > 0
    )
    AND (
      P.RAMOS_PARAM IS NULL
      OR INSTR(
        CONCAT('|', P.RAMOS_PARAM, '|'),
        CONCAT('|', REPLACE(COALESCE(NULLIF(TRIM(CAST(D.RAMO_CLIENTE AS CHAR)), ''), 'Sem ramo'), '''', ''), '|')
      ) > 0
    )
    AND (
      P.CLIENTE_PARAM IS NULL
      OR FIND_IN_SET(TRIM(CAST(D.CODCLI AS CHAR)), P.CLIENTE_PARAM) > 0
    )
  
  GROUP BY D.CODCLI
),
BASE AS (
  SELECT
    V.CODCLI,
    V.CLIENTE,
    V.RAMO,
    V.FATURAMENTO_BRUTO,
    COALESCE(D.DEVOLVIDO, 0) AS DEVOLVIDO,
    ROUND(GREATEST(V.FATURAMENTO_BRUTO - COALESCE(D.DEVOLVIDO, 0), 0), 2) AS FATURAMENTO_LIQUIDO,
    V.QTD_PEDIDOS,
    ROUND(CASE WHEN V.QTD_PEDIDOS = 0 THEN 0 ELSE GREATEST(V.FATURAMENTO_BRUTO - COALESCE(D.DEVOLVIDO, 0), 0) / V.QTD_PEDIDOS END, 2) AS TICKET_MEDIO
  FROM VENDAS_CLIENTE V
  LEFT JOIN DEVOLUCOES_CLIENTE D ON D.CODCLI = V.CODCLI
),
TOTAL AS (
  SELECT SUM(FATURAMENTO_LIQUIDO) AS TOTAL_LIQUIDO FROM BASE
)
SELECT
  B.CODCLI,
  B.CLIENTE,
  B.RAMO,
  B.FATURAMENTO_BRUTO,
  B.DEVOLVIDO,
  B.FATURAMENTO_LIQUIDO,
  B.QTD_PEDIDOS,
  B.TICKET_MEDIO,
  ROUND(CASE WHEN COALESCE(T.TOTAL_LIQUIDO, 0) <= 0 THEN 0 ELSE (B.FATURAMENTO_LIQUIDO / T.TOTAL_LIQUIDO) * 100 END, 2) AS PERC_TOTAL
FROM BASE B
JOIN TOTAL T ON 1 = 1
ORDER BY B.FATURAMENTO_LIQUIDO DESC
LIMIT 10
