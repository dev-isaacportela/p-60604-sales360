WITH RECURSIVE
INPUT_SCOPE AS (
  SELECT
    CASE WHEN '{{scopeMode}}' IN ('TEAM','SELLER','GLOBAL') THEN '{{scopeMode}}' ELSE 'ME' END AS SCOPE_MODE,
    CASE WHEN '{{scopeUserId}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeUserId}}' AS UNSIGNED) ELSE NULL END AS SCOPE_USER_ID,
    CASE WHEN '{{scopeCodRca}}'  REGEXP '^[0-9]+$' THEN CAST('{{scopeCodRca}}'  AS UNSIGNED) ELSE NULL END AS SCOPE_COD_RCA,
    CASE WHEN '{{scopeCodSupervisor}}' = '' OR LOCATE('{', '{{scopeCodSupervisor}}') > 0
         THEN NULL ELSE TRIM('{{scopeCodSupervisor}}') END AS SCOPE_COD_SUPERVISOR,
    CASE WHEN '{{scopeCodFilial}}' = '' OR LOCATE('{', '{{scopeCodFilial}}') > 0
         THEN NULL ELSE TRIM('{{scopeCodFilial}}') END AS SCOPE_CODFILIAL,
    CASE WHEN '{{scopeCodepto}}'   = '' OR LOCATE('{', '{{scopeCodepto}}')   > 0
         THEN NULL ELSE TRIM('{{scopeCodepto}}')   END AS SCOPE_CODEPTO,
    CASE WHEN '{{scopeIdSecao}}'   = '' OR LOCATE('{', '{{scopeIdSecao}}')   > 0
         THEN NULL ELSE TRIM('{{scopeIdSecao}}')   END AS SCOPE_ID_SECAO
),

JANELA AS (
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 20 DAY) AS DT_INI, CURRENT_DATE AS DT_FIM
),

PERMISSAO AS (
  SELECT (
    EXISTS (
      SELECT 1 FROM USUARIO_CARGO UC
      WHERE UC.USER_ID = :VAR_USER            -- CONFIRMAR: nome da coluna de usuario nesta tabela
        AND UPPER(UC.CARGO) IN ('ADMIN','DIRETORIA')
    )
    OR EXISTS (
      SELECT 1 FROM INT_USER IU
      WHERE IU.ID = :VAR_USER AND LOWER(IU.DESCR) = 'ti@benenutri.com'
    )
  ) AS EH_DIRETORIA
),

ESCOPO AS (
  SELECT I.*, P.EH_DIRETORIA,
         (P.EH_DIRETORIA AND I.SCOPE_COD_SUPERVISOR IS NULL) AS ESCOPO_ABERTO
  FROM INPUT_SCOPE I JOIN PERMISSAO P ON 1 = 1
),

-- Filial+depto que o solicitante pode enxergar. Coordenador enxerga as suas;
-- diretoria enxerga as do supervisor escolhido, ou todas quando nao escolhe.
BU_AUTORIZADA AS (
  SELECT DISTINCT
    TRIM(COALESCE(CAST(CB.CODFILIAL AS CHAR), '')) AS CODFILIAL,
    TRIM(COALESCE(CAST(CB.CODEPTO   AS CHAR), '')) AS CODEPTO
  FROM ESCOPO E
  JOIN COORDENADORES C     ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  WHERE E.SCOPE_COD_SUPERVISOR IS NULL
     OR TRIM(COALESCE(CAST(C.COD_SUPERVISOR AS CHAR), '')) = E.SCOPE_COD_SUPERVISOR

  UNION

  SELECT DISTINCT
    TRIM(COALESCE(CAST(CB.CODFILIAL AS CHAR), '')),
    TRIM(COALESCE(CAST(CB.CODEPTO   AS CHAR), ''))
  FROM ESCOPO E
  JOIN COORDENADORES_BU CB ON 1 = 1
  WHERE E.EH_DIRETORIA
    AND E.SCOPE_COD_SUPERVISOR IS NOT NULL
    AND TRIM(COALESCE(CAST(CB.COD_SUPERVISOR AS CHAR), '')) = E.SCOPE_COD_SUPERVISOR
),

TARGET_USERS AS (
  SELECT :VAR_USER AS USER_ID
  FROM ESCOPO E WHERE E.SCOPE_MODE = 'ME'

  UNION

  SELECT F.ID
  FROM ESCOPO E
  JOIN FUNCIONARIOS F ON F.ID_SUBSTITUTO = :VAR_USER
  WHERE E.SCOPE_MODE = 'ME'

  UNION

  SELECT VR_DONO.USER_ID
  FROM ESCOPO E
  JOIN VENDEDOR_RCA VR_SUB  ON VR_SUB.USER_ID = :VAR_USER
  JOIN FERIAS_VENDEDOR FV   ON FV.COD_RCA_SUBSTITUTO = VR_SUB.COD_RCA
  JOIN VENDEDOR_RCA VR_DONO ON VR_DONO.COD_RCA = FV.COD_RCA
  WHERE E.SCOPE_MODE = 'ME'
    AND COALESCE(FV.ATIVO, TRUE) = TRUE
    AND CURRENT_DATE BETWEEN FV.DT_INICIO AND FV.DT_FIM

  UNION

  -- TEAM: vendedores comuns das BUs autorizadas. Diretoria nao sofre a exclusao de coordenador.
  SELECT DISTINCT BV.VENDEDOR_ID
  FROM ESCOPO E
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE E.SCOPE_MODE = 'TEAM'
    AND (
      E.ESCOPO_ABERTO
      OR EXISTS (
        SELECT 1 FROM BU_AUTORIZADA A
        WHERE A.CODFILIAL = TRIM(COALESCE(CAST(BV.CODFILIAL  AS CHAR), ''))
          AND A.CODEPTO   = TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), ''))
      )
    )
    AND (E.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL  AS CHAR), '')) = E.SCOPE_CODFILIAL)
    AND (E.SCOPE_CODEPTO   IS NULL OR TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) = E.SCOPE_CODEPTO)
    AND (
      E.SCOPE_ID_SECAO IS NULL
      OR TRIM(COALESCE(CAST(BV.ID_SECAO AS CHAR), '')) = E.SCOPE_ID_SECAO
      OR LPAD(TRIM(COALESCE(CAST(BV.ID_SECAO AS CHAR), '')), 2, '0') = E.SCOPE_ID_SECAO
    )
    AND (
      E.EH_DIRETORIA
      OR NOT EXISTS (
        SELECT 1 FROM COORDENADORES CO
        WHERE CO.USER_ID = BV.VENDEDOR_ID
          AND COALESCE(CO.ATIVO, TRUE) = TRUE
          AND CO.USER_ID <> :VAR_USER
      )
    )

  UNION

  -- SELLER: um vendedor especifico, por id ou por RCA.
  SELECT DISTINCT BV.VENDEDOR_ID
  FROM ESCOPO E
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  LEFT JOIN VENDEDOR_RCA VR ON VR.USER_ID = BV.VENDEDOR_ID
  WHERE E.SCOPE_MODE = 'SELLER'
    AND (BV.VENDEDOR_ID = E.SCOPE_USER_ID OR VR.COD_RCA = E.SCOPE_COD_RCA)
    AND (
      E.ESCOPO_ABERTO
      OR EXISTS (
        SELECT 1 FROM BU_AUTORIZADA A
        WHERE A.CODFILIAL = TRIM(COALESCE(CAST(BV.CODFILIAL  AS CHAR), ''))
          AND A.CODEPTO   = TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), ''))
      )
    )
    AND (E.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL  AS CHAR), '')) = E.SCOPE_CODFILIAL)
    AND (E.SCOPE_CODEPTO   IS NULL OR TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) = E.SCOPE_CODEPTO)
    AND (
      E.SCOPE_ID_SECAO IS NULL
      OR TRIM(COALESCE(CAST(BV.ID_SECAO AS CHAR), '')) = E.SCOPE_ID_SECAO
      OR LPAD(TRIM(COALESCE(CAST(BV.ID_SECAO AS CHAR), '')), 2, '0') = E.SCOPE_ID_SECAO
    )
    AND (
      E.EH_DIRETORIA
      OR NOT EXISTS (
        SELECT 1 FROM COORDENADORES CO
        WHERE CO.USER_ID = BV.VENDEDOR_ID
          AND COALESCE(CO.ATIVO, TRUE) = TRUE
          AND CO.USER_ID <> :VAR_USER
      )
    )

  UNION

  -- GLOBAL: so diretoria. Coordenadores entram no conjunto, nao sao excluidos.
  SELECT DISTINCT BV.VENDEDOR_ID
  FROM ESCOPO E
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE E.SCOPE_MODE = 'GLOBAL'
    AND E.EH_DIRETORIA
    AND (
      E.ESCOPO_ABERTO
      OR EXISTS (
        SELECT 1 FROM BU_AUTORIZADA A
        WHERE A.CODFILIAL = TRIM(COALESCE(CAST(BV.CODFILIAL  AS CHAR), ''))
          AND A.CODEPTO   = TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), ''))
      )
    )
    AND (E.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL  AS CHAR), '')) = E.SCOPE_CODFILIAL)
    AND (E.SCOPE_CODEPTO   IS NULL OR TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) = E.SCOPE_CODEPTO)
    AND (
      E.SCOPE_ID_SECAO IS NULL
      OR TRIM(COALESCE(CAST(BV.ID_SECAO AS CHAR), '')) = E.SCOPE_ID_SECAO
      OR LPAD(TRIM(COALESCE(CAST(BV.ID_SECAO AS CHAR), '')), 2, '0') = E.SCOPE_ID_SECAO
    )
),

-- Filial/depto/secao saem inteiros do BU_VENDEDOR. Filtros de escopo repetidos aqui
-- porque este e o CTE que casa com a venda.
BU_SCOPE AS (
  SELECT DISTINCT
    TU.USER_ID AS TARGET_USER_ID,
    TRIM(COALESCE(CAST(BV.CODFILIAL  AS CHAR), '')) AS CODFILIAL,
    TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) AS CODEPTO,
    BV.ID_SECAO
  FROM TARGET_USERS TU
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = TU.USER_ID
  JOIN ESCOPO E ON 1 = 1
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND TRIM(COALESCE(CAST(BV.CODFILIAL  AS CHAR), '')) <> ''
    AND TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) <> ''
    AND (E.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL  AS CHAR), '')) = E.SCOPE_CODFILIAL)
    AND (E.SCOPE_CODEPTO   IS NULL OR TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) = E.SCOPE_CODEPTO)
    AND (
      E.SCOPE_ID_SECAO IS NULL
      OR TRIM(COALESCE(CAST(BV.ID_SECAO AS CHAR), '')) = E.SCOPE_ID_SECAO
      OR LPAD(TRIM(COALESCE(CAST(BV.ID_SECAO AS CHAR), '')), 2, '0') = E.SCOPE_ID_SECAO
    )
),

-- Vinculo cliente x vendedor apenas. Sem fallback para ID interno.
CARTEIRA_SCOPE AS (
  SELECT DISTINCT
    TU.USER_ID AS TARGET_USER_ID,
    TRIM(COALESCE(CAST(C.WINTHOR_CODCLI AS CHAR), '')) AS CODCLI
  FROM TARGET_USERS TU
  JOIN EQUIPE_CLIENTE EC ON EC.ID_VENDEDOR = TU.USER_ID
  JOIN CLIENTES C ON C.ID = EC.ID_CLIENTE
  WHERE C.WINTHOR_CODCLI IS NOT NULL
    AND TRIM(COALESCE(CAST(C.WINTHOR_CODCLI AS CHAR), '')) <> ''
),

VENDAS_ATRIBUIDAS AS (
  SELECT
    CASE
      WHEN CAST(V.DTSAIDA AS CHAR) REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}'
        THEN STR_TO_DATE(SUBSTRING(CAST(V.DTSAIDA AS CHAR), 1, 10), '%Y-%m-%d')
      WHEN CAST(V.DTSAIDA AS CHAR) REGEXP '^[0-9]{2}/[0-9]{2}/[0-9]{4}'
        THEN STR_TO_DATE(SUBSTRING(CAST(V.DTSAIDA AS CHAR), 1, 10), '%d/%m/%Y')
      WHEN CAST(V.DTSAIDA AS CHAR) REGEXP '^[0-9]{8}$'
        THEN STR_TO_DATE(CAST(V.DTSAIDA AS CHAR), '%Y%m%d')
      ELSE NULL
    END AS DATA_REF,
    V.TOTAL
  FROM IMP_VENDAS_DASHBOARD_TOTVS_RCA V
  WHERE EXISTS (
      SELECT 1
      FROM BU_SCOPE B
      JOIN CARTEIRA_SCOPE CS ON CS.TARGET_USER_ID = B.TARGET_USER_ID
      WHERE B.CODFILIAL = TRIM(COALESCE(CAST(V.CODFILIAL AS CHAR), ''))
        AND B.CODEPTO   = TRIM(COALESCE(CAST(V.CODEPTO  AS CHAR), ''))
        AND CS.CODCLI   = TRIM(COALESCE(CAST(V.CODCLI   AS CHAR), ''))
        AND (
          B.ID_SECAO IS NULL
          OR TRIM(COALESCE(CAST(B.ID_SECAO AS CHAR), '')) = TRIM(COALESCE(CAST(V.CODSEC AS CHAR), ''))
          OR LPAD(TRIM(COALESCE(CAST(B.ID_SECAO AS CHAR), '')), 2, '0') = TRIM(COALESCE(CAST(V.CODSEC AS CHAR), ''))
        )
    )
  HAVING DATA_REF BETWEEN (SELECT DT_INI FROM JANELA) AND (SELECT DT_FIM FROM JANELA)
),

DEVOLUCOES_ATRIBUIDAS AS (
  SELECT
    CASE
      WHEN CAST(D.DATA_DEVOLUCAO AS CHAR) REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}'
        THEN STR_TO_DATE(SUBSTRING(CAST(D.DATA_DEVOLUCAO AS CHAR), 1, 10), '%Y-%m-%d')
      WHEN CAST(D.DATA_DEVOLUCAO AS CHAR) REGEXP '^[0-9]{2}/[0-9]{2}/[0-9]{4}'
        THEN STR_TO_DATE(SUBSTRING(CAST(D.DATA_DEVOLUCAO AS CHAR), 1, 10), '%d/%m/%Y')
      WHEN CAST(D.DATA_DEVOLUCAO AS CHAR) REGEXP '^[0-9]{8}$'
        THEN STR_TO_DATE(CAST(D.DATA_DEVOLUCAO AS CHAR), '%Y%m%d')
      ELSE NULL
    END AS DATA_REF,
    D.VALOR_DEVOLVIDO
  FROM IMP_DEVOLUCOES_TOTVS D
  WHERE EXISTS (
      SELECT 1
      FROM BU_SCOPE B
      JOIN CARTEIRA_SCOPE CS ON CS.TARGET_USER_ID = B.TARGET_USER_ID
      WHERE B.CODFILIAL = TRIM(COALESCE(CAST(D.CODFILIAL AS CHAR), ''))
        AND B.CODEPTO   = TRIM(COALESCE(CAST(D.CODEPTO  AS CHAR), ''))
        AND CS.CODCLI   = TRIM(COALESCE(CAST(D.CODCLI   AS CHAR), ''))
        AND (
          B.ID_SECAO IS NULL
          OR TRIM(COALESCE(CAST(B.ID_SECAO AS CHAR), '')) = TRIM(COALESCE(CAST(D.CODSEC AS CHAR), ''))
          OR LPAD(TRIM(COALESCE(CAST(B.ID_SECAO AS CHAR), '')), 2, '0') = TRIM(COALESCE(CAST(D.CODSEC AS CHAR), ''))
        )
    )
  HAVING DATA_REF BETWEEN (SELECT DT_INI FROM JANELA) AND (SELECT DT_FIM FROM JANELA)
),

DIAS_BASE AS (
  SELECT DT_INI AS DATA_REF FROM JANELA
  UNION ALL
  SELECT DATE_ADD(DB.DATA_REF, INTERVAL 1 DAY)
  FROM DIAS_BASE DB JOIN JANELA J ON 1 = 1
  WHERE DB.DATA_REF < J.DT_FIM
),

DIAS AS (
  SELECT DATA_REF FROM (
    SELECT DATA_REF FROM DIAS_BASE
    WHERE WEEKDAY(DATA_REF) < 5
    ORDER BY DATA_REF DESC LIMIT 7
  ) ULTIMOS_DIAS_UTEIS
),

VENDAS_DIA AS (
  SELECT DATA_REF, ROUND(SUM(TOTAL), 2) AS VENDAS_BRUTAS
  FROM VENDAS_ATRIBUIDAS GROUP BY DATA_REF
),

DEVOLUCOES_DIA AS (
  SELECT DATA_REF, ROUND(SUM(VALOR_DEVOLVIDO), 2) AS DEVOLUCOES
  FROM DEVOLUCOES_ATRIBUIDAS GROUP BY DATA_REF
),

SERIE AS (
  SELECT
    D.DATA_REF,
    DATE_FORMAT(D.DATA_REF, '%d/%m') AS DIA_LABEL,
    ROUND(COALESCE(V.VENDAS_BRUTAS, 0) - COALESCE(DEV.DEVOLUCOES, 0), 2) AS VALOR_ATUAL
  FROM DIAS D
  LEFT JOIN VENDAS_DIA     V   ON V.DATA_REF   = D.DATA_REF
  LEFT JOIN DEVOLUCOES_DIA DEV ON DEV.DATA_REF = D.DATA_REF
),

SERIE_COMP AS (
  SELECT S.*, LAG(S.VALOR_ATUAL) OVER (ORDER BY S.DATA_REF) AS VALOR_ANTERIOR
  FROM SERIE S
)

SELECT
  DATE_FORMAT(S.DATA_REF, '%Y-%m-%d') AS DATA_REF,
  S.DIA_LABEL,
  S.VALOR_ATUAL,
  S.VALOR_ANTERIOR,
  CASE
    WHEN S.VALOR_ANTERIOR IS NULL THEN NULL
    WHEN S.VALOR_ANTERIOR = 0 AND S.VALOR_ATUAL = 0 THEN 0
    WHEN S.VALOR_ANTERIOR <= 0 THEN NULL
    ELSE ROUND(((S.VALOR_ATUAL - S.VALOR_ANTERIOR) / S.VALOR_ANTERIOR) * 100, 1)
  END AS VARIACAO_DIA
FROM SERIE_COMP S
ORDER BY S.DATA_REF