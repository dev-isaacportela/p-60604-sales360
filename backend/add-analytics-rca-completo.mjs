function extractSfId(response) {
  return response?.result?.serverFunctionId
    || response?.result?.id
    || response?.serverFunctionId
    || response?.id
    || null;
}

async function main() {
  if (process.env.ALLOW_ANALYTICS_BASE_OVERWRITE !== 'true') {
    throw new Error(
      'Este script base pode sobrescrever ajustes incrementais do Analytics. Use repair-analytics-cliente-faturamento.mjs ou execute com ALLOW_ANALYTICS_BASE_OVERWRITE=true apenas para recriar a base conscientemente.',
    );
  }

  const listed = await listServerFunctionsMitra({ projectId });
  const existing = listed?.result || [];
  const ids = {};

  for (const [name, description, code] of serverFunctions) {
    const found = existing.find((sf) => sf.name === name);
    if (found) {
      await updateServerFunctionMitra({ projectId, serverFunctionId: found.id, code, description });
      ids[name] = found.id;
      console.log(`${name}: atualizada (ID ${found.id})`);
      continue;
    }

    const created = await createServerFunctionMitra({ projectId, name, type: 'SQL', code, description });
    const id = extractSfId(created);
    ids[name] = id;
    console.log(`${name}: criada (ID ${id})`);
  }

  const now = new Date();
  const dataInicio = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-01`;
  const dataFim = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(new Date(now.getFullYear(), now.getMonth() + 1, 0).getDate()).padStart(2, '0')}`;
  for (const name of ['analyticsRcaMetaResumo', 'analyticsRcaEvolucao24m']) {
    const result = await executeServerFunctionMitra({
      projectId,
      serverFunctionId: ids[name],
      input: { dataInicio, dataFim, departamentos: '', ramos: '', limit: '50', offset: '0' },
    });
    const status = String(result?.result?.executionStatus || '');
    const error = String(result?.result?.error || '').trim();
    if ((status && status !== 'COMPLETED') || error) throw new Error(`${name} falhou no smoke: ${error || status}`);
    console.log(`${name}: smoke OK`);
  }

  console.log(JSON.stringify(ids, null, 2));
}

main().catch((error) => {
  console.error('Falha ao configurar Analytics RCA completo:');
  console.error(error?.message || error);
  process.exit(1);
});
