async function main() {
  const col = await runQueryMitra({ projectId, sql: "SELECT COUNT(*) N FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='CLIENTE_TITULAR_DEPTO' AND COLUMN_NAME='ALTERADO_POR'" });
  if (Number(col.result.rows[0].N) === 0) {
    await runDdlMitra({ projectId, sql: 'ALTER TABLE CLIENTE_TITULAR_DEPTO ADD COLUMN ALTERADO_POR INT NULL' });
    console.log('Coluna ALTERADO_POR adicionada');
  }

  const list = await listServerFunctionsMitra({ projectId });
  const existentes = new Map((list.result || []).map((f) => [f.name, f.id]));
  for (const sf of SFS) {
    const id = existentes.get(sf.name);
    if (id) {
      await updateServerFunctionMitra({ projectId, serverFunctionId: id, code: sf.code, description: sf.description });
      console.log(`${sf.name}: ${id} (atualizada)`);
    } else {
      const r = await createServerFunctionMitra({ projectId, name: sf.name, type: 'SQL', code: sf.code, description: sf.description });
      console.log(`${sf.name}: ${r.result.serverFunctionId} (criada)`);
    }
  }
}
main().catch((e) => { console.error(e?.response?.data || e); process.exit(1); });
