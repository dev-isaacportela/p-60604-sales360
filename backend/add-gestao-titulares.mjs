// Fase 2 — Gestão de Titulares (cliente x filial x depto x seção).
// Coordenador gerencia as filiais/deptos do seu COORDENADORES_BU; diretoria/admin gerencia tudo.
// Candidatos = vendedores com o cliente na carteira (EQUIPE_CLIENTE) e a combinação no BU_VENDEDOR
// (junção só por VENDEDOR_ID — filial/depto/seção vêm do BU_VENDEDOR).
import 'dotenv/config';
import {
  configureSdkMitra, runDdlMitra, runQueryMitra,
  createServerFunctionMitra, updateServerFunctionMitra, listServerFunctionsMitra
} from 'mitra-sdk';
import { USUARIOS_EXCLUIDOS_SQL } from './titulares-config.mjs';

configureSdkMitra({
  baseURL: process.env.MITRA_BASE_URL,
  token: process.env.MITRA_TOKEN,
  integrationURL: process.env.MITRA_BASE_URL_INTEGRATIONS
});
const projectId = parseInt(process.env.MITRA_PROJECT_ID);

// Bloqueados e institucionais — fora da titularidade (ver titulares-config.mjs)
const INSTITUCIONAIS = USUARIOS_EXCLUIDOS_SQL;
// Departamentos em que o titular é decidido por seção (Enfermagem). Nos demais, a decisão é
// por cliente x filial x departamento e vale para todas as seções (gravação segue por seção).
const DEPTOS_POR_SECAO = "'2'";

const PERM_CTE = `
PERM AS (
  SELECT
    CASE
      WHEN UPPER(COALESCE(UC.CARGO, '')) IN ('ADMIN', 'DIRETORIA') THEN 1
      WHEN LOWER(COALESCE(U.DESCR, '')) = 'ti@benenutri.com' THEN 1
      ELSE 0
    END AS PODE_DIRETORIA,
    C.COD_SUPERVISOR
  FROM INT_USER U
  LEFT JOIN USUARIO_CARGO UC ON UC.USER_ID = U.ID
  LEFT JOIN COORDENADORES C ON C.USER_ID = U.ID AND COALESCE(C.ATIVO, TRUE) = TRUE
  WHERE U.ID = :VAR_USER
  LIMIT 1
),
ESCOPO_GESTAO AS (
  SELECT DISTINCT TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL, TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO
  FROM BU_VENDEDOR BV
  JOIN PERM P ON P.PODE_DIRETORIA = 1
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
  UNION
  SELECT DISTINCT TRIM(CAST(CB.CODFILIAL AS CHAR)), TRIM(CAST(CB.CODEPTO AS CHAR))
  FROM COORDENADORES_BU CB
  JOIN PERM P ON P.COD_SUPERVISOR = CB.COD_SUPERVISOR
)`;

const INPUTS_CTE = `
INPUTS AS (
  SELECT
    CASE WHEN '{{codFilial}}' = '' OR LOCATE('{', '{{codFilial}}') > 0 THEN NULL ELSE TRIM('{{codFilial}}') END AS F_PARAM,
    CASE WHEN '{{codepto}}' = '' OR LOCATE('{', '{{codepto}}') > 0 THEN NULL ELSE TRIM('{{codepto}}') END AS D_PARAM,
    CASE WHEN '{{situacao}}' IN ('PENDENTE', 'DEFINIDO', 'AUTO', 'MANUAL') THEN '{{situacao}}' ELSE NULL END AS SIT_PARAM,
    CASE WHEN '{{busca}}' = '' OR LOCATE('{', '{{busca}}') > 0 THEN NULL ELSE UPPER(TRIM('{{busca}}')) END AS BUSCA_PARAM
)`;

// Combinações candidatas dentro do escopo de gestão
const COMBOS_CTE = `
CAND AS (
  SELECT DISTINCT
    EC.ID_CLIENTE,
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL,
    TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO,
    BV.ID_SECAO,
    BV.VENDEDOR_ID
  FROM EQUIPE_CLIENTE EC
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = EC.ID_VENDEDOR
   AND COALESCE(BV.ATIVO, TRUE) = TRUE
  JOIN ESCOPO_GESTAO EG
    ON EG.CODFILIAL = TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), ''))
   AND EG.CODEPTO = TRIM(CAST(BV.BU_CODIGO AS CHAR))
  JOIN INPUTS I ON 1 = 1
  WHERE BV.ID_SECAO IS NOT NULL
    AND BV.VENDEDOR_ID NOT IN ${INSTITUCIONAIS}
    AND (I.F_PARAM IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.F_PARAM)
    AND (I.D_PARAM IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.D_PARAM)
),
COMBOS AS (
  SELECT
    CA.ID_CLIENTE, CA.CODFILIAL, CA.CODEPTO, CA.ID_SECAO,
    COUNT(DISTINCT CA.VENDEDOR_ID) AS N_CANDIDATOS,
    GROUP_CONCAT(DISTINCT CONCAT(CA.VENDEDOR_ID, ':', REPLACE(COALESCE(NULLIF(TRIM(FN.NOME), ''), NULLIF(TRIM(U.NOME), ''), U.DESCR, CONCAT('Usuário ', CA.VENDEDOR_ID)), '|', ' ')) ORDER BY CA.VENDEDOR_ID SEPARATOR '|') AS CANDIDATOS
  FROM CAND CA
  LEFT JOIN INT_USER U ON U.ID = CA.VENDEDOR_ID
  LEFT JOIN FUNCIONARIOS FN ON FN.ID = CA.VENDEDOR_ID
  GROUP BY CA.ID_CLIENTE, CA.CODFILIAL, CA.CODEPTO, CA.ID_SECAO
),
POR_SECAO AS (
  SELECT
    CO.*,
    CASE WHEN CO.CODEPTO IN (${DEPTOS_POR_SECAO}) THEN CO.ID_SECAO END AS GRUPO_SECAO,
    T.VENDEDOR_ID AS TIT_ID,
    T.ORIGEM AS TIT_ORIGEM,
    T.ATUALIZADO_EM AS TIT_ATUALIZADO
  FROM COMBOS CO
  LEFT JOIN CLIENTE_TITULAR_DEPTO T
    ON T.ID_CLIENTE = CO.ID_CLIENTE AND T.CODFILIAL = CO.CODFILIAL
   AND T.CODEPTO = CO.CODEPTO AND T.ID_SECAO = CO.ID_SECAO
   AND COALESCE(T.ATIVO, TRUE) = TRUE
   AND T.VENDEDOR_ID NOT IN ${INSTITUCIONAIS}
),
GRUPOS AS (
  SELECT
    PS.ID_CLIENTE, PS.CODFILIAL, PS.CODEPTO, PS.GRUPO_SECAO,
    MIN(PS.ID_SECAO) AS ID_SECAO,
    COUNT(*) AS N_SECOES,
    MAX(PS.N_CANDIDATOS) AS N_CANDIDATOS_MAX,
    SUM(CASE WHEN PS.TIT_ID IS NULL AND PS.N_CANDIDATOS > 1 THEN 1 ELSE 0 END) AS SECOES_PENDENTES,
    SUM(CASE WHEN PS.TIT_ID IS NULL THEN 1 ELSE 0 END) AS SECOES_SEM_TITULAR,
    COUNT(DISTINCT PS.TIT_ID) AS N_TITULARES,
    MAX(PS.TIT_ID) AS TIT_MAX,
    MAX(PS.TIT_ORIGEM) AS ORIGEM,
    MAX(PS.TIT_ATUALIZADO) AS ATUALIZADO_EM
  FROM POR_SECAO PS
  GROUP BY PS.ID_CLIENTE, PS.CODFILIAL, PS.CODEPTO, PS.GRUPO_SECAO
),
GRUPO_CAND AS (
  SELECT
    CA.ID_CLIENTE, CA.CODFILIAL, CA.CODEPTO,
    CASE WHEN CA.CODEPTO IN (${DEPTOS_POR_SECAO}) THEN CA.ID_SECAO END AS GRUPO_SECAO,
    COUNT(DISTINCT CA.VENDEDOR_ID) AS N_CANDIDATOS,
    GROUP_CONCAT(DISTINCT CONCAT(CA.VENDEDOR_ID, ':', REPLACE(COALESCE(NULLIF(TRIM(FN.NOME), ''), NULLIF(TRIM(U.NOME), ''), U.DESCR, CONCAT('Usuário ', CA.VENDEDOR_ID)), '|', ' ')) ORDER BY CA.VENDEDOR_ID SEPARATOR '|') AS CANDIDATOS
  FROM CAND CA
  LEFT JOIN INT_USER U ON U.ID = CA.VENDEDOR_ID
  LEFT JOIN FUNCIONARIOS FN ON FN.ID = CA.VENDEDOR_ID
  GROUP BY CA.ID_CLIENTE, CA.CODFILIAL, CA.CODEPTO, CASE WHEN CA.CODEPTO IN (${DEPTOS_POR_SECAO}) THEN CA.ID_SECAO END
),
BASE AS (
  SELECT
    G.ID_CLIENTE, G.CODFILIAL, G.CODEPTO, G.ID_SECAO, G.GRUPO_SECAO, G.N_SECOES,
    GC.N_CANDIDATOS, GC.CANDIDATOS,
    C.WINTHOR_CODCLI AS CODCLI,
    COALESCE(NULLIF(TRIM(C.NOME_FANTASIA), ''), NULLIF(TRIM(C.RAZAO_SOCIAL), ''), CONCAT('Cliente ', G.ID_CLIENTE)) AS CLIENTE,
    CASE WHEN G.SECOES_SEM_TITULAR = 0 AND G.N_TITULARES = 1 THEN G.TIT_MAX END AS TITULAR_ID,
    G.ORIGEM,
    G.ATUALIZADO_EM,
    CASE
      WHEN G.SECOES_PENDENTES > 0 THEN 'PENDENTE'
      WHEN G.SECOES_SEM_TITULAR = 0 AND G.N_TITULARES = 1 THEN 'DEFINIDO'
      WHEN G.SECOES_SEM_TITULAR = 0 THEN 'MISTO'
      ELSE 'SEM_TITULAR'
    END AS SITUACAO
  FROM GRUPOS G
  JOIN GRUPO_CAND GC
    ON GC.ID_CLIENTE = G.ID_CLIENTE AND GC.CODFILIAL = G.CODFILIAL AND GC.CODEPTO = G.CODEPTO
   AND COALESCE(GC.GRUPO_SECAO, -1) = COALESCE(G.GRUPO_SECAO, -1)
  LEFT JOIN CLIENTES C ON C.ID = G.ID_CLIENTE
  JOIN INPUTS I ON 1 = 1
  WHERE (I.SIT_PARAM IS NULL
      OR (I.SIT_PARAM = 'PENDENTE' AND G.SECOES_PENDENTES > 0)
      OR (I.SIT_PARAM = 'DEFINIDO' AND G.SECOES_SEM_TITULAR = 0)
      OR (I.SIT_PARAM IN ('AUTO', 'MANUAL') AND G.ORIGEM = I.SIT_PARAM))
    AND (I.BUSCA_PARAM IS NULL
      OR UPPER(COALESCE(C.NOME_FANTASIA, '')) LIKE CONCAT('%', I.BUSCA_PARAM, '%')
      OR UPPER(COALESCE(C.RAZAO_SOCIAL, '')) LIKE CONCAT('%', I.BUSCA_PARAM, '%')
      OR CAST(C.WINTHOR_CODCLI AS CHAR) LIKE CONCAT('%', I.BUSCA_PARAM, '%'))
)`;

const VENDAS_CTE = `
VENDAS_12M AS (
  SELECT
    TRIM(CAST(P.CLIENTE_ID AS CHAR)) AS CODCLI,
    TRIM(CAST(P.CODFILIAL AS CHAR)) AS CODFILIAL,
    TRIM(CAST(P.CODEPTO AS CHAR)) AS CODEPTO,
    TRIM(CAST(P.ID_SECAO AS CHAR)) AS ID_SECAO,
    SUM(P.VALOR) AS VALOR
  FROM PEDIDOS_SEMANAIS_SYNC P
  WHERE COALESCE(P.ATIVO, 1) = 1
    AND (P.ANO * 100 + P.MES) >= CAST(DATE_FORMAT(DATE_SUB(CURRENT_DATE, INTERVAL 12 MONTH), '%Y%m') AS UNSIGNED)
  GROUP BY 1, 2, 3, 4
)`;

