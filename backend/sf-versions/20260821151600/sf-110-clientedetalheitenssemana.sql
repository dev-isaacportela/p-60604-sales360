WITH
INPUT_SCOPE AS (
  SELECT
    CASE WHEN '{{scopeMode}}' IN ('TEAM', 'SELLER', 'GLOBAL') THEN '{{scopeMode}}' ELSE 'ME' END AS SCOPE_MODE,
    CASE WHEN '{{scopeUserId}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeUserId}}' AS UNSIGNED) ELSE NULL END AS SCOPE_USER_ID,
    CASE WHEN '{{scopeCodRca}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeCodRca}}' AS UNSIGNED) ELSE NULL END AS SCOPE_COD_RCA,
    CASE WHEN '{{scopeCodFilial}}' = '' OR LOCATE('{', '{{scopeCodFilial}}') > 0 THEN NULL ELSE TRIM('{{scopeCodFilial}}') END AS SCOPE_CODFILIAL,
    CASE WHEN '{{scopeCodepto}}' = '' OR LOCATE('{', '{{scopeCodepto}}') > 0 THEN NULL ELSE TRIM('{{scopeCodepto}}') END AS SCOPE_CODEPTO,
    CASE WHEN '{{scopeIdSecao}}' = '' OR LOCATE('{', '{{scopeIdSecao}}') > 0 THEN NULL ELSE TRIM('{{scopeIdSecao}}') END AS SCOPE_ID_SECAO,
    CASE WHEN '{{scopeCodSupervisor}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeCodSupervisor}}' AS UNSIGNED) ELSE NULL END AS SCOPE_COD_SUPERVISOR
),
TARGET_USERS AS (
  SELECT :VAR_USER AS USER_ID
  FROM INPUT_SCOPE I
  WHERE I.SCOPE_MODE = 'ME'
  UNION
  SELECT F.ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN FUNCIONARIOS F ON F.ID_SUBSTITUTO = :VAR_USER
  WHERE I.SCOPE_MODE = 'ME'
  UNION
  SELECT VR_DONO.USER_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN VENDEDOR_RCA VR_SUB ON VR_SUB.USER_ID = :VAR_USER
  JOIN FERIAS_VENDEDOR FV ON FV.COD_RCA_SUBSTITUTO = VR_SUB.COD_RCA
  JOIN VENDEDOR_RCA VR_DONO ON VR_DONO.COD_RCA = FV.COD_RCA
  WHERE I.SCOPE_MODE = 'ME'
    AND COALESCE(FV.ATIVO, TRUE) = TRUE
    AND CURRENT_DATE BETWEEN FV.DT_INICIO AND FV.DT_FIM
  UNION
  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  WHERE I.SCOPE_MODE = 'TEAM'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND NOT EXISTS (
      SELECT 1
      FROM COORDENADORES C_COORD_ALVO
      WHERE C_COORD_ALVO.USER_ID = BV.VENDEDOR_ID
        AND COALESCE(C_COORD_ALVO.ATIVO, TRUE) = TRUE
        AND C_COORD_ALVO.USER_ID <> :VAR_USER
    )
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
  UNION
  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN INT_USER U ON U.ID = :VAR_USER
  LEFT JOIN USUARIO_CARGO UC ON UC.USER_ID = U.ID
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  LEFT JOIN VENDEDOR_RCA VR ON VR.USER_ID = BV.VENDEDOR_ID
  WHERE I.SCOPE_MODE = 'SELLER'
    AND (BV.VENDEDOR_ID = I.SCOPE_USER_ID OR VR.COD_RCA = I.SCOPE_COD_RCA)
    AND (
      UPPER(COALESCE(UC.CARGO, '')) IN ('ADMIN', 'DIRETORIA')
      OR LOWER(COALESCE(U.DESCR, '')) = 'ti@benenutri.com'
      OR EXISTS (
        SELECT 1
        FROM COORDENADORES C
        JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
        WHERE C.USER_ID = :VAR_USER
          AND COALESCE(C.ATIVO, TRUE) = TRUE
          AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
          AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
      )
    )
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
  UNION
  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN INT_USER U ON U.ID = :VAR_USER
  LEFT JOIN USUARIO_CARGO UC ON UC.USER_ID = U.ID
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE I.SCOPE_MODE = 'GLOBAL'
    AND (
      UPPER(COALESCE(UC.CARGO, '')) IN ('ADMIN', 'DIRETORIA')
      OR LOWER(COALESCE(U.DESCR, '')) = 'ti@benenutri.com'
    )
    AND (
      I.SCOPE_COD_SUPERVISOR IS NULL
      OR EXISTS (
        SELECT 1
        FROM COORDENADORES C_GLOBAL_SELF
        WHERE C_GLOBAL_SELF.USER_ID = BV.VENDEDOR_ID
          AND COALESCE(C_GLOBAL_SELF.ATIVO, TRUE) = TRUE
          AND C_GLOBAL_SELF.COD_SUPERVISOR = I.SCOPE_COD_SUPERVISOR
      )
      OR (
        NOT EXISTS (
          SELECT 1
          FROM COORDENADORES C_GLOBAL_OTHER_COORD
          WHERE C_GLOBAL_OTHER_COORD.USER_ID = BV.VENDEDOR_ID
            AND COALESCE(C_GLOBAL_OTHER_COORD.ATIVO, TRUE) = TRUE
        )
        AND EXISTS (
          SELECT 1
          FROM COORDENADORES_BU CB_GLOBAL
          WHERE CB_GLOBAL.COD_SUPERVISOR = I.SCOPE_COD_SUPERVISOR
            AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB_GLOBAL.CODFILIAL AS CHAR)
            AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB_GLOBAL.CODEPTO AS CHAR)
        )
      )
    )
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
),
-- Escopo no modelo correto: cliente pela EQUIPE_CLIENTE (so VENDEDOR_ID) e filial/depto/secao pelo BU_VENDEDOR.
ESCOPO AS (
  SELECT DISTINCT
    EC.ID_CLIENTE,
    BV.CODFILIAL,
    BV.BU_CODIGO AS CODEPTO,
    BV.ID_SECAO
  FROM EQUIPE_CLIENTE EC
  JOIN TARGET_USERS TU ON TU.USER_ID = EC.ID_VENDEDOR
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = EC.ID_VENDEDOR
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) <> ''
    AND TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) <> ''
),
-- Periodo de referencia (atual) e a mesma semana do mes anterior.
PERIODO AS (
  SELECT
    CASE WHEN '{{ANO}}' = '' THEN CAST(DATE_FORMAT(GREATEST(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), DATE_SUB(CURRENT_DATE, INTERVAL ((WEEKDAY(CURRENT_DATE) + 3) % 7) DAY)), '%Y') AS UNSIGNED) ELSE CAST('{{ANO}}' AS UNSIGNED) END AS ANO_REF,
    CASE WHEN '{{MES}}' = '' THEN MONTH(GREATEST(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), DATE_SUB(CURRENT_DATE, INTERVAL ((WEEKDAY(CURRENT_DATE) + 3) % 7) DAY))) ELSE CAST('{{MES}}' AS UNSIGNED) END AS MES_REF,
    CAST('{{SEMANA_NUMERO}}' AS UNSIGNED) AS SEMANA_REF
),
PERIODO_CALC AS (
  SELECT
    P.ANO_REF, P.MES_REF, P.SEMANA_REF,
    CASE WHEN P.MES_REF = 1 THEN 12 ELSE P.MES_REF - 1 END AS MES_ANT,
    CASE WHEN P.MES_REF = 1 THEN P.ANO_REF - 1 ELSE P.ANO_REF END AS ANO_ANT
  FROM PERIODO P
),
-- Quantidade por produto por semana, dentro do escopo, cobrindo mes atual + mes anterior.
MOV AS (
  SELECT
    R.CODPROD,
    MAX(R.DESCRICAO) AS DESCRICAO_PRODUTO,
    CAST(DATE_FORMAT(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), '%Y') AS UNSIGNED) AS ANO,
    MONTH(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY))) AS MES,
    CASE WHEN GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)) = DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY) THEN 1 ELSE 2 + FLOOR(DATEDIFF(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), DATE_ADD(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), INTERVAL (CASE WHEN ((4 - WEEKDAY(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY)) + 7) % 7) = 0 THEN 7 ELSE ((4 - WEEKDAY(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY)) + 7) % 7) END) DAY)) / 7) END AS SEMANA_NUMERO,
    SUM(COALESCE(R.QT, 0)) AS QT,
    SUM(COALESCE(R.TOTAL, 0)) AS VALOR_TOTAL,
    ROUND(
      CASE
        WHEN SUM(COALESCE(R.QT, 0)) = 0 THEN COALESCE(MAX(NULLIF(COALESCE(R.VLUNIT, 0), 0)), 0)
        ELSE SUM(COALESCE(R.TOTAL, 0)) / SUM(COALESCE(R.QT, 0))
      END,
      6
    ) AS VALOR_UNITARIO
  FROM PEDIDOS_SEMANAIS_SYNC_RAW R
  JOIN ESCOPO E ON E.ID_CLIENTE = R.CLIENTE_ID
    AND E.CODFILIAL = R.CODFILIAL
    AND E.CODEPTO = R.CODEPTO
    AND (
      E.ID_SECAO IS NULL
      OR E.ID_SECAO = R.ID_SECAO
    )
  JOIN PERIODO_CALC PC ON 1 = 1
  WHERE R.ATIVO = TRUE
    AND R.STATUS_INGESTAO = 'ATIVO'
    AND CAST(R.DATA_SAIDA AS CHAR) REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}'
    AND R.CLIENTE_ID = {{ID_CLIENTE}}
    AND (
      (CAST(DATE_FORMAT(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), '%Y') AS UNSIGNED) = PC.ANO_REF AND MONTH(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY))) = PC.MES_REF)
      OR (CAST(DATE_FORMAT(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), '%Y') AS UNSIGNED) = PC.ANO_ANT AND MONTH(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY))) = PC.MES_ANT)
    )
  GROUP BY R.CODPROD, CAST(DATE_FORMAT(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), '%Y') AS UNSIGNED), MONTH(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY))), CASE WHEN GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)) = DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY) THEN 1 ELSE 2 + FLOOR(DATEDIFF(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), DATE_ADD(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), INTERVAL (CASE WHEN ((4 - WEEKDAY(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY)) + 7) % 7) = 0 THEN 7 ELSE ((4 - WEEKDAY(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY)) + 7) % 7) END) DAY)) / 7) END
),
AGG AS (
  SELECT
    M.CODPROD,
    MAX(M.DESCRICAO_PRODUTO) AS DESCRICAO_PRODUTO,
    SUM(CASE WHEN M.ANO = PC.ANO_REF AND M.MES = PC.MES_REF AND M.SEMANA_NUMERO = PC.SEMANA_REF THEN M.QT ELSE 0 END) AS QTD_SEMANA_ATUAL,
    SUM(CASE WHEN M.ANO = PC.ANO_ANT AND M.MES = PC.MES_ANT AND M.SEMANA_NUMERO = PC.SEMANA_REF THEN M.QT ELSE 0 END) AS QTD_SEMANA_MES_ANTERIOR,
    SUM(CASE WHEN M.ANO = PC.ANO_REF AND M.MES = PC.MES_REF AND M.SEMANA_NUMERO = PC.SEMANA_REF THEN M.VALOR_TOTAL ELSE 0 END) AS VALOR_TOTAL_PRODUTO_SEMANA,
    MAX(CASE WHEN M.ANO = PC.ANO_REF AND M.MES = PC.MES_REF AND M.SEMANA_NUMERO = PC.SEMANA_REF THEN M.VALOR_UNITARIO ELSE NULL END) AS VALOR_UNITARIO_ATUAL,
    MAX(CASE WHEN M.ANO = PC.ANO_ANT AND M.MES = PC.MES_ANT AND M.SEMANA_NUMERO = PC.SEMANA_REF THEN M.VALOR_UNITARIO ELSE NULL END) AS VALOR_UNITARIO_ANTERIOR,
    -- HISTORICO_SEMANAL no formato label:qtd|label:qtd..., mais recente primeiro, so semanas com quantidade.
    GROUP_CONCAT(
      CASE WHEN M.QT <> 0
        THEN CONCAT(M.ANO, '-', LPAD(M.MES, 2, '0'), '-S', M.SEMANA_NUMERO, ':', ROUND(M.QT, 2))
      END
      ORDER BY M.ANO DESC, M.MES DESC, M.SEMANA_NUMERO DESC
      SEPARATOR '|'
    ) AS HISTORICO_SEMANAL
  FROM MOV M
  JOIN PERIODO_CALC PC ON 1 = 1
  GROUP BY M.CODPROD
)
SELECT
  A.CODPROD,
  A.DESCRICAO_PRODUTO,
  ROUND(A.QTD_SEMANA_ATUAL, 2) AS QTD_SEMANA_ATUAL,
  ROUND(A.QTD_SEMANA_MES_ANTERIOR, 2) AS QTD_SEMANA_MES_ANTERIOR,
  CASE
    WHEN A.QTD_SEMANA_MES_ANTERIOR = 0 THEN -1
    ELSE ROUND((A.QTD_SEMANA_ATUAL - A.QTD_SEMANA_MES_ANTERIOR) / A.QTD_SEMANA_MES_ANTERIOR, 4)
  END AS DELTA_QTD_SEMANA,
  ROUND(COALESCE(A.VALOR_TOTAL_PRODUTO_SEMANA, 0), 2) AS VALOR_TOTAL_PRODUTO_SEMANA,
  ROUND(
    COALESCE(
      A.VALOR_UNITARIO_ATUAL,
      A.VALOR_UNITARIO_ANTERIOR,
      CASE
        WHEN COALESCE(A.QTD_SEMANA_ATUAL, 0) = 0 THEN 0
        ELSE A.VALOR_TOTAL_PRODUTO_SEMANA / A.QTD_SEMANA_ATUAL
      END,
      0
    ),
    6
  ) AS VALOR_UNITARIO,
  COALESCE(A.HISTORICO_SEMANAL, '') AS HISTORICO_SEMANAL,
  CASE
    WHEN A.QTD_SEMANA_MES_ANTERIOR = 0 THEN 'Sem histórico'
    WHEN ABS((A.QTD_SEMANA_ATUAL - A.QTD_SEMANA_MES_ANTERIOR) / A.QTD_SEMANA_MES_ANTERIOR) < 0.10 THEN 'Estável'
    WHEN A.QTD_SEMANA_ATUAL > A.QTD_SEMANA_MES_ANTERIOR THEN 'Alta'
    ELSE 'Queda'
  END AS STATUS_COMPARATIVO
FROM AGG A
ORDER BY A.CODPROD