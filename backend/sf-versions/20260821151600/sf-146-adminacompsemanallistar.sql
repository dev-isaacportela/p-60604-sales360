
WITH INPUTS AS (
  SELECT
    CASE WHEN '{{userId}}' REGEXP '^[0-9]+$' THEN CAST('{{userId}}' AS UNSIGNED) ELSE NULL END AS VENDEDOR_PARAM,
    CASE WHEN '{{mes}}' REGEXP '^[0-9]{1,2}$' THEN CAST('{{mes}}' AS UNSIGNED) ELSE MONTH(GREATEST(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), DATE_SUB(CURRENT_DATE, INTERVAL ((WEEKDAY(CURRENT_DATE) + 3) % 7) DAY))) END AS MES_REF,
    CASE WHEN '{{ano}}' REGEXP '^[0-9]{4}$' THEN CAST('{{ano}}' AS UNSIGNED) ELSE CAST(DATE_FORMAT(GREATEST(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), DATE_SUB(CURRENT_DATE, INTERVAL ((WEEKDAY(CURRENT_DATE) + 3) % 7) DAY)), '%Y') AS UNSIGNED) END AS ANO_REF,
    CASE WHEN '{{ramoCliente}}' = '' OR LOCATE('{', '{{ramoCliente}}') > 0 THEN NULL ELSE UPPER('{{ramoCliente}}') END AS RAMO_PARAM
),
ADMIN AS (
  SELECT CASE WHEN LOWER(COALESCE(DESCR, '')) = 'ti@benenutri.com' THEN 1 ELSE 0 END AS PODE_ACESSAR
  FROM INT_USER
  WHERE ID = :VAR_USER
),
BU_SCOPE AS (
  SELECT DISTINCT
    BV.VENDEDOR_ID AS TARGET_USER_ID,
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL,
    TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO,
    BV.ID_SECAO
  FROM BU_VENDEDOR BV
  JOIN INPUTS I ON I.VENDEDOR_PARAM = BV.VENDEDOR_ID
  JOIN ADMIN A ON A.PODE_ACESSAR = 1
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) <> ''
    AND TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) <> ''
),
CLIENTES_RAMO AS (
  SELECT
    ICT.CODCLI,
    MAX(NULLIF(TRIM(CAST(ICT.CLIENTE AS CHAR)), '')) AS CLIENTE_TOTVS,
    COALESCE(NULLIF(TRIM(MAX(CAST(ICT.RAMO AS CHAR))), ''), 'Sem ramo') AS RAMO_CLIENTE
  FROM IMP_CLIENTES_TOTVS ICT
  GROUP BY ICT.CODCLI
),
BASE AS (
  SELECT
    COALESCE(R.CLIENTE_ID, R.CODCLI) AS CLIENTE_ID,
    COALESCE(R.CODCLI, R.CLIENTE_ID) AS CODCLI,
    COALESCE(C.NOME_FANTASIA, C.RAZAO_SOCIAL, CR.CLIENTE_TOTVS, CONCAT('Cliente ', COALESCE(R.CODCLI, R.CLIENTE_ID))) AS CLIENTE,
    COALESCE(CR.RAMO_CLIENTE, 'Sem ramo') AS RAMO_CLIENTE,
    CASE WHEN GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)) = DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY) THEN 1 ELSE 2 + FLOOR(DATEDIFF(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), DATE_ADD(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), INTERVAL (CASE WHEN ((4 - WEEKDAY(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY)) + 7) % 7) = 0 THEN 7 ELSE ((4 - WEEKDAY(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY)) + 7) % 7) END) DAY)) / 7) END AS SEMANA_NUMERO,
    R.COD_RCA,
    B.TARGET_USER_ID AS VENDEDOR_BU_USER_ID,
    COALESCE(NULLIF(TRIM(F.NOME), ''), NULLIF(TRIM(U.NOME), ''), U.DESCR, CONCAT('Usuario ', B.TARGET_USER_ID)) AS VENDEDOR_BU_NOME,
    ROUND(SUM(COALESCE(R.TOTAL, R.VALOR, 0)), 2) AS TOTAL,
    MAX(CASE WHEN EC.ID IS NULL THEN 0 ELSE 1 END) AS NA_CARTEIRA_FLAG
  FROM PEDIDOS_SEMANAIS_SYNC_RAW R
  JOIN INPUTS I ON 1 = 1
  JOIN BU_SCOPE B ON 
  B.CODFILIAL = TRIM(COALESCE(CAST(R.CODFILIAL AS CHAR), ''))
  AND B.CODEPTO = TRIM(CAST(R.CODEPTO AS CHAR))
  AND (
    (
      B.ID_SECAO IS NOT NULL
      AND (
        TRIM(CAST(B.ID_SECAO AS CHAR)) = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
        OR LPAD(TRIM(CAST(B.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
      )
    )
    OR (
      B.ID_SECAO IS NULL
      AND NOT EXISTS (
        SELECT 1
        FROM BU_SCOPE B2
        WHERE B2.TARGET_USER_ID = B.TARGET_USER_ID
          AND B2.CODFILIAL = B.CODFILIAL
          AND B2.CODEPTO = B.CODEPTO
          AND B2.ID_SECAO IS NOT NULL
          AND (
            TRIM(CAST(B2.ID_SECAO AS CHAR)) = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
            OR LPAD(TRIM(CAST(B2.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
          )
      )
    )
  )

  LEFT JOIN CLIENTES C ON C.ID = COALESCE(R.CLIENTE_ID, R.CODCLI)
  LEFT JOIN CLIENTES_RAMO CR ON CR.CODCLI = COALESCE(R.CODCLI, C.WINTHOR_CODCLI, R.CLIENTE_ID)
  LEFT JOIN EQUIPE_CLIENTE EC
    ON EC.ID_VENDEDOR = I.VENDEDOR_PARAM
   AND EC.ID_CLIENTE = COALESCE(R.CLIENTE_ID, R.CODCLI)
  LEFT JOIN FUNCIONARIOS F ON F.ID = B.TARGET_USER_ID
  LEFT JOIN INT_USER U ON U.ID = B.TARGET_USER_ID
  WHERE R.ATIVO = TRUE
    AND R.STATUS_INGESTAO = 'ATIVO'
    AND CAST(R.DATA_SAIDA AS CHAR) REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}'
    AND CAST(DATE_FORMAT(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), '%Y') AS UNSIGNED) = I.ANO_REF
    AND MONTH(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY))) = I.MES_REF
    AND COALESCE(R.CLIENTE_ID, R.CODCLI) IS NOT NULL
    AND (I.RAMO_PARAM IS NULL OR UPPER(COALESCE(CR.RAMO_CLIENTE, 'Sem ramo')) = I.RAMO_PARAM)
  GROUP BY
    COALESCE(R.CLIENTE_ID, R.CODCLI),
    COALESCE(R.CODCLI, R.CLIENTE_ID),
    COALESCE(C.NOME_FANTASIA, C.RAZAO_SOCIAL, CR.CLIENTE_TOTVS, CONCAT('Cliente ', COALESCE(R.CODCLI, R.CLIENTE_ID))),
    COALESCE(CR.RAMO_CLIENTE, 'Sem ramo'),
    CASE WHEN GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)) = DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY) THEN 1 ELSE 2 + FLOOR(DATEDIFF(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), DATE_ADD(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), INTERVAL (CASE WHEN ((4 - WEEKDAY(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY)) + 7) % 7) = 0 THEN 7 ELSE ((4 - WEEKDAY(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY)) + 7) % 7) END) DAY)) / 7) END,
    R.COD_RCA,
    B.TARGET_USER_ID,
    COALESCE(NULLIF(TRIM(F.NOME), ''), NULLIF(TRIM(U.NOME), ''), U.DESCR, CONCAT('Usuario ', B.TARGET_USER_ID))
)
SELECT
  CLIENTE,
  CODCLI,
  RAMO_CLIENTE,
  SEMANA_NUMERO AS SEMANA,
  TOTAL,
  COD_RCA,
  VENDEDOR_BU_USER_ID,
  VENDEDOR_BU_NOME,
  CASE WHEN NA_CARTEIRA_FLAG = 1 THEN 'Sim' ELSE 'Nao' END AS NA_CARTEIRA
FROM BASE
ORDER BY CLIENTE, SEMANA, COD_RCA
