WITH PARAMS AS (
  SELECT
    CASE WHEN '{{mes}}' = '' THEN MONTH(GREATEST(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), DATE_SUB(CURRENT_DATE, INTERVAL ((WEEKDAY(CURRENT_DATE) + 3) % 7) DAY))) ELSE CAST('{{mes}}' AS UNSIGNED) END AS MES_REF,
    CASE WHEN '{{ano}}' = '' THEN CAST(DATE_FORMAT(GREATEST(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), DATE_SUB(CURRENT_DATE, INTERVAL ((WEEKDAY(CURRENT_DATE) + 3) % 7) DAY)), '%Y') AS UNSIGNED) ELSE CAST('{{ano}}' AS UNSIGNED) END AS ANO_REF,
    CASE WHEN '{{semanaNumero}}' = '' THEN CASE WHEN GREATEST(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), DATE_SUB(CURRENT_DATE, INTERVAL ((WEEKDAY(CURRENT_DATE) + 3) % 7) DAY)) = DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY) THEN 1 ELSE 2 + FLOOR(DATEDIFF(GREATEST(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), DATE_SUB(CURRENT_DATE, INTERVAL ((WEEKDAY(CURRENT_DATE) + 3) % 7) DAY)), DATE_ADD(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), INTERVAL (CASE WHEN ((4 - WEEKDAY(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY)) + 7) % 7) = 0 THEN 7 ELSE ((4 - WEEKDAY(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY)) + 7) % 7) END) DAY)) / 7) END ELSE CAST('{{semanaNumero}}' AS UNSIGNED) END AS SEMANA_REF,
    CASE
      WHEN '{{scopeUserId}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeUserId}}' AS UNSIGNED)
      WHEN '{{vendedorId}}' REGEXP '^[0-9]+$' THEN CAST('{{vendedorId}}' AS UNSIGNED)
      ELSE :VAR_USER
    END AS TARGET_USER_ID,
    CASE WHEN '{{scopeMode}}' IN ('ME', 'TEAM', 'SELLER', 'GLOBAL') THEN '{{scopeMode}}' ELSE 'ME' END AS SCOPE_MODE,
    NULLIF('{{scopeCodFilial}}', '') AS FILIAL_PARAM,
    NULLIF('{{scopeCodepto}}', '') AS DEPTO_PARAM,
    NULLIF('{{scopeIdSecao}}', '') AS SECAO_PARAM,
    CASE WHEN '{{scopeCodSupervisor}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeCodSupervisor}}' AS UNSIGNED) ELSE NULL END AS SCOPE_COD_SUPERVISOR,
    CASE
      WHEN '{{cliente}}' = '' OR LOCATE('{', '{{cliente}}') > 0 THEN NULL
      ELSE REPLACE(TRIM('{{cliente}}'), '|', ',')
    END AS CLIENTE_PARAM
),
RAW_OPERACIONAL AS (
  SELECT
    R.*,
    GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)) AS DATA_INICIO_SEMANA_OPERACIONAL,
    LEAST(LAST_DAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')), DATE_ADD(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY), INTERVAL 6 DAY)) AS DATA_FIM_SEMANA_OPERACIONAL,
    CAST(DATE_FORMAT(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), '%Y') AS UNSIGNED) AS ANO_OPERACIONAL,
    MONTH(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY))) AS MES_OPERACIONAL,
    CASE WHEN GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)) = DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY) THEN 1 ELSE 2 + FLOOR(DATEDIFF(GREATEST(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL ((WEEKDAY(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) + 3) % 7) DAY)), DATE_ADD(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY), INTERVAL (CASE WHEN ((4 - WEEKDAY(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY)) + 7) % 7) = 0 THEN 7 ELSE ((4 - WEEKDAY(DATE_SUB(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d'), INTERVAL (DAYOFMONTH(STR_TO_DATE(LEFT(TRIM(CAST(R.DATA_SAIDA AS CHAR)), 10), '%Y-%m-%d')) - 1) DAY)) + 7) % 7) END) DAY)) / 7) END AS SEMANA_NUMERO_OPERACIONAL
  FROM PEDIDOS_SEMANAIS_SYNC_RAW R
  WHERE CAST(R.DATA_SAIDA AS CHAR) REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}'
    AND R.ATIVO = TRUE
    AND R.STATUS_INGESTAO = 'ATIVO'
    AND R.CLIENTE_ID IS NOT NULL
    AND R.CODFILIAL IS NOT NULL
    AND R.CODFILIAL <> ''
    AND R.CODEPTO IS NOT NULL
    AND R.CODEPTO <> ''
    AND R.ID_SECAO IS NOT NULL
),
PEDIDOS_SEMANAIS_SYNC_OPERACIONAL AS (
  SELECT
    R.CLIENTE_ID,
    0 AS VENDEDOR_ID,
    R.CODFILIAL,
    R.CODEPTO,
    R.ID_SECAO,
    MAX(R.SEGMENTO) AS SEGMENTO,
    ROUND(SUM(COALESCE(R.TOTAL, R.VALOR, 0)), 2) AS VALOR,
    ROUND(SUM(COALESCE(R.QT, 0)), 6) AS QT,
    R.SEMANA_NUMERO_OPERACIONAL AS SEMANA_NUMERO,
    R.MES_OPERACIONAL AS MES,
    R.ANO_OPERACIONAL AS ANO,
    TRUE AS ATIVO
  FROM RAW_OPERACIONAL R
  GROUP BY R.CLIENTE_ID, R.CODFILIAL, R.CODEPTO, R.ID_SECAO, R.ANO_OPERACIONAL, R.MES_OPERACIONAL, R.SEMANA_NUMERO_OPERACIONAL
),
PERFIL_COMPRA_CLIENTE_OPERACIONAL AS (
  SELECT
    BASE.CLIENTE_ID,
    BASE.FREQUENCIA,
    BASE.SEMANA_PADRAO,
    BASE.TICKET_MEDIO_3M
  FROM (
    SELECT
      PS.CLIENTE_ID,
      CASE
        WHEN COUNT(DISTINCT CONCAT(PS.ANO, '-', LPAD(PS.MES, 2, '0'), '-', PS.SEMANA_NUMERO)) >= 9 THEN 'SEMANAL'
        WHEN COUNT(DISTINCT CONCAT(PS.ANO, '-', LPAD(PS.MES, 2, '0'), '-', PS.SEMANA_NUMERO)) >= 4 THEN 'QUINZENAL'
        ELSE 'MENSAL'
      END AS FREQUENCIA,
      (
        SELECT P2.SEMANA_NUMERO
        FROM PEDIDOS_SEMANAIS_SYNC_OPERACIONAL P2
        WHERE P2.CLIENTE_ID = PS.CLIENTE_ID
          AND STR_TO_DATE(CONCAT(P2.ANO, '-', LPAD(P2.MES, 2, '0'), '-01'), '%Y-%m-%d') >= DATE_SUB(DATE_FORMAT(GREATEST(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), DATE_SUB(CURRENT_DATE, INTERVAL ((WEEKDAY(CURRENT_DATE) + 3) % 7) DAY)), '%Y-%m-01'), INTERVAL 2 MONTH)
        GROUP BY P2.SEMANA_NUMERO
        ORDER BY COUNT(*) DESC, P2.SEMANA_NUMERO
        LIMIT 1
      ) AS SEMANA_PADRAO,
      ROUND(AVG(PS.VALOR), 2) AS TICKET_MEDIO_3M
    FROM PEDIDOS_SEMANAIS_SYNC_OPERACIONAL PS
    WHERE PS.ATIVO = TRUE
      AND STR_TO_DATE(CONCAT(PS.ANO, '-', LPAD(PS.MES, 2, '0'), '-01'), '%Y-%m-%d') >= DATE_SUB(DATE_FORMAT(GREATEST(DATE_SUB(CURRENT_DATE, INTERVAL (DAYOFMONTH(CURRENT_DATE) - 1) DAY), DATE_SUB(CURRENT_DATE, INTERVAL ((WEEKDAY(CURRENT_DATE) + 3) % 7) DAY)), '%Y-%m-01'), INTERVAL 2 MONTH)
    GROUP BY PS.CLIENTE_ID
  ) BASE
),
PERIODO_ANTERIOR AS (
  SELECT
    CASE WHEN P.MES_REF = 1 THEN 12 ELSE P.MES_REF - 1 END AS MES_ANT,
    CASE WHEN P.MES_REF = 1 THEN P.ANO_REF - 1 ELSE P.ANO_REF END AS ANO_ANT
  FROM PARAMS P
),
COORD AS (
  SELECT C.COD_SUPERVISOR
  FROM COORDENADORES C
  WHERE C.USER_ID = :VAR_USER
    AND COALESCE(C.ATIVO, TRUE) = TRUE
  LIMIT 1
),
-- CORRECAO: flag de diretoria/admin do usuario logado, para liberar SELLER e o escopo.
IS_DIRETORIA AS (
  SELECT 1 AS OK
  FROM INT_USER U
  LEFT JOIN USUARIO_CARGO UC ON UC.USER_ID = U.ID
  WHERE U.ID = :VAR_USER
    AND (
      UPPER(COALESCE(UC.CARGO, '')) IN ('ADMIN', 'DIRETORIA')
      OR LOWER(COALESCE(U.DESCR, '')) = 'ti@benenutri.com'
    )
  LIMIT 1
),
ESCOPO_COORD AS (
  SELECT DISTINCT TRIM(CAST(CB.CODFILIAL AS CHAR)) AS CODFILIAL, TRIM(CAST(CB.CODEPTO AS CHAR)) AS CODEPTO
  FROM COORDENADORES_BU CB
  JOIN COORD C ON C.COD_SUPERVISOR = CB.COD_SUPERVISOR
),
GLOBAL_SCOPE_USERS AS (
  SELECT DISTINCT BV.VENDEDOR_ID AS TARGET_USER_ID
  FROM PARAMS P
  JOIN INT_USER U ON U.ID = :VAR_USER
  LEFT JOIN USUARIO_CARGO UC ON UC.USER_ID = U.ID
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE P.SCOPE_MODE = 'GLOBAL'
    AND (
      UPPER(COALESCE(UC.CARGO, '')) IN ('ADMIN', 'DIRETORIA')
      OR LOWER(COALESCE(U.DESCR, '')) = 'ti@benenutri.com'
    )
    AND (
      P.SCOPE_COD_SUPERVISOR IS NULL
      OR EXISTS (
        SELECT 1
        FROM COORDENADORES_BU CB_GLOBAL
        WHERE CB_GLOBAL.COD_SUPERVISOR = P.SCOPE_COD_SUPERVISOR
          AND TRIM(CAST(BV.CODFILIAL AS CHAR)) = CAST(CB_GLOBAL.CODFILIAL AS CHAR)
          AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB_GLOBAL.CODEPTO AS CHAR)
      )
    )
),
COORD_SCOPE_USERS AS (
  SELECT DISTINCT BV.VENDEDOR_ID AS TARGET_USER_ID
  FROM BU_VENDEDOR BV
  JOIN ESCOPO_COORD EC
    ON TRIM(CAST(BV.CODFILIAL AS CHAR)) = EC.CODFILIAL
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = EC.CODEPTO
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND NOT EXISTS (
      SELECT 1
      FROM COORDENADORES C_COORD_ALVO
      WHERE C_COORD_ALVO.USER_ID = BV.VENDEDOR_ID
        AND COALESCE(C_COORD_ALVO.ATIVO, TRUE) = TRUE
        AND C_COORD_ALVO.USER_ID <> :VAR_USER
    )
),
CLIENTES_RAMO AS (
  SELECT
    CAST(ICT.CODCLI AS CHAR) AS CODCLI,
    COALESCE(MAX(NULLIF(TRIM(CAST(ICT.RAMO AS CHAR)), '')), 'Sem ramo') AS RAMO_CLIENTE
  FROM IMP_CLIENTES_TOTVS ICT
  GROUP BY CAST(ICT.CODCLI AS CHAR)
),
TARGET AS (
  SELECT DISTINCT TARGET_USER_ID
  FROM (
    SELECT :VAR_USER AS TARGET_USER_ID
    FROM PARAMS P
    WHERE P.SCOPE_MODE = 'ME'
       OR NOT EXISTS (SELECT 1 FROM COORD)
    UNION ALL
    -- CORRECAO: diretoria/admin pode selecionar qualquer vendedor no modo SELLER.
    SELECT P.TARGET_USER_ID
    FROM PARAMS P
    WHERE P.SCOPE_MODE = 'SELLER'
      AND (
        P.TARGET_USER_ID = :VAR_USER
        OR EXISTS (SELECT 1 FROM COORD_SCOPE_USERS CSU WHERE CSU.TARGET_USER_ID = P.TARGET_USER_ID)
        OR EXISTS (SELECT 1 FROM IS_DIRETORIA)
      )
    UNION ALL
    SELECT CSU.TARGET_USER_ID
    FROM COORD_SCOPE_USERS CSU
    JOIN PARAMS P ON P.SCOPE_MODE = 'TEAM'
    UNION ALL
    SELECT GSU.TARGET_USER_ID
    FROM GLOBAL_SCOPE_USERS GSU
  ) BASE
),
CARTEIRA AS (
  SELECT DISTINCT
    EC.ID_CLIENTE,
    T.TARGET_USER_ID
  FROM TARGET T
  JOIN EQUIPE_CLIENTE EC ON EC.ID_VENDEDOR = T.TARGET_USER_ID
  LEFT JOIN FUNCIONARIOS F ON F.ID = EC.ID_VENDEDOR
  WHERE (EC.ID_VENDEDOR = T.TARGET_USER_ID OR F.ID_SUBSTITUTO = T.TARGET_USER_ID)
),
VENDEDOR_ESCOPO AS (
  SELECT DISTINCT
    T.TARGET_USER_ID,
    BV.CODFILIAL,
    BV.BU_CODIGO AS CODEPTO,
    BV.ID_SECAO
  FROM TARGET T
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = T.TARGET_USER_ID
  JOIN PARAMS P ON 1 = 1
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (
      P.SCOPE_MODE = 'ME'
      OR NOT EXISTS (SELECT 1 FROM COORD)
      -- CORRECAO: diretoria/admin (mesmo que tambem seja coordenador) abre o escopo.
      OR EXISTS (SELECT 1 FROM IS_DIRETORIA)
      OR EXISTS (
        SELECT 1
        FROM ESCOPO_COORD EC
        WHERE TRIM(CAST(BV.CODFILIAL AS CHAR)) = EC.CODFILIAL
          AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = EC.CODEPTO
      )
    )
    AND (P.FILIAL_PARAM IS NULL OR FIND_IN_SET(TRIM(CAST(BV.CODFILIAL AS CHAR)), REPLACE(P.FILIAL_PARAM, '|', ',')) > 0)
    AND (P.DEPTO_PARAM IS NULL OR FIND_IN_SET(TRIM(CAST(BV.BU_CODIGO AS CHAR)), REPLACE(P.DEPTO_PARAM, '|', ',')) > 0)
    AND (P.SECAO_PARAM IS NULL OR FIND_IN_SET(TRIM(CAST(BV.ID_SECAO AS CHAR)), REPLACE(P.SECAO_PARAM, '|', ',')) > 0)
),
BASE_ATUAL AS (
  SELECT
    CASE WHEN P.SCOPE_MODE IN ('TEAM','GLOBAL') THEN 0 ELSE E.TARGET_USER_ID END AS VENDEDOR_ID,
    PS.CLIENTE_ID,
    PS.SEGMENTO,
    PS.SEMANA_NUMERO,
    PS.VALOR,
    COALESCE(CR.RAMO_CLIENTE, 'Sem ramo') AS RAMO_CLIENTE_FILTRADO
  FROM PEDIDOS_SEMANAIS_SYNC_OPERACIONAL PS
  JOIN PARAMS P ON 1 = 1
  JOIN CARTEIRA C ON C.ID_CLIENTE = PS.CLIENTE_ID
  JOIN VENDEDOR_ESCOPO E ON E.TARGET_USER_ID = C.TARGET_USER_ID
    AND TRIM(CAST(E.CODFILIAL AS CHAR)) = TRIM(CAST(PS.CODFILIAL AS CHAR))
    AND TRIM(CAST(E.CODEPTO AS CHAR)) = TRIM(CAST(PS.CODEPTO AS CHAR))
    AND (
      E.ID_SECAO IS NULL
      OR TRIM(CAST(E.ID_SECAO AS CHAR)) = TRIM(CAST(PS.ID_SECAO AS CHAR))
      OR LPAD(TRIM(CAST(E.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(PS.ID_SECAO AS CHAR))
    )
  LEFT JOIN CLIENTES C_FILTRO ON C_FILTRO.ID = PS.CLIENTE_ID
  LEFT JOIN CLIENTES_RAMO CR ON CR.CODCLI = CAST(COALESCE(C_FILTRO.WINTHOR_CODCLI, C_FILTRO.ID, PS.CLIENTE_ID) AS CHAR)
  WHERE PS.ATIVO = TRUE
    AND PS.ANO = P.ANO_REF
    AND PS.MES = P.MES_REF
    AND ('{{ramoCliente}}' = '' OR FIND_IN_SET(UPPER(COALESCE(CR.RAMO_CLIENTE, 'Sem ramo')), UPPER(REPLACE('{{ramoCliente}}', '|', ','))) > 0)
    AND (P.CLIENTE_PARAM IS NULL OR FIND_IN_SET(CAST(COALESCE(C_FILTRO.WINTHOR_CODCLI, C_FILTRO.ID, PS.CLIENTE_ID) AS CHAR), P.CLIENTE_PARAM) > 0)
),
BASE_ANTERIOR AS (
  SELECT
    CASE WHEN P.SCOPE_MODE IN ('TEAM','GLOBAL') THEN 0 ELSE E.TARGET_USER_ID END AS VENDEDOR_ID,
    PS.CLIENTE_ID,
    PS.SEMANA_NUMERO,
    PS.VALOR
  FROM PEDIDOS_SEMANAIS_SYNC_OPERACIONAL PS
  JOIN PARAMS P ON 1 = 1
  JOIN PERIODO_ANTERIOR PA ON 1 = 1
  JOIN CARTEIRA C ON C.ID_CLIENTE = PS.CLIENTE_ID
  JOIN VENDEDOR_ESCOPO E ON E.TARGET_USER_ID = C.TARGET_USER_ID
    AND TRIM(CAST(E.CODFILIAL AS CHAR)) = TRIM(CAST(PS.CODFILIAL AS CHAR))
    AND TRIM(CAST(E.CODEPTO AS CHAR)) = TRIM(CAST(PS.CODEPTO AS CHAR))
    AND (
      E.ID_SECAO IS NULL
      OR TRIM(CAST(E.ID_SECAO AS CHAR)) = TRIM(CAST(PS.ID_SECAO AS CHAR))
      OR LPAD(TRIM(CAST(E.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(PS.ID_SECAO AS CHAR))
    )
  LEFT JOIN CLIENTES C_FILTRO ON C_FILTRO.ID = PS.CLIENTE_ID
  LEFT JOIN CLIENTES_RAMO CR ON CR.CODCLI = CAST(COALESCE(C_FILTRO.WINTHOR_CODCLI, C_FILTRO.ID, PS.CLIENTE_ID) AS CHAR)
  WHERE PS.ATIVO = TRUE
    AND PS.MES = PA.MES_ANT
    AND PS.ANO = PA.ANO_ANT
    AND ('{{ramoCliente}}' = '' OR FIND_IN_SET(UPPER(COALESCE(CR.RAMO_CLIENTE, 'Sem ramo')), UPPER(REPLACE('{{ramoCliente}}', '|', ','))) > 0)
    AND (P.CLIENTE_PARAM IS NULL OR FIND_IN_SET(CAST(COALESCE(C_FILTRO.WINTHOR_CODCLI, C_FILTRO.ID, PS.CLIENTE_ID) AS CHAR), P.CLIENTE_PARAM) > 0)
),
BASE_CLIENTES AS (
  SELECT VENDEDOR_ID, CLIENTE_ID, MAX(SEGMENTO) AS SEGMENTO, MAX(RAMO_CLIENTE_FILTRADO) AS RAMO_CLIENTE
  FROM BASE_ATUAL
  GROUP BY VENDEDOR_ID, CLIENTE_ID
),
SEMANAS_MES AS (
  SELECT
    VENDEDOR_ID,
    CLIENTE_ID,
    SUM(CASE WHEN SEMANA_NUMERO = 1 THEN VALOR ELSE 0 END) AS SEM_1,
    SUM(CASE WHEN SEMANA_NUMERO = 2 THEN VALOR ELSE 0 END) AS SEM_2,
    SUM(CASE WHEN SEMANA_NUMERO = 3 THEN VALOR ELSE 0 END) AS SEM_3,
    SUM(CASE WHEN SEMANA_NUMERO = 4 THEN VALOR ELSE 0 END) AS SEM_4,
    SUM(CASE WHEN SEMANA_NUMERO = 5 THEN VALOR ELSE 0 END) AS SEM_5,
    SUM(CASE WHEN SEMANA_NUMERO = 6 THEN VALOR ELSE 0 END) AS SEM_6,
    SUM(VALOR) AS FECHAMENTO_MES
  FROM BASE_ATUAL
  GROUP BY VENDEDOR_ID, CLIENTE_ID
),
SEMANAS_ANTERIOR AS (
  SELECT
    VENDEDOR_ID,
    CLIENTE_ID,
    SUM(CASE WHEN SEMANA_NUMERO = 1 THEN VALOR ELSE 0 END) AS SEM_1_ANT,
    SUM(CASE WHEN SEMANA_NUMERO = 2 THEN VALOR ELSE 0 END) AS SEM_2_ANT,
    SUM(CASE WHEN SEMANA_NUMERO = 3 THEN VALOR ELSE 0 END) AS SEM_3_ANT,
    SUM(CASE WHEN SEMANA_NUMERO = 4 THEN VALOR ELSE 0 END) AS SEM_4_ANT,
    SUM(CASE WHEN SEMANA_NUMERO = 5 THEN VALOR ELSE 0 END) AS SEM_5_ANT,
    SUM(CASE WHEN SEMANA_NUMERO = 6 THEN VALOR ELSE 0 END) AS SEM_6_ANT,
    SUM(VALOR) AS FECHAMENTO_MES_ANTERIOR
  FROM BASE_ANTERIOR
  GROUP BY VENDEDOR_ID, CLIENTE_ID
),
SEMANA_ATUAL AS (
  SELECT VENDEDOR_ID, CLIENTE_ID, SUM(VALOR) AS VALOR_ATUAL
  FROM BASE_ATUAL
  WHERE SEMANA_NUMERO = (SELECT SEMANA_REF FROM PARAMS)
  GROUP BY VENDEDOR_ID, CLIENTE_ID
),
SEMANA_ANTERIOR AS (
  SELECT VENDEDOR_ID, CLIENTE_ID, SUM(VALOR) AS VALOR_ANTERIOR
  FROM BASE_ANTERIOR
  WHERE SEMANA_NUMERO = (SELECT SEMANA_REF FROM PARAMS)
  GROUP BY VENDEDOR_ID, CLIENTE_ID
)
SELECT
  BC.CLIENTE_ID,
  C.NOME_FANTASIA AS CLIENTE,
  BC.SEGMENTO,
  BC.RAMO_CLIENTE,
  BC.VENDEDOR_ID,
  CASE
    WHEN BC.VENDEDOR_ID = 0 THEN 'Coordenador'
    ELSE COALESCE(NULLIF(TRIM(U.NOME), ''), U.DESCR, CONCAT('Usuario ', BC.VENDEDOR_ID))
  END AS VENDEDOR,
  COALESCE(SM.SEM_1, 0) AS SEM_1,
  CASE WHEN COALESCE(SA3.SEM_1_ANT, 0) = 0 THEN -1 ELSE ROUND((COALESCE(SM.SEM_1, 0) - SA3.SEM_1_ANT) / SA3.SEM_1_ANT, 4) END AS DELTA_BW_SEM_1,
  COALESCE(SM.SEM_2, 0) AS SEM_2,
  CASE WHEN COALESCE(SA3.SEM_2_ANT, 0) = 0 THEN -1 ELSE ROUND((COALESCE(SM.SEM_2, 0) - SA3.SEM_2_ANT) / SA3.SEM_2_ANT, 4) END AS DELTA_BW_SEM_2,
  COALESCE(SM.SEM_3, 0) AS SEM_3,
  CASE WHEN COALESCE(SA3.SEM_3_ANT, 0) = 0 THEN -1 ELSE ROUND((COALESCE(SM.SEM_3, 0) - SA3.SEM_3_ANT) / SA3.SEM_3_ANT, 4) END AS DELTA_BW_SEM_3,
  COALESCE(SM.SEM_4, 0) AS SEM_4,
  CASE WHEN COALESCE(SA3.SEM_4_ANT, 0) = 0 THEN -1 ELSE ROUND((COALESCE(SM.SEM_4, 0) - SA3.SEM_4_ANT) / SA3.SEM_4_ANT, 4) END AS DELTA_BW_SEM_4,
  COALESCE(SM.SEM_5, 0) AS SEM_5,
  CASE WHEN COALESCE(SA3.SEM_5_ANT, 0) = 0 THEN -1 ELSE ROUND((COALESCE(SM.SEM_5, 0) - SA3.SEM_5_ANT) / SA3.SEM_5_ANT, 4) END AS DELTA_BW_SEM_5,
  COALESCE(SM.SEM_6, 0) AS SEM_6,
  CASE WHEN COALESCE(SA3.SEM_6_ANT, 0) = 0 THEN -1 ELSE ROUND((COALESCE(SM.SEM_6, 0) - SA3.SEM_6_ANT) / SA3.SEM_6_ANT, 4) END AS DELTA_BW_SEM_6,
  COALESCE(SM.FECHAMENTO_MES, 0) AS FECHAMENTO_MES,
  COALESCE(SA3.FECHAMENTO_MES_ANTERIOR, 0) AS FECHAMENTO_MES_ANTERIOR,
  CASE
    WHEN COALESCE(SA3.FECHAMENTO_MES_ANTERIOR, 0) = 0 THEN -1
    ELSE ROUND((COALESCE(SM.FECHAMENTO_MES, 0) - SA3.FECHAMENTO_MES_ANTERIOR) / SA3.FECHAMENTO_MES_ANTERIOR, 4)
  END AS DELTA_BW_FECHAMENTO_MES,
  COALESCE(SA.VALOR_ATUAL, 0) AS VALOR_SEMANA_ATUAL,
  SA2.VALOR_ANTERIOR AS VALOR_SEMANA_ANTERIOR,
  CASE
    WHEN SA2.VALOR_ANTERIOR IS NULL OR SA2.VALOR_ANTERIOR = 0 THEN -1
    ELSE ROUND((COALESCE(SA.VALOR_ATUAL, 0) - SA2.VALOR_ANTERIOR) / SA2.VALOR_ANTERIOR, 4)
  END AS DELTA_BW,
  PC.FREQUENCIA,
  PC.SEMANA_PADRAO,
  COALESCE(PC.TICKET_MEDIO_3M, 0) AS TICKET_MEDIO_3M,
  CASE
    WHEN COALESCE(PC.TICKET_MEDIO_3M, 0) >= 15000 THEN 'A'
    WHEN COALESCE(PC.TICKET_MEDIO_3M, 0) >= 7000 THEN 'B'
    ELSE 'C'
  END AS CURVA,
  CASE
    WHEN ((PC.FREQUENCIA = 'SEMANAL' OR PC.SEMANA_PADRAO = (SELECT SEMANA_REF FROM PARAMS)) AND COALESCE(SA.VALOR_ATUAL, 0) = 0) THEN 'Alerta'
    WHEN PC.SEMANA_PADRAO IS NOT NULL
      AND PC.FREQUENCIA <> 'SEMANAL'
      AND PC.SEMANA_PADRAO <> (SELECT SEMANA_REF FROM PARAMS)
      AND COALESCE(SA.VALOR_ATUAL, 0) > 0 THEN 'Fora do padrao'
    ELSE 'No padrao'
  END AS STATUS,
  'Exibindo apenas clientes da carteira do vendedor selecionado' AS NOTA_ESCOPO
FROM BASE_CLIENTES BC
LEFT JOIN CLIENTES C ON C.ID = BC.CLIENTE_ID
LEFT JOIN INT_USER U ON U.ID = BC.VENDEDOR_ID
LEFT JOIN SEMANAS_MES SM ON SM.VENDEDOR_ID = BC.VENDEDOR_ID AND SM.CLIENTE_ID = BC.CLIENTE_ID
LEFT JOIN SEMANAS_ANTERIOR SA3 ON SA3.VENDEDOR_ID = BC.VENDEDOR_ID AND SA3.CLIENTE_ID = BC.CLIENTE_ID
LEFT JOIN SEMANA_ATUAL SA ON SA.VENDEDOR_ID = BC.VENDEDOR_ID AND SA.CLIENTE_ID = BC.CLIENTE_ID
LEFT JOIN SEMANA_ANTERIOR SA2 ON SA2.VENDEDOR_ID = BC.VENDEDOR_ID AND SA2.CLIENTE_ID = BC.CLIENTE_ID
LEFT JOIN PERFIL_COMPRA_CLIENTE_OPERACIONAL PC ON PC.CLIENTE_ID = BC.CLIENTE_ID
ORDER BY VENDEDOR, CLIENTE