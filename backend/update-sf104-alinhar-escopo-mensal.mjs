import 'dotenv/config';
import { configureSdkMitra, updateServerFunctionMitra, readServerFunctionMitra } from 'mitra-sdk';

function decodeTokenPayload(token) {
  try {
    const raw = String(token || '').replace(/^Bearer\s+/i, '');
    const parts = raw.split('.');
    if (parts.length < 2) return null;
    const normalized = parts[1].replace(/-/g, '+').replace(/_/g, '/');
    const padded = normalized + '='.repeat((4 - (normalized.length % 4)) % 4);
    return JSON.parse(Buffer.from(padded, 'base64').toString('utf8'));
  } catch {
    return null;
  }
}

const tokenPayload = decodeTokenPayload(process.env.MITRA_TOKEN);
const baseURL = process.env.MITRA_BASE_URL || tokenPayload?.backURL || process.env.MITRA_BASE_URL_SPACE;
const integrationURL = process.env.MITRA_BASE_URL_INTEGRATIONS || baseURL;

configureSdkMitra({
  baseURL,
  token: process.env.MITRA_TOKEN,
  integrationURL,
});

const projectId = Number(process.env.MITRA_PROJECT_ID);

const SF104_CODE = `
WITH INPUTS AS (
  SELECT
    CASE
      WHEN '{{mes}}' REGEXP '^[0-9]{1,2}$' THEN CAST('{{mes}}' AS UNSIGNED)
      ELSE MONTH(CURRENT_DATE)
    END AS MES_REF,
    CASE
      WHEN '{{ano}}' REGEXP '^[0-9]{4}$' THEN CAST('{{ano}}' AS UNSIGNED)
      ELSE YEAR(CURRENT_DATE)
    END AS ANO_REF,
    CASE
      WHEN '{{semanaNumero}}' REGEXP '^[0-9]{1,2}$' THEN CAST('{{semanaNumero}}' AS UNSIGNED)
      ELSE CEIL(DAY(CURRENT_DATE) / 7)
    END AS SEMANA_REF,
    CASE
      WHEN '{{vendedorId}}' REGEXP '^[0-9]+$' THEN CAST('{{vendedorId}}' AS UNSIGNED)
      ELSE NULL
    END AS VENDEDOR_PARAM,
    CASE
      WHEN '{{segmento}}' = '' OR LOCATE('{', '{{segmento}}') > 0 THEN NULL
      ELSE UPPER('{{segmento}}')
    END AS SEGMENTO_PARAM,
    CASE
      WHEN '{{codFilial}}' = '' OR LOCATE('{', '{{codFilial}}') > 0 THEN NULL
      ELSE '{{codFilial}}'
    END AS CODFILIAL_PARAM,
    CASE
      WHEN '{{idSecao}}' REGEXP '^-?[0-9]+$' THEN CAST('{{idSecao}}' AS SIGNED)
      ELSE NULL
    END AS IDSECAO_PARAM
),
PERMISSAO AS (
  SELECT
    CASE
      WHEN EXISTS (
        SELECT 1
        FROM USUARIO_CARGO UC
        WHERE UC.USER_ID = :VAR_USER
          AND UC.CARGO IN ('GESTOR', 'ADMIN')
      ) THEN 1
      ELSE 0
    END AS EH_GESTAO
),
TARGET_USERS AS (
  SELECT DISTINCT BASE.USER_ID
  FROM (
    SELECT
      CASE
        WHEN P.EH_GESTAO = 1 AND I.VENDEDOR_PARAM IS NOT NULL THEN I.VENDEDOR_PARAM
        WHEN P.EH_GESTAO = 1 AND I.VENDEDOR_PARAM IS NULL THEN VR.USER_ID
        ELSE :VAR_USER
      END AS USER_ID
    FROM INPUTS I
    CROSS JOIN PERMISSAO P
    LEFT JOIN VENDEDOR_RCA VR ON P.EH_GESTAO = 1 AND I.VENDEDOR_PARAM IS NULL
  ) BASE
  WHERE BASE.USER_ID IS NOT NULL
),
PERIODO_ANTERIOR AS (
  SELECT
    CASE WHEN I.MES_REF = 1 THEN 12 ELSE I.MES_REF - 1 END AS MES_ANT,
    CASE WHEN I.MES_REF = 1 THEN I.ANO_REF - 1 ELSE I.ANO_REF END AS ANO_ANT
  FROM INPUTS I
),
CARTEIRA_SCOPE_RAW AS (
  SELECT
    TU.USER_ID AS TARGET_USER_ID,
    EC.ID_CLIENTE,
    EC.ID_VENDEDOR
  FROM TARGET_USERS TU
  JOIN EQUIPE_CLIENTE EC ON 1 = 1
  LEFT JOIN FUNCIONARIOS F ON F.ID = EC.ID_VENDEDOR
  WHERE (EC.ID_VENDEDOR = TU.USER_ID OR F.ID_SUBSTITUTO = TU.USER_ID)
),
CARTEIRA_SCOPE AS (
  SELECT
    BASE.TARGET_USER_ID,
    BASE.ID_CLIENTE,
    BASE.ID_VENDEDOR AS VENDEDOR_DONO_CLIENTE
  FROM (
    SELECT
      CSR.TARGET_USER_ID,
      CSR.ID_CLIENTE,
      CSR.ID_VENDEDOR,
      ROW_NUMBER() OVER (
        PARTITION BY CSR.TARGET_USER_ID, CSR.ID_CLIENTE
        ORDER BY
          CASE WHEN CSR.ID_VENDEDOR = CSR.TARGET_USER_ID THEN 0 ELSE 1 END,
          CSR.ID_VENDEDOR
      ) AS RN
    FROM CARTEIRA_SCOPE_RAW CSR
  ) BASE
  WHERE BASE.RN = 1
),
CURVA_MANUAL AS (
  SELECT
    CS.TARGET_USER_ID AS VENDEDOR_ID,
    CS.ID_CLIENTE,
    MAX(UPPER(TRIM(COALESCE(EC.CURVA_CLASSIFICACAO, '')))) AS CURVA_MANUAL
  FROM CARTEIRA_SCOPE CS
  JOIN EQUIPE_CLIENTE EC
    ON EC.ID_CLIENTE = CS.ID_CLIENTE
   AND EC.ID_VENDEDOR = CS.VENDEDOR_DONO_CLIENTE
  WHERE COALESCE(NULLIF(TRIM(EC.CURVA_CLASSIFICACAO), ''), '') <> ''
  GROUP BY CS.TARGET_USER_ID, CS.ID_CLIENTE
),
RCA_SCOPE AS (
  SELECT DISTINCT
    TU.USER_ID AS TARGET_USER_ID,
    VR.COD_RCA
  FROM TARGET_USERS TU
  JOIN VENDEDOR_RCA VR ON VR.USER_ID = TU.USER_ID

  UNION

  SELECT DISTINCT
    TU.USER_ID AS TARGET_USER_ID,
    VR.COD_RCA
  FROM TARGET_USERS TU
  JOIN FUNCIONARIOS F ON F.ID_SUBSTITUTO = TU.USER_ID
  JOIN VENDEDOR_RCA VR ON VR.USER_ID = F.ID
),
ESCOPO_RCA_DEPTO AS (
  SELECT DISTINCT
    RS.TARGET_USER_ID,
    RD.COD_RCA,
    TRIM(CAST(RD.COD_DEPARTAMENTO AS CHAR)) AS CODEPTO
  FROM RCA_SCOPE RS
  JOIN RCA_DEPARTAMENTO RD ON RD.COD_RCA = RS.COD_RCA
  WHERE COALESCE(RD.ATIVO, TRUE) = TRUE
),
BASE_ATUAL_RAW AS (
  SELECT
    CS.TARGET_USER_ID AS VENDEDOR_ID,
    R.CLIENTE_ID,
    MAX(R.SEGMENTO) AS SEGMENTO,
    R.SEMANA_NUMERO,
    ROUND(SUM(COALESCE(R.TOTAL, 0)), 2) AS VALOR
  FROM PEDIDOS_SEMANAIS_SYNC_RAW R
  JOIN INPUTS I ON 1 = 1
  JOIN CARTEIRA_SCOPE CS ON CS.ID_CLIENTE = R.CLIENTE_ID
  JOIN ESCOPO_RCA_DEPTO E ON E.TARGET_USER_ID = CS.TARGET_USER_ID
    AND E.COD_RCA = R.COD_RCA
    AND E.CODEPTO = TRIM(CAST(R.CODEPTO AS CHAR))
  WHERE R.ATIVO = TRUE
    AND R.STATUS_INGESTAO = 'ATIVO'
    AND R.ANO = I.ANO_REF
    AND R.MES = I.MES_REF
    AND (I.SEGMENTO_PARAM IS NULL OR UPPER(R.SEGMENTO) = I.SEGMENTO_PARAM)
    AND (I.CODFILIAL_PARAM IS NULL OR R.CODFILIAL = I.CODFILIAL_PARAM)
    AND (I.IDSECAO_PARAM IS NULL OR R.ID_SECAO = I.IDSECAO_PARAM)
  GROUP BY CS.TARGET_USER_ID, R.CLIENTE_ID, R.SEMANA_NUMERO
),
BASE_CLIENTES AS (
  SELECT
    VENDEDOR_ID,
    CLIENTE_ID,
    MAX(SEGMENTO) AS SEGMENTO
  FROM BASE_ATUAL_RAW
  GROUP BY VENDEDOR_ID, CLIENTE_ID
),
SEMANAS_MES AS (
  SELECT
    VENDEDOR_ID,
    CLIENTE_ID,
    SUM(CASE WHEN SEMANA_NUMERO = 1 THEN VALOR ELSE 0 END) AS SEM_1,
    SUM(CASE WHEN SEMANA_NUMERO = 2 THEN VALOR ELSE 0 END) AS SEM_2,
    SUM(CASE WHEN SEMANA_NUMERO = 3 THEN VALOR ELSE 0 END) AS SEM_3,
    SUM(CASE WHEN SEMANA_NUMERO = 4 THEN VALOR ELSE 0 END) AS SEM_4,
    SUM(CASE WHEN SEMANA_NUMERO = 5 THEN VALOR ELSE 0 END) AS SEM_5,
    SUM(VALOR) AS FECHAMENTO_MES
  FROM BASE_ATUAL_RAW
  GROUP BY VENDEDOR_ID, CLIENTE_ID
),
SEMANA_ATUAL AS (
  SELECT
    BAR.VENDEDOR_ID,
    BAR.CLIENTE_ID,
    SUM(BAR.VALOR) AS VALOR_ATUAL
  FROM BASE_ATUAL_RAW BAR
  JOIN INPUTS I ON 1 = 1
  WHERE BAR.SEMANA_NUMERO = I.SEMANA_REF
  GROUP BY BAR.VENDEDOR_ID, BAR.CLIENTE_ID
),
BASE_ANTERIOR_RAW AS (
  SELECT
    CS.TARGET_USER_ID AS VENDEDOR_ID,
    R.CLIENTE_ID,
    ROUND(SUM(COALESCE(R.TOTAL, 0)), 2) AS VALOR_ANTERIOR
  FROM PEDIDOS_SEMANAIS_SYNC_RAW R
  JOIN INPUTS I ON 1 = 1
  JOIN PERIODO_ANTERIOR PA ON 1 = 1
  JOIN CARTEIRA_SCOPE CS ON CS.ID_CLIENTE = R.CLIENTE_ID
  JOIN ESCOPO_RCA_DEPTO E ON E.TARGET_USER_ID = CS.TARGET_USER_ID
    AND E.COD_RCA = R.COD_RCA
    AND E.CODEPTO = TRIM(CAST(R.CODEPTO AS CHAR))
  WHERE R.ATIVO = TRUE
    AND R.STATUS_INGESTAO = 'ATIVO'
    AND R.ANO = PA.ANO_ANT
    AND R.MES = PA.MES_ANT
    AND R.SEMANA_NUMERO = I.SEMANA_REF
    AND (I.SEGMENTO_PARAM IS NULL OR UPPER(R.SEGMENTO) = I.SEGMENTO_PARAM)
    AND (I.CODFILIAL_PARAM IS NULL OR R.CODFILIAL = I.CODFILIAL_PARAM)
    AND (I.IDSECAO_PARAM IS NULL OR R.ID_SECAO = I.IDSECAO_PARAM)
  GROUP BY CS.TARGET_USER_ID, R.CLIENTE_ID
)
SELECT
  BC.CLIENTE_ID,
  C.NOME_FANTASIA AS CLIENTE,
  BC.SEGMENTO,
  BC.VENDEDOR_ID,
  COALESCE(NULLIF(TRIM(F.NOME), ''), NULLIF(TRIM(U.NOME), ''), U.DESCR, CONCAT('Usuario ', BC.VENDEDOR_ID)) AS VENDEDOR,
  COALESCE(SM.SEM_1, 0) AS SEM_1,
  COALESCE(SM.SEM_2, 0) AS SEM_2,
  COALESCE(SM.SEM_3, 0) AS SEM_3,
  COALESCE(SM.SEM_4, 0) AS SEM_4,
  COALESCE(SM.SEM_5, 0) AS SEM_5,
  COALESCE(SM.FECHAMENTO_MES, 0) AS FECHAMENTO_MES,
  COALESCE(SA.VALOR_ATUAL, 0) AS VALOR_SEMANA_ATUAL,
  SA2.VALOR_ANTERIOR AS VALOR_SEMANA_ANTERIOR,
  CASE
    WHEN SA2.VALOR_ANTERIOR IS NULL OR SA2.VALOR_ANTERIOR = 0 THEN -1
    ELSE ROUND((COALESCE(SA.VALOR_ATUAL, 0) - SA2.VALOR_ANTERIOR) / SA2.VALOR_ANTERIOR, 4)
  END AS DELTA_BW,
  PC.FREQUENCIA,
  PC.SEMANA_PADRAO,
  COALESCE(PC.TICKET_MEDIO_3M, 0) AS TICKET_MEDIO_3M,
  COALESCE(
    CM.CURVA_MANUAL,
    CASE
      WHEN COALESCE(PC.TICKET_MEDIO_3M, 0) >= 15000 THEN 'A'
      WHEN COALESCE(PC.TICKET_MEDIO_3M, 0) >= 7000 THEN 'B'
      ELSE 'C'
    END
  ) AS CURVA,
  CASE
    WHEN ((PC.FREQUENCIA = 'SEMANAL' OR PC.SEMANA_PADRAO = (SELECT SEMANA_REF FROM INPUTS)) AND COALESCE(SA.VALOR_ATUAL, 0) = 0) THEN 'Alerta'
    WHEN PC.SEMANA_PADRAO IS NOT NULL
      AND PC.FREQUENCIA <> 'SEMANAL'
      AND PC.SEMANA_PADRAO <> (SELECT SEMANA_REF FROM INPUTS)
      AND COALESCE(SA.VALOR_ATUAL, 0) > 0 THEN 'Fora do padrao'
    ELSE 'No padrao'
  END AS STATUS,
  'Escopo semanal robusto: carteira + COD_RCA + departamento por vendedor alvo' AS NOTA_ESCOPO
FROM BASE_CLIENTES BC
LEFT JOIN CLIENTES C ON C.ID = BC.CLIENTE_ID
LEFT JOIN FUNCIONARIOS F ON F.ID = BC.VENDEDOR_ID
LEFT JOIN INT_USER U ON U.ID = BC.VENDEDOR_ID
LEFT JOIN CURVA_MANUAL CM ON CM.VENDEDOR_ID = BC.VENDEDOR_ID AND CM.ID_CLIENTE = BC.CLIENTE_ID
LEFT JOIN SEMANAS_MES SM ON SM.VENDEDOR_ID = BC.VENDEDOR_ID AND SM.CLIENTE_ID = BC.CLIENTE_ID
LEFT JOIN SEMANA_ATUAL SA ON SA.VENDEDOR_ID = BC.VENDEDOR_ID AND SA.CLIENTE_ID = BC.CLIENTE_ID
LEFT JOIN BASE_ANTERIOR_RAW SA2 ON SA2.VENDEDOR_ID = BC.VENDEDOR_ID AND SA2.CLIENTE_ID = BC.CLIENTE_ID
LEFT JOIN PERFIL_COMPRA_CLIENTE PC ON PC.CLIENTE_ID = BC.CLIENTE_ID
ORDER BY VENDEDOR, CLIENTE
`;

async function main() {
  const current = await readServerFunctionMitra({ projectId, serverFunctionId: 104 });
  await updateServerFunctionMitra({
    projectId,
    serverFunctionId: 104,
    code: SF104_CODE,
    description: current?.result?.description || 'Calcula B/W semanal com escopo alinhado ao mensal',
  });

  console.log('SF 104 atualizada com escopo alinhado a SF 2 (mensal).');
}

main().catch((error) => {
  console.error('Falha ao atualizar SF 104:');
  console.error(error?.message || error);
  process.exit(1);
});
