import 'dotenv/config';
import {
  configureSdkMitra,
  executeServerFunctionMitra,
  readServerFunctionMitra,
  updateServerFunctionMitra,
} from 'mitra-sdk';

configureSdkMitra({
  baseURL: process.env.MITRA_BASE_URL,
  token: process.env.MITRA_TOKEN,
  integrationURL: process.env.MITRA_BASE_URL_INTEGRATIONS,
});

const projectId = Number(process.env.MITRA_PROJECT_ID);
const serverFunctionId = 214;

const RAW_SECTION_MATCH = `
  B.CODFILIAL = TRIM(COALESCE(CAST(R.CODFILIAL AS CHAR), ''))
  AND B.CODEPTO = TRIM(CAST(R.CODEPTO AS CHAR))
  AND (
    (
      B.ID_SECAO IS NOT NULL
      AND (
        TRIM(CAST(B.ID_SECAO AS CHAR)) = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
        OR LPAD(TRIM(CAST(B.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
      )
    )
    OR (
      B.ID_SECAO IS NULL
      AND NOT EXISTS (
        SELECT 1
        FROM BU_SCOPE B2
        WHERE B2.TARGET_USER_ID = B.TARGET_USER_ID
          AND B2.CODFILIAL = B.CODFILIAL
          AND B2.CODEPTO = B.CODEPTO
          AND B2.ID_SECAO IS NOT NULL
          AND (
            TRIM(CAST(B2.ID_SECAO AS CHAR)) = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
            OR LPAD(TRIM(CAST(B2.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
          )
      )
    )
  )
`;

const DEV_SECTION_MATCH = `
  B.CODFILIAL = TRIM(COALESCE(CAST(D.CODFILIAL AS CHAR), ''))
  AND B.CODEPTO = TRIM(CAST(D.CODEPTO AS CHAR))
  AND (
    (
      B.ID_SECAO IS NOT NULL
      AND (
        TRIM(CAST(B.ID_SECAO AS CHAR)) = TRIM(CAST(D.CODSEC AS CHAR))
        OR LPAD(TRIM(CAST(B.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(D.CODSEC AS CHAR))
      )
    )
    OR (
      B.ID_SECAO IS NULL
      AND NOT EXISTS (
        SELECT 1
        FROM BU_SCOPE B2
        WHERE B2.TARGET_USER_ID = B.TARGET_USER_ID
          AND B2.CODFILIAL = B.CODFILIAL
          AND B2.CODEPTO = B.CODEPTO
          AND B2.ID_SECAO IS NOT NULL
          AND (
            TRIM(CAST(B2.ID_SECAO AS CHAR)) = TRIM(CAST(D.CODSEC AS CHAR))
            OR LPAD(TRIM(CAST(B2.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(D.CODSEC AS CHAR))
          )
      )
    )
  )
`;

const RAW_CARTEIRA_MATCH = `
  CS.TARGET_USER_ID = B.TARGET_USER_ID
  AND (
    (R.CLIENTE_ID IS NOT NULL AND CS.CLIENTE_ID = R.CLIENTE_ID)
    OR TRIM(CAST(CS.CODCLI AS CHAR)) = TRIM(CAST(R.CODCLI AS CHAR))
  )
`;

const DEV_CARTEIRA_MATCH = `
  CS.TARGET_USER_ID = B.TARGET_USER_ID
  AND TRIM(CAST(CS.CODCLI AS CHAR)) = TRIM(CAST(D.CODCLI AS CHAR))
`;

const code = `WITH
INPUT_SCOPE AS (
  SELECT
    CASE WHEN '{{scopeMode}}' IN ('TEAM', 'SELLER', 'GLOBAL') THEN '{{scopeMode}}' ELSE 'ME' END AS SCOPE_MODE,
    CASE WHEN '{{scopeUserId}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeUserId}}' AS UNSIGNED) ELSE NULL END AS SCOPE_USER_ID,
    CASE WHEN '{{scopeCodRca}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeCodRca}}' AS UNSIGNED) ELSE NULL END AS SCOPE_COD_RCA,
    CASE WHEN '{{scopeCodFilial}}' = '' OR LOCATE('{', '{{scopeCodFilial}}') > 0 THEN NULL ELSE TRIM('{{scopeCodFilial}}') END AS SCOPE_CODFILIAL,
    CASE WHEN '{{scopeCodepto}}' = '' OR LOCATE('{', '{{scopeCodepto}}') > 0 THEN NULL ELSE TRIM('{{scopeCodepto}}') END AS SCOPE_CODEPTO,
    CASE WHEN '{{scopeIdSecao}}' = '' OR LOCATE('{', '{{scopeIdSecao}}') > 0 THEN NULL ELSE TRIM('{{scopeIdSecao}}') END AS SCOPE_ID_SECAO,
    CASE WHEN '{{scopeCodSupervisor}}' REGEXP '^[0-9]+$' THEN CAST('{{scopeCodSupervisor}}' AS UNSIGNED) ELSE NULL END AS SCOPE_COD_SUPERVISOR
),
TARGET_USERS AS (
  SELECT :VAR_USER AS USER_ID
  FROM INPUT_SCOPE I
  WHERE I.SCOPE_MODE = 'ME'

  UNION

  SELECT F.ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN FUNCIONARIOS F ON F.ID_SUBSTITUTO = :VAR_USER
  WHERE I.SCOPE_MODE = 'ME'

  UNION

  SELECT VR_DONO.USER_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN VENDEDOR_RCA VR_SUB ON VR_SUB.USER_ID = :VAR_USER
  JOIN FERIAS_VENDEDOR FV ON FV.COD_RCA_SUBSTITUTO = VR_SUB.COD_RCA
  JOIN VENDEDOR_RCA VR_DONO ON VR_DONO.COD_RCA = FV.COD_RCA
  WHERE I.SCOPE_MODE = 'ME'
    AND COALESCE(FV.ATIVO, TRUE) = TRUE
    AND CURRENT_DATE BETWEEN FV.DT_INICIO AND FV.DT_FIM

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN COORDENADORES C ON C.USER_ID = :VAR_USER AND COALESCE(C.ATIVO, TRUE) = TRUE
  JOIN COORDENADORES_BU CB ON CB.COD_SUPERVISOR = C.COD_SUPERVISOR
  JOIN BU_VENDEDOR BV
    ON TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB.CODFILIAL AS CHAR)
   AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB.CODEPTO AS CHAR)
  WHERE I.SCOPE_MODE = 'TEAM'
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  LEFT JOIN VENDEDOR_RCA VR ON VR.USER_ID = BV.VENDEDOR_ID
  WHERE I.SCOPE_MODE = 'SELLER'
    AND (BV.VENDEDOR_ID = I.SCOPE_USER_ID OR VR.COD_RCA = I.SCOPE_COD_RCA)
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )

  UNION

  SELECT DISTINCT BV.VENDEDOR_ID AS USER_ID
  FROM INPUT_SCOPE I
  JOIN INT_USER U ON U.ID = :VAR_USER
  LEFT JOIN USUARIO_CARGO UC ON UC.USER_ID = U.ID
  JOIN BU_VENDEDOR BV ON COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE I.SCOPE_MODE = 'GLOBAL'
    AND (
      UPPER(COALESCE(UC.CARGO, '')) IN ('ADMIN', 'DIRETORIA')
      OR LOWER(COALESCE(U.DESCR, '')) = 'ti@benenutri.com'
    )
    AND (
      I.SCOPE_COD_SUPERVISOR IS NULL
      OR EXISTS (
        SELECT 1
        FROM COORDENADORES_BU CB_GLOBAL
        WHERE CB_GLOBAL.COD_SUPERVISOR = I.SCOPE_COD_SUPERVISOR
          AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = CAST(CB_GLOBAL.CODFILIAL AS CHAR)
          AND TRIM(CAST(BV.BU_CODIGO AS CHAR)) = CAST(CB_GLOBAL.CODEPTO AS CHAR)
      )
    )
    AND (I.SCOPE_CODFILIAL IS NULL OR TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) = I.SCOPE_CODFILIAL)
    AND (I.SCOPE_CODEPTO IS NULL OR TRIM(CAST(BV.BU_CODIGO AS CHAR)) = I.SCOPE_CODEPTO)
    AND (
      I.SCOPE_ID_SECAO IS NULL
      OR TRIM(CAST(BV.ID_SECAO AS CHAR)) = I.SCOPE_ID_SECAO
      OR LPAD(TRIM(CAST(BV.ID_SECAO AS CHAR)), 2, '0') = I.SCOPE_ID_SECAO
    )
),
BU_SCOPE AS (
  SELECT DISTINCT
    TU.USER_ID AS TARGET_USER_ID,
    BV.VENDEDOR_ID,
    TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL,
    TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO,
    BV.ID_SECAO
  FROM TARGET_USERS TU
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = TU.USER_ID
  WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
    AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) <> ''
    AND TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) <> ''
),
CARTEIRA_SCOPE AS (
  SELECT DISTINCT
    TU.USER_ID AS TARGET_USER_ID,
    C.ID AS CLIENTE_ID,
    TRIM(CAST(COALESCE(C.WINTHOR_CODCLI, C.ID) AS CHAR)) AS CODCLI
  FROM TARGET_USERS TU
  JOIN EQUIPE_CLIENTE EC ON EC.ID_VENDEDOR = TU.USER_ID
  JOIN CLIENTES C ON C.ID = EC.ID_CLIENTE
  WHERE COALESCE(C.WINTHOR_CODCLI, C.ID) IS NOT NULL
),
VENDAS_ATRIBUIDAS AS (
  SELECT R.*
  FROM PEDIDOS_SEMANAIS_SYNC_RAW R
  JOIN BU_SCOPE B ON ${RAW_SECTION_MATCH}
  JOIN CARTEIRA_SCOPE CS ON ${RAW_CARTEIRA_MATCH}
  WHERE R.ATIVO = TRUE
    AND R.STATUS_INGESTAO = 'ATIVO'
),
DEVOLUCOES_ATRIBUIDAS AS (
  SELECT D.*
  FROM IMP_DEVOLUCOES_TOTVS D
  JOIN BU_SCOPE B ON ${DEV_SECTION_MATCH}
  JOIN CARTEIRA_SCOPE CS ON ${DEV_CARTEIRA_MATCH}
),
DIAS_BASE AS (
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 20 DAY) AS DATA_REF UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 19 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 18 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 17 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 16 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 15 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 14 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 13 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 12 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 11 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 10 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 9 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 8 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 7 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 6 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 5 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 4 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 3 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 2 DAY) UNION ALL
  SELECT DATE_SUB(CURRENT_DATE, INTERVAL 1 DAY) UNION ALL
  SELECT CURRENT_DATE
),
DIAS AS (
  SELECT DATA_REF
  FROM (
    SELECT DATA_REF
    FROM DIAS_BASE
    WHERE WEEKDAY(DATA_REF) < 5
    ORDER BY DATA_REF DESC
    LIMIT 7
  ) ULTIMOS_DIAS_UTEIS
),
VENDAS_DIA AS (
  SELECT
    STR_TO_DATE(V.DATA_SAIDA, '%Y-%m-%d') AS DATA_REF,
    ROUND(SUM(V.TOTAL), 2) AS VENDAS_BRUTAS
  FROM VENDAS_ATRIBUIDAS V
  WHERE V.DATA_SAIDA IS NOT NULL
    AND V.DATA_SAIDA <> ''
    AND STR_TO_DATE(V.DATA_SAIDA, '%Y-%m-%d') BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 20 DAY) AND CURRENT_DATE
  GROUP BY STR_TO_DATE(V.DATA_SAIDA, '%Y-%m-%d')
),
DEVOLUCOES_DIA AS (
  SELECT
    STR_TO_DATE(SUBSTRING(CAST(D.DATA_DEVOLUCAO AS CHAR), 1, 10), '%Y-%m-%d') AS DATA_REF,
    ROUND(SUM(D.VALOR_DEVOLVIDO), 2) AS DEVOLUCOES
  FROM DEVOLUCOES_ATRIBUIDAS D
  WHERE CAST(D.DATA_DEVOLUCAO AS CHAR) REGEXP '^[0-9]{4}-[0-9]{2}-[0-9]{2}'
    AND STR_TO_DATE(SUBSTRING(CAST(D.DATA_DEVOLUCAO AS CHAR), 1, 10), '%Y-%m-%d') BETWEEN DATE_SUB(CURRENT_DATE, INTERVAL 20 DAY) AND CURRENT_DATE
  GROUP BY STR_TO_DATE(SUBSTRING(CAST(D.DATA_DEVOLUCAO AS CHAR), 1, 10), '%Y-%m-%d')
),
SERIE AS (
  SELECT
    D.DATA_REF,
    DATE_FORMAT(D.DATA_REF, '%d/%m') AS DIA_LABEL,
    ROUND(COALESCE(V.VENDAS_BRUTAS, 0) - COALESCE(DEV.DEVOLUCOES, 0), 2) AS VALOR_ATUAL
  FROM DIAS D
  LEFT JOIN VENDAS_DIA V ON V.DATA_REF = D.DATA_REF
  LEFT JOIN DEVOLUCOES_DIA DEV ON DEV.DATA_REF = D.DATA_REF
)
SELECT
  DATE_FORMAT(S.DATA_REF, '%Y-%m-%d') AS DATA_REF,
  S.DIA_LABEL,
  S.VALOR_ATUAL,
  P.VALOR_ATUAL AS VALOR_ANTERIOR,
  CASE
    WHEN P.VALOR_ATUAL IS NULL THEN NULL
    WHEN P.VALOR_ATUAL = 0 AND S.VALOR_ATUAL = 0 THEN 0
    WHEN P.VALOR_ATUAL = 0 THEN NULL
    ELSE ROUND(((S.VALOR_ATUAL - P.VALOR_ATUAL) / P.VALOR_ATUAL) * 100, 1)
  END AS VARIACAO_DIA
FROM SERIE S
LEFT JOIN SERIE P ON P.DATA_REF = (
  SELECT MAX(D2.DATA_REF)
  FROM DIAS D2
  WHERE D2.DATA_REF < S.DATA_REF
)
ORDER BY S.DATA_REF`;

function extractRows(response) {
  let output = response?.result?.output;
  if (typeof output === 'string') {
    try { output = JSON.parse(output); } catch { return []; }
  }
  if (Array.isArray(output?.rows)) return output.rows;
  if (Array.isArray(output?.result)) return output.result;
  if (Array.isArray(output)) return output;
  return [];
}

async function smoke(input) {
  const response = await executeServerFunctionMitra({ projectId, serverFunctionId, input });
  const status = String(response?.result?.executionStatus || '');
  const error = String(response?.result?.error || '').trim();
  if ((status && status !== 'COMPLETED') || error) throw new Error(`SF ${serverFunctionId} falhou: ${error || status}`);
  return extractRows(response);
}

async function main() {
  const current = await readServerFunctionMitra({ projectId, serverFunctionId });
  if (current?.result?.name !== 'dashboardVendasDiarias') {
    throw new Error(`SF ${serverFunctionId} esperada dashboardVendasDiarias, encontrada ${current?.result?.name || 'sem nome'}.`);
  }

  await updateServerFunctionMitra({
    projectId,
    serverFunctionId,
    code,
    description: 'Serie dos ultimos 7 dias uteis do dashboard inicial com vendas liquidas, respeitando escopo ME, TEAM, SELLER e GLOBAL da diretoria.',
  });

  const globalRows = await smoke({
    scopeMode: 'GLOBAL',
    scopeUserId: '',
    scopeCodRca: '',
    scopeCodSupervisor: '',
    scopeCodFilial: '',
    scopeCodepto: '',
    scopeIdSecao: '',
  });
  const coordRows = await smoke({
    scopeMode: 'GLOBAL',
    scopeUserId: '',
    scopeCodRca: '',
    scopeCodSupervisor: '469',
    scopeCodFilial: '',
    scopeCodepto: '',
    scopeIdSecao: '',
  });

  console.log(`dashboardVendasDiarias GLOBAL OK (${globalRows.length} linhas). Coordenador 469 OK (${coordRows.length} linhas).`);
}

main().catch((error) => {
  console.error('Falha ao atualizar vendas diarias da diretoria:');
  console.error(error?.message || error);
  process.exit(1);
});
