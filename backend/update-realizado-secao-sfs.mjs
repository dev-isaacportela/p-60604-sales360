function temperatureDetailBaseCte() {
  return `INPUTS AS (
      SELECT
        CASE WHEN '{{idCliente}}' REGEXP '^[0-9]+$' THEN CAST('{{idCliente}}' AS UNSIGNED) ELSE 0 END AS ID_CLIENTE_REF,
        CASE WHEN '{{idVendedor}}' REGEXP '^[0-9]+$' THEN CAST('{{idVendedor}}' AS UNSIGNED) ELSE :VAR_USER END AS ID_VENDEDOR_REF,
        CASE WHEN '{{codFilial}}' REGEXP '^[0-9]+$' THEN '{{codFilial}}' ELSE '' END AS CODFILIAL_REF,
        CASE WHEN TRIM('{{idSecao}}') <> '' AND LOCATE('{', '{{idSecao}}') = 0 THEN LEFT(TRIM('{{idSecao}}'), 20) ELSE '' END AS ID_SECAO_REF
    ),
    CARTEIRA_LOGADA_RAW AS (
      SELECT EC.ID_CLIENTE, EC.ID_VENDEDOR
      FROM INPUTS I
      JOIN EQUIPE_CLIENTE EC ON EC.ID_CLIENTE = I.ID_CLIENTE_REF
      LEFT JOIN FUNCIONARIOS F ON F.ID = EC.ID_VENDEDOR
      WHERE ${visibleOwnerPredicate('EC.ID_VENDEDOR', 'I.ID_VENDEDOR_REF')}
    ),
    CARTEIRA_LOGADA AS (
      SELECT BASE.ID_CLIENTE, BASE.ID_VENDEDOR AS VENDEDOR_DONO_CLIENTE
      FROM (
        SELECT CLR.*, ROW_NUMBER() OVER (PARTITION BY CLR.ID_CLIENTE ORDER BY CASE WHEN CLR.ID_VENDEDOR = (SELECT ID_VENDEDOR_REF FROM INPUTS) THEN 0 ELSE 1 END, CLR.ID_VENDEDOR) AS RN
        FROM CARTEIRA_LOGADA_RAW CLR
      ) BASE
      WHERE BASE.RN = 1
    ),
    BU_SCOPE AS (
      SELECT DISTINCT CL.VENDEDOR_DONO_CLIENTE AS TARGET_USER_ID, BV.VENDEDOR_ID, TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL, TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO, BV.ID_SECAO
      FROM CARTEIRA_LOGADA CL
      JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = CL.VENDEDOR_DONO_CLIENTE
      WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
        AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) <> ''
        AND TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) <> ''
    ),
    BASE_VENDAS AS (
      SELECT R.*, CL.VENDEDOR_DONO_CLIENTE
      FROM PEDIDOS_SEMANAIS_SYNC_RAW R
      JOIN INPUTS I ON 1 = 1
      JOIN CARTEIRA_LOGADA CL ON CL.ID_CLIENTE = R.CLIENTE_ID
      JOIN BU_SCOPE B ON B.TARGET_USER_ID = CL.VENDEDOR_DONO_CLIENTE AND ${RAW_SECTION_MATCH}
      WHERE R.ATIVO = TRUE
        AND R.STATUS_INGESTAO = 'ATIVO'
        AND R.CLIENTE_ID = I.ID_CLIENTE_REF
        AND (I.CODFILIAL_REF = '' OR TRIM(COALESCE(CAST(R.CODFILIAL AS CHAR), '')) = I.CODFILIAL_REF)
        AND (I.ID_SECAO_REF = '' OR LEFT(TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR)), 20) = I.ID_SECAO_REF OR LPAD(LEFT(TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR)), 20), 2, '0') = I.ID_SECAO_REF)
    )`;
}

