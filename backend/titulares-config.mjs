// Quem NUNCA pode ser candidato/titular: usuários bloqueados (tela Executivas de Venda)
// e usuários institucionais (por e-mail — os IDs podem diferir entre DEV e PROD).
export const EMAILS_INSTITUCIONAIS = ['comunicacao@benenutri.com'];

export const USUARIOS_EXCLUIDOS_SQL = `(
    SELECT UB_EXC.USER_ID FROM USUARIO_BLOQUEIO UB_EXC WHERE UB_EXC.BLOQUEADO = 1
    UNION
    SELECT UI_EXC.ID FROM INT_USER UI_EXC WHERE LOWER(TRIM(UI_EXC.DESCR)) IN (${EMAILS_INSTITUCIONAIS.map((e) => `'${e}'`).join(', ')})
  )`;

// Combinações com UM único candidato (vira titular AUTO)
export const CANDIDATOS_UNICOS_SQL = `
  SELECT EC.ID_CLIENTE,
         TRIM(CAST(BV.CODFILIAL AS CHAR)) AS CODFILIAL,
         TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO,
         BV.ID_SECAO,
         MIN(BV.VENDEDOR_ID) AS VENDEDOR_ID
  FROM EQUIPE_CLIENTE EC
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = EC.ID_VENDEDOR
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE BV.VENDEDOR_ID NOT IN ${USUARIOS_EXCLUIDOS_SQL}
    AND BV.ID_SECAO IS NOT NULL
    AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) <> ''
    AND TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) <> ''
  GROUP BY EC.ID_CLIENTE, TRIM(CAST(BV.CODFILIAL AS CHAR)), TRIM(CAST(BV.BU_CODIGO AS CHAR)), BV.ID_SECAO
  HAVING COUNT(DISTINCT BV.VENDEDOR_ID) = 1`;

// Todos os candidatos válidos (para validar titular MANUAL)
export const CANDIDATOS_VALIDOS_SQL = `
  SELECT DISTINCT EC.ID_CLIENTE,
         TRIM(CAST(BV.CODFILIAL AS CHAR)) AS CODFILIAL,
         TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO,
         BV.ID_SECAO,
         BV.VENDEDOR_ID
  FROM EQUIPE_CLIENTE EC
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = EC.ID_VENDEDOR
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE BV.VENDEDOR_ID NOT IN ${USUARIOS_EXCLUIDOS_SQL}
    AND BV.ID_SECAO IS NOT NULL`;

// Remove AUTO que deixou de ser candidato único e MANUAL cujo vendedor deixou de ser candidato
// (saiu da carteira, perdeu a BU, foi bloqueado). Manual válido nunca é tocado.
export const SYNC_LIMPAR_SQL = `DELETE T FROM CLIENTE_TITULAR_DEPTO T
  LEFT JOIN (${CANDIDATOS_UNICOS_SQL}) U
    ON U.ID_CLIENTE = T.ID_CLIENTE AND U.CODFILIAL = T.CODFILIAL
   AND U.CODEPTO = T.CODEPTO AND U.ID_SECAO = T.ID_SECAO AND U.VENDEDOR_ID = T.VENDEDOR_ID
  LEFT JOIN (${CANDIDATOS_VALIDOS_SQL}) V
    ON V.ID_CLIENTE = T.ID_CLIENTE AND V.CODFILIAL = T.CODFILIAL
   AND V.CODEPTO = T.CODEPTO AND V.ID_SECAO = T.ID_SECAO AND V.VENDEDOR_ID = T.VENDEDOR_ID
  WHERE (T.ORIGEM = 'AUTO' AND U.ID_CLIENTE IS NULL)
     OR (COALESCE(T.ORIGEM, '') <> 'AUTO' AND V.ID_CLIENTE IS NULL)`;

export const SYNC_INSERIR_SQL = `INSERT IGNORE INTO CLIENTE_TITULAR_DEPTO (ID_CLIENTE, CODFILIAL, CODEPTO, ID_SECAO, VENDEDOR_ID, ORIGEM, ATIVO, CRIADO_EM, ATUALIZADO_EM)
  SELECT U.ID_CLIENTE, U.CODFILIAL, U.CODEPTO, U.ID_SECAO, U.VENDEDOR_ID, 'AUTO', TRUE,
         DATE_FORMAT(NOW(), '%Y-%m-%dT%H:%i:%s'), DATE_FORMAT(NOW(), '%Y-%m-%dT%H:%i:%s')
  FROM (${CANDIDATOS_UNICOS_SQL}) U`;
