import 'dotenv/config';
import { configureSdkMitra, runQueryMitra } from 'mitra-sdk';

function decodeTokenPayload(token) {
  try {
    const raw = String(token || '').replace(/^Bearer\s+/i, '');
    const parts = raw.split('.');
    if (parts.length < 2) return null;
    const normalized = parts[1].replace(/-/g, '+').replace(/_/g, '/');
    const padded = normalized + '='.repeat((4 - (normalized.length % 4)) % 4);
    return JSON.parse(Buffer.from(padded, 'base64').toString('utf8'));
  } catch {
    return null;
  }
}

const payload = decodeTokenPayload(process.env.MITRA_TOKEN);
const baseURL = process.env.MITRA_BASE_URL || payload?.backURL || process.env.MITRA_BASE_URL_SPACE;

configureSdkMitra({
  baseURL,
  token: process.env.MITRA_TOKEN,
  integrationURL: process.env.MITRA_BASE_URL_INTEGRATIONS || baseURL,
});

const projectId = Number(process.env.MITRA_PROJECT_ID);

const sql = `
WITH ESCOPO_COMPLETO AS (
  SELECT DISTINCT
    EC.ID_CLIENTE,
    TRIM(COALESCE(EC.CODFILIAL, '')) AS CODFILIAL,
    COALESCE(
      (SELECT B.CODIGO FROM BU B WHERE UPPER(TRIM(B.CODIGO)) = UPPER(TRIM(BV.BU_CODIGO)) LIMIT 1),
      (SELECT B.CODIGO FROM BU B WHERE UPPER(TRIM(B.NOME)) = UPPER(TRIM(BV.BU_CODIGO)) LIMIT 1),
      CASE WHEN TRIM(BV.BU_CODIGO) REGEXP '^[0-9]+$' THEN CAST(CAST(BV.BU_CODIGO AS UNSIGNED) AS CHAR) ELSE TRIM(BV.BU_CODIGO) END
    ) AS CODEPTO,
    EC.ID_SECAO
  FROM EQUIPE_CLIENTE EC
  LEFT JOIN FUNCIONARIOS F ON F.ID = EC.ID_VENDEDOR
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = EC.ID_VENDEDOR
    AND BV.CODFILIAL = EC.CODFILIAL
    AND BV.ID_SECAO = EC.ID_SECAO
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE (EC.ID_VENDEDOR = 5 OR F.ID_SUBSTITUTO = 5)
    AND BV.CODFILIAL IS NOT NULL
    AND TRIM(COALESCE(BV.CODFILIAL, '')) <> ''
    AND BV.ID_SECAO IS NOT NULL
),
ESCOPO_FALLBACK_BU AS (
  SELECT DISTINCT
    EC.ID_CLIENTE,
    NULL AS CODFILIAL,
    COALESCE(
      (SELECT B.CODIGO FROM BU B WHERE UPPER(TRIM(B.CODIGO)) = UPPER(TRIM(BV.BU_CODIGO)) LIMIT 1),
      (SELECT B.CODIGO FROM BU B WHERE UPPER(TRIM(B.NOME)) = UPPER(TRIM(BV.BU_CODIGO)) LIMIT 1),
      CASE WHEN TRIM(BV.BU_CODIGO) REGEXP '^[0-9]+$' THEN CAST(CAST(BV.BU_CODIGO AS UNSIGNED) AS CHAR) ELSE TRIM(BV.BU_CODIGO) END
    ) AS CODEPTO,
    NULL AS ID_SECAO
  FROM EQUIPE_CLIENTE EC
  LEFT JOIN FUNCIONARIOS F ON F.ID = EC.ID_VENDEDOR
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = EC.ID_VENDEDOR
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE (EC.ID_VENDEDOR = 5 OR F.ID_SUBSTITUTO = 5)
    AND (BV.CODFILIAL IS NULL OR TRIM(COALESCE(BV.CODFILIAL, '')) = '')
    AND BV.ID_SECAO IS NULL
    AND NOT EXISTS (
      SELECT 1
      FROM BU_VENDEDOR BV2
      WHERE BV2.VENDEDOR_ID = EC.ID_VENDEDOR
        AND COALESCE(BV2.ATIVO, TRUE) = TRUE
        AND BV2.CODFILIAL IS NOT NULL
        AND TRIM(COALESCE(BV2.CODFILIAL, '')) <> ''
        AND BV2.ID_SECAO IS NOT NULL
    )
),
ESCOPO AS (
  SELECT * FROM ESCOPO_COMPLETO
  UNION
  SELECT * FROM ESCOPO_FALLBACK_BU
),
BASE_ATUAL AS (
  SELECT PS.*
  FROM PEDIDOS_SEMANAIS_SYNC PS
  JOIN ESCOPO E ON E.ID_CLIENTE = PS.CLIENTE_ID
    AND (
      (
        E.CODFILIAL IS NOT NULL
        AND TRIM(COALESCE(CAST(PS.CODFILIAL AS CHAR), '')) = E.CODFILIAL
        AND CAST(PS.CODEPTO AS CHAR) = E.CODEPTO
        AND PS.ID_SECAO = E.ID_SECAO
      )
      OR (
        E.CODFILIAL IS NULL
        AND E.ID_SECAO IS NULL
        AND CAST(PS.CODEPTO AS CHAR) = E.CODEPTO
      )
    )
  WHERE PS.ATIVO = TRUE
    AND PS.ANO = YEAR(CURRENT_DATE)
    AND PS.MES = MONTH(CURRENT_DATE)
    AND ('' = '' OR UPPER(PS.SEGMENTO) = UPPER(''))
    AND ('' = '' OR PS.CODFILIAL = '')
    AND ('' = '' OR PS.ID_SECAO = CAST('' AS SIGNED))
)
SELECT
  (SELECT COUNT(*) FROM ESCOPO_COMPLETO) AS C_ESC_COMPLETO,
  (SELECT COUNT(*) FROM ESCOPO_FALLBACK_BU) AS C_ESC_FALLBACK,
  (SELECT COUNT(*) FROM ESCOPO) AS C_ESC_TOTAL,
  (SELECT COUNT(*) FROM BASE_ATUAL) AS C_BASE_ATUAL
`;

const response = await runQueryMitra({ projectId, sql });
const resumo = response?.result?.rows || [];

const sqlEscopoCodepto = `
WITH ESCOPO_FALLBACK_BU AS (
  SELECT DISTINCT
    EC.ID_CLIENTE,
    COALESCE(
      (SELECT B.CODIGO FROM BU B WHERE UPPER(TRIM(B.CODIGO)) = UPPER(TRIM(BV.BU_CODIGO)) LIMIT 1),
      (SELECT B.CODIGO FROM BU B WHERE UPPER(TRIM(B.NOME)) = UPPER(TRIM(BV.BU_CODIGO)) LIMIT 1),
      CASE WHEN TRIM(BV.BU_CODIGO) REGEXP '^[0-9]+$' THEN CAST(CAST(BV.BU_CODIGO AS UNSIGNED) AS CHAR) ELSE TRIM(BV.BU_CODIGO) END
    ) AS CODEPTO
  FROM EQUIPE_CLIENTE EC
  LEFT JOIN FUNCIONARIOS F ON F.ID = EC.ID_VENDEDOR
  JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = EC.ID_VENDEDOR
    AND COALESCE(BV.ATIVO, TRUE) = TRUE
  WHERE (EC.ID_VENDEDOR = 5 OR F.ID_SUBSTITUTO = 5)
    AND (BV.CODFILIAL IS NULL OR TRIM(COALESCE(BV.CODFILIAL, '')) = '')
    AND BV.ID_SECAO IS NULL
    AND NOT EXISTS (
      SELECT 1
      FROM BU_VENDEDOR BV2
      WHERE BV2.VENDEDOR_ID = EC.ID_VENDEDOR
        AND COALESCE(BV2.ATIVO, TRUE) = TRUE
        AND BV2.CODFILIAL IS NOT NULL
        AND TRIM(COALESCE(BV2.CODFILIAL, '')) <> ''
        AND BV2.ID_SECAO IS NOT NULL
    )
)
SELECT CODEPTO, COUNT(*) AS TOTAL
FROM ESCOPO_FALLBACK_BU
GROUP BY CODEPTO
ORDER BY TOTAL DESC
`;

const sqlPsCodepto = `
WITH CARTEIRA AS (
  SELECT DISTINCT EC.ID_CLIENTE
  FROM EQUIPE_CLIENTE EC
  LEFT JOIN FUNCIONARIOS F ON F.ID = EC.ID_VENDEDOR
  WHERE (EC.ID_VENDEDOR = 5 OR F.ID_SUBSTITUTO = 5)
)
SELECT CAST(PS.CODEPTO AS CHAR) AS CODEPTO, COUNT(*) AS TOTAL
FROM PEDIDOS_SEMANAIS_SYNC PS
JOIN CARTEIRA C ON C.ID_CLIENTE = PS.CLIENTE_ID
WHERE PS.ATIVO = TRUE
  AND PS.ANO = YEAR(CURRENT_DATE)
  AND PS.MES = MONTH(CURRENT_DATE)
GROUP BY CAST(PS.CODEPTO AS CHAR)
ORDER BY TOTAL DESC
`;

const escopoCodepto = await runQueryMitra({ projectId, sql: sqlEscopoCodepto });
const psCodepto = await runQueryMitra({ projectId, sql: sqlPsCodepto });

console.log(
  JSON.stringify(
    {
      resumo,
      escopoCodepto: escopoCodepto?.result?.rows || [],
      pedidosCodeptoMesAtual: psCodepto?.result?.rows || [],
    },
    null,
    2,
  ),
);
