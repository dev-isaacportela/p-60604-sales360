import 'dotenv/config';
import { configureSdkMitra, readServerFunctionMitra, updateServerFunctionMitra } from 'mitra-sdk';

function decodeTokenPayload(token) {
  try {
    const raw = String(token || '').replace(/^Bearer\s+/i, '');
    const parts = raw.split('.');
    if (parts.length < 2) return null;
    const normalized = parts[1].replace(/-/g, '+').replace(/_/g, '/');
    const padded = normalized + '='.repeat((4 - (normalized.length % 4)) % 4);
    return JSON.parse(Buffer.from(padded, 'base64').toString('utf8'));
  } catch {
    return null;
  }
}

const payload = decodeTokenPayload(process.env.MITRA_TOKEN);
const baseURL = process.env.MITRA_BASE_URL || payload?.backURL || process.env.MITRA_BASE_URL_SPACE;
const integrationURL = process.env.MITRA_BASE_URL_INTEGRATIONS || baseURL;

configureSdkMitra({
  baseURL,
  token: process.env.MITRA_TOKEN,
  integrationURL,
});

const projectId = Number(process.env.MITRA_PROJECT_ID);
const serverFunctionId = 110;

const RAW_SECTION_MATCH = `
  B.CODFILIAL = TRIM(COALESCE(CAST(R.CODFILIAL AS CHAR), ''))
  AND B.CODEPTO = TRIM(CAST(R.CODEPTO AS CHAR))
  AND (
    (
      B.ID_SECAO IS NOT NULL
      AND (
        TRIM(CAST(B.ID_SECAO AS CHAR)) = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
        OR LPAD(TRIM(CAST(B.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
      )
    )
    OR (
      B.ID_SECAO IS NULL
      AND NOT EXISTS (
        SELECT 1
        FROM BU_SCOPE B2
        WHERE B2.TARGET_USER_ID = B.TARGET_USER_ID
          AND B2.CODFILIAL = B.CODFILIAL
          AND B2.CODEPTO = B.CODEPTO
          AND B2.ID_SECAO IS NOT NULL
          AND (
            TRIM(CAST(B2.ID_SECAO AS CHAR)) = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
            OR LPAD(TRIM(CAST(B2.ID_SECAO AS CHAR)), 2, '0') = TRIM(CAST(COALESCE(R.ID_SECAO, R.CODSECAO) AS CHAR))
          )
      )
    )
  )
`;

const CODE = `WITH INPUTS AS (
    SELECT
      CASE WHEN '{{vendedorId}}' REGEXP '^[0-9]+$' THEN CAST('{{vendedorId}}' AS UNSIGNED) ELSE NULL END AS VENDEDOR_PARAM,
      CASE WHEN '{{ID_CLIENTE}}' REGEXP '^[0-9]+$' THEN CAST('{{ID_CLIENTE}}' AS UNSIGNED) ELSE 0 END AS CLIENTE_PARAM,
      CASE WHEN '{{ANO}}' REGEXP '^[0-9]{4}$' THEN CAST('{{ANO}}' AS UNSIGNED) ELSE YEAR(CURRENT_DATE) END AS ANO_PARAM,
      CASE WHEN '{{MES}}' REGEXP '^[0-9]{1,2}$' THEN CAST('{{MES}}' AS UNSIGNED) ELSE MONTH(CURRENT_DATE) END AS MES_PARAM,
      CASE WHEN '{{SEMANA_NUMERO}}' REGEXP '^[0-9]{1,2}$' THEN CAST('{{SEMANA_NUMERO}}' AS UNSIGNED) ELSE CEIL(DAY(CURRENT_DATE) / 7) END AS SEMANA_PARAM
  ),
  TARGET_USERS AS (
    SELECT COALESCE(I.VENDEDOR_PARAM, :VAR_USER) AS USER_ID FROM INPUTS I
    UNION
    SELECT F.ID AS USER_ID
    FROM FUNCIONARIOS F
    JOIN INPUTS I ON F.ID_SUBSTITUTO = COALESCE(I.VENDEDOR_PARAM, :VAR_USER)

    UNION

    SELECT VR_DONO.USER_ID AS USER_ID
    FROM INPUTS I
    JOIN VENDEDOR_RCA VR_SUB ON VR_SUB.USER_ID = COALESCE(I.VENDEDOR_PARAM, :VAR_USER)
    JOIN FERIAS_VENDEDOR FV ON FV.COD_RCA_SUBSTITUTO = VR_SUB.COD_RCA
    JOIN VENDEDOR_RCA VR_DONO ON VR_DONO.COD_RCA = FV.COD_RCA
    WHERE COALESCE(FV.ATIVO, TRUE) = TRUE
      AND CURRENT_DATE BETWEEN FV.DT_INICIO AND FV.DT_FIM
  ),
  BU_SCOPE AS (
    SELECT DISTINCT
      TU.USER_ID AS TARGET_USER_ID,
      BV.VENDEDOR_ID,
      TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) AS CODFILIAL,
      TRIM(CAST(BV.BU_CODIGO AS CHAR)) AS CODEPTO,
      BV.ID_SECAO
    FROM TARGET_USERS TU
    JOIN BU_VENDEDOR BV ON BV.VENDEDOR_ID = TU.USER_ID
    WHERE COALESCE(BV.ATIVO, TRUE) = TRUE
      AND TRIM(COALESCE(CAST(BV.CODFILIAL AS CHAR), '')) <> ''
      AND TRIM(COALESCE(CAST(BV.BU_CODIGO AS CHAR), '')) <> ''
  ),
  PERIODO_ANTERIOR AS (
    SELECT
      CASE WHEN I.MES_PARAM = 1 THEN 12 ELSE I.MES_PARAM - 1 END AS MES_ANT,
      CASE WHEN I.MES_PARAM = 1 THEN I.ANO_PARAM - 1 ELSE I.ANO_PARAM END AS ANO_ANT
    FROM INPUTS I
  ),
  BASE_HISTORICA AS (
    SELECT R.*
    FROM PEDIDOS_SEMANAIS_SYNC_RAW R
    JOIN INPUTS I ON 1 = 1
    JOIN BU_SCOPE B ON ${RAW_SECTION_MATCH}
    WHERE R.ATIVO = TRUE
      AND R.STATUS_INGESTAO = 'ATIVO'
      AND R.CLIENTE_ID = I.CLIENTE_PARAM
      AND R.CODPROD IS NOT NULL
  ),
  ITENS_BASE AS (
    SELECT
      R.ANO,
      R.MES,
      R.SEMANA_NUMERO,
      R.CODPROD,
      COALESCE(NULLIF(TRIM(R.DESCRICAO), ''), CONCAT('Produto ', CAST(R.CODPROD AS CHAR))) AS DESCRICAO_PRODUTO,
      CASE
        WHEN COALESCE(R.QT, 0) > 0 THEN COALESCE(R.QT, 0)
        WHEN COALESCE(R.VLUNIT, 0) > 0 AND COALESCE(R.TOTAL, 0) <> 0 THEN COALESCE(R.TOTAL, 0) / COALESCE(R.VLUNIT, 0)
        WHEN COALESCE(R.TOTAL, 0) > 0 THEN 1
        ELSE 0
      END AS QT_EFETIVA,
      COALESCE(R.TOTAL, 0) AS VALOR_TOTAL
    FROM BASE_HISTORICA R
  ),
  PRODUTOS_SEMANAIS AS (
    SELECT
      IB.ANO,
      IB.MES,
      IB.SEMANA_NUMERO,
      IB.CODPROD,
      MAX(IB.DESCRICAO_PRODUTO) AS DESCRICAO_PRODUTO,
      ROUND(SUM(IB.QT_EFETIVA), 6) AS QTD_SEMANA,
      ROUND(SUM(IB.VALOR_TOTAL), 2) AS VALOR_TOTAL_SEMANA,
      ROUND(CASE WHEN SUM(IB.QT_EFETIVA) = 0 THEN 0 ELSE SUM(IB.VALOR_TOTAL) / SUM(IB.QT_EFETIVA) END, 6) AS VALOR_UNITARIO
    FROM ITENS_BASE IB
    GROUP BY IB.ANO, IB.MES, IB.SEMANA_NUMERO, IB.CODPROD
  ),
  SEMANA_ATUAL AS (
    SELECT PS.*
    FROM PRODUTOS_SEMANAIS PS
    JOIN INPUTS I ON I.ANO_PARAM = PS.ANO AND I.MES_PARAM = PS.MES AND I.SEMANA_PARAM = PS.SEMANA_NUMERO
  ),
  SEMANA_ANTERIOR AS (
    SELECT PS.*
    FROM PRODUTOS_SEMANAIS PS
    JOIN INPUTS I ON I.SEMANA_PARAM = PS.SEMANA_NUMERO
    JOIN PERIODO_ANTERIOR PA ON PA.ANO_ANT = PS.ANO AND PA.MES_ANT = PS.MES
  ),
  PRODUTOS_COMPARADOS AS (
    SELECT
      BASE.CODPROD,
      MAX(BASE.DESCRICAO_PRODUTO) AS DESCRICAO_PRODUTO
    FROM (
      SELECT CODPROD, DESCRICAO_PRODUTO FROM SEMANA_ATUAL
      UNION ALL
      SELECT CODPROD, DESCRICAO_PRODUTO FROM SEMANA_ANTERIOR
    ) BASE
    GROUP BY BASE.CODPROD
  ),
  HISTORICO_RANKEADO AS (
    SELECT
      PS.*,
      ROW_NUMBER() OVER (PARTITION BY PS.CODPROD ORDER BY PS.ANO DESC, PS.MES DESC, PS.SEMANA_NUMERO DESC) AS RN
    FROM PRODUTOS_SEMANAIS PS
  ),
  HISTORICO_RECENTE AS (
    SELECT
      HR.CODPROD,
      GROUP_CONCAT(
        CONCAT(HR.ANO, '-', LPAD(HR.MES, 2, '0'), '-S', HR.SEMANA_NUMERO, ':', CAST(ROUND(HR.QTD_SEMANA, 3) AS CHAR))
        ORDER BY HR.ANO DESC, HR.MES DESC, HR.SEMANA_NUMERO DESC
        SEPARATOR '|'
      ) AS HISTORICO_SEMANAL
    FROM HISTORICO_RANKEADO HR
    WHERE HR.RN <= 8
    GROUP BY HR.CODPROD
  ),
  HISTORICO_PICO AS (
    SELECT
      PS.CODPROD,
      ROUND(MAX(PS.QTD_SEMANA), 6) AS QTD_PICO_HISTORICO,
      COUNT(*) AS TOTAL_SEMANAS_HISTORICO
    FROM PRODUTOS_SEMANAIS PS
    GROUP BY PS.CODPROD
  )
  SELECT
    PC.CODPROD,
    PC.DESCRICAO_PRODUTO,
    ROUND(COALESCE(SA.QTD_SEMANA, 0), 6) AS QTD_SEMANA_ATUAL,
    ROUND(COALESCE(SP.QTD_SEMANA, 0), 6) AS QTD_SEMANA_MES_ANTERIOR,
    ROUND(COALESCE(SA.QTD_SEMANA, 0) - COALESCE(SP.QTD_SEMANA, 0), 6) AS DELTA_QTD_SEMANA,
    ROUND(COALESCE(SA.VALOR_TOTAL_SEMANA, 0), 2) AS VALOR_TOTAL_PRODUTO_SEMANA,
    ROUND(COALESCE(SP.VALOR_TOTAL_SEMANA, 0), 2) AS VALOR_TOTAL_SEMANA_ANTERIOR,
    ROUND(COALESCE(SA.VALOR_UNITARIO, SP.VALOR_UNITARIO, 0), 6) AS VALOR_UNITARIO,
    COALESCE(HP.QTD_PICO_HISTORICO, 0) AS QTD_PICO_HISTORICO,
    COALESCE(HP.TOTAL_SEMANAS_HISTORICO, 0) AS TOTAL_SEMANAS_HISTORICO,
    COALESCE(HR.HISTORICO_SEMANAL, '') AS HISTORICO_SEMANAL,
    CASE
      WHEN COALESCE(SA.QTD_SEMANA, 0) > 0 AND COALESCE(SP.QTD_SEMANA, 0) = 0 THEN 'NOVO'
      WHEN COALESCE(SA.QTD_SEMANA, 0) = 0 AND COALESCE(SP.QTD_SEMANA, 0) > 0 THEN 'SEM_RECOMPRA'
      WHEN COALESCE(SA.QTD_SEMANA, 0) > COALESCE(SP.QTD_SEMANA, 0) THEN 'ALTA'
      WHEN COALESCE(SA.QTD_SEMANA, 0) < COALESCE(SP.QTD_SEMANA, 0) THEN 'QUEDA'
      ELSE 'ESTAVEL'
    END AS STATUS_COMPARATIVO
  FROM PRODUTOS_COMPARADOS PC
  LEFT JOIN SEMANA_ATUAL SA ON SA.CODPROD = PC.CODPROD
  LEFT JOIN SEMANA_ANTERIOR SP ON SP.CODPROD = PC.CODPROD
  LEFT JOIN HISTORICO_RECENTE HR ON HR.CODPROD = PC.CODPROD
  LEFT JOIN HISTORICO_PICO HP ON HP.CODPROD = PC.CODPROD
  WHERE COALESCE(SA.QTD_SEMANA, 0) > 0 OR COALESCE(SP.QTD_SEMANA, 0) > 0
  ORDER BY
    CASE
      WHEN COALESCE(SA.QTD_SEMANA, 0) = 0 AND COALESCE(SP.QTD_SEMANA, 0) > 0 THEN 0
      WHEN COALESCE(SA.QTD_SEMANA, 0) > COALESCE(SP.QTD_SEMANA, 0) THEN 1
      WHEN COALESCE(SA.QTD_SEMANA, 0) < COALESCE(SP.QTD_SEMANA, 0) THEN 2
      ELSE 3
    END,
    ABS(COALESCE(SA.QTD_SEMANA, 0) - COALESCE(SP.QTD_SEMANA, 0)) DESC,
    COALESCE(SA.VALOR_TOTAL_SEMANA, 0) DESC,
    PC.CODPROD`;

async function main() {
  const current = await readServerFunctionMitra({ projectId, serverFunctionId });
  await updateServerFunctionMitra({
    projectId,
    serverFunctionId,
    code: CODE,
    description: current?.result?.description || 'Detalha itens da semana por cliente com comparativo semanal e sazonalidade.',
  });

  console.log('SF 110 atualizada com comparativo semanal por quantidade e historico recente.');
}

main().catch((error) => {
  console.error('Falha ao atualizar SF 110:');
  console.error(error?.message || error);
  process.exit(1);
});
