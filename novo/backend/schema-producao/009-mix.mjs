// Tabelas de PRODUCAO do Mix Builder (spec 009) — so para o simulador local.
// Contrato: docs/specs/000-visao-geral/modelo-de-dados.md, "Mix e custos".
// NAO e publicado: as tabelas ja existem no Mitra. Custos, catalogo e fotos
// sao preenchidos pelas rotinas do sistema antigo (D-903); a 009 so le.
// FKs ficam de fora (o SQLite do simulador nao as liga).

export const TABELAS = [
  `CREATE TABLE IF NOT EXISTS PRODUCT_MIX (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(220) NOT NULL,
    DESCRICAO TEXT NULL,
    ID_CLIENTE INT NOT NULL,
    ID_USUARIO_CRIACAO INT NOT NULL,
    TOTAL_CUSTO DECIMAL(14,2) DEFAULT 0,
    TOTAL_VENDA DECIMAL(14,2) DEFAULT 0,
    MARGEM_MEDIA DECIMAL(7,2) DEFAULT 0,
    DT_CRIACAO VARCHAR(19) NOT NULL,
    ENVIADO_HISTORICO BOOLEAN DEFAULT FALSE,
    DT_ENVIO_HISTORICO VARCHAR(19) NULL
  )`,

  // ID_PRODUTO = PRODUTOS_CUSTOS.CODPROD (itens antigos podem apontar para PRODUTOS.ID).
  // CMV_PERCENT = CMV do concorrente.
  `CREATE TABLE IF NOT EXISTS PRODUCT_MIX_ITEMS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    ID_MIX INT NOT NULL,
    ID_PRODUTO INT NOT NULL,
    QUANTIDADE INT NOT NULL,
    TIPO_CUSTO VARCHAR(40) NOT NULL,
    CUSTO_UNITARIO DECIMAL(12,2) NOT NULL,
    MARGEM_PERCENT DECIMAL(7,2) NOT NULL,
    PRECO_VENDA DECIMAL(12,2) NOT NULL,
    PRECO_CONCORRENTE DECIMAL(12,2) NULL,
    CMV_PERCENT DECIMAL(7,2) NULL,
    INDEX IDX_PRODUCT_MIX_ITEMS_ID_PRODUTO (ID_PRODUTO)
  )`,

  `CREATE TABLE IF NOT EXISTS PRODUTOS_CUSTOS (
    CODPROD INT NOT NULL PRIMARY KEY,
    CODFAB VARCHAR(60) NOT NULL,
    CODAUXILIAR VARCHAR(60) NULL,
    NOME VARCHAR(255) NOT NULL,
    FORNECEDOR_ID INT NOT NULL,
    DEPARTAMENTO_ID INT NOT NULL,
    SECAO_ID INT NOT NULL,
    ATIVO BOOLEAN NULL
  )`,

  `CREATE TABLE IF NOT EXISTS CUSTO_PADRAO_PRODUTO (
    CODPROD INT NOT NULL PRIMARY KEY,
    CUSTO DECIMAL(12,4) NOT NULL,
    DATA_REF VARCHAR(19) NOT NULL,
    ATUALIZADO_EM VARCHAR(19) NOT NULL
  )`,

  // STATUS vem da gestao de custos: 'ACTIVE' = ativa. Datas 'AAAA-MM-DD'.
  `CREATE TABLE IF NOT EXISTS CUSTO_ESPECIAL_PRODUTO (
    ITEM_ID BIGINT NOT NULL PRIMARY KEY,
    CODPROD INT NOT NULL,
    CLIENTE_ID INT NULL,
    CUSTO DECIMAL(12,4) NOT NULL,
    POLITICA_ID INT NOT NULL,
    POLITICA_NOME VARCHAR(180) NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    FILIAL_ID INT NULL,
    DATA_INICIO VARCHAR(10) NOT NULL,
    DATA_FIM VARCHAR(10) NOT NULL,
    ATUALIZADO_EM VARCHAR(19) NOT NULL,
    INDEX IX_CEP_CODPROD (CODPROD),
    INDEX IX_CEP_CLIENTE (CLIENTE_ID),
    INDEX IX_CEP_POLITICA (POLITICA_ID),
    INDEX IX_CEP_FILIAL (FILIAL_ID)
  )`,

  // Clientes vinculados a um custo especial (CLIENTE_ID = ID ou codigo do ERP).
  `CREATE TABLE IF NOT EXISTS CUSTO_ESPECIAL_CLIENTES_BIG (
    CUSTO_ESPECIAL_ID BIGINT NOT NULL,
    CLIENTE_ID INT NOT NULL,
    PRIMARY KEY (CUSTO_ESPECIAL_ID, CLIENTE_ID),
    INDEX IX_CECB_CLIENTE (CLIENTE_ID)
  )`,

  // Chave/valor do sync de custos. LAST_SUCCESS_AT em UTC (toISOString).
  `CREATE TABLE IF NOT EXISTS MIX_CUSTOS_SYNC (
    CHAVE VARCHAR(80) NOT NULL PRIMARY KEY,
    VALOR VARCHAR(255) NULL,
    ATUALIZADO_EM VARCHAR(19) NOT NULL
  )`,

  `CREATE TABLE IF NOT EXISTS MIX_PRODUTO_FOTO (
    CODPROD INT NOT NULL PRIMARY KEY,
    URL VARCHAR(1000) NOT NULL DEFAULT '',
    NOME_ARQUIVO VARCHAR(255) NULL,
    BUSCADO_EM VARCHAR(19) NOT NULL
  )`,
];
