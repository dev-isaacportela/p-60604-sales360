// SQL da carga de vendas do ERP (spec 006, RF-011..013, RN-013..016).
// Porta a SF 107 do antigo com as correcoes da spec. O corpo publicado de
// s360SemanalCarga roda estes textos em ordem; o smoke roda o mesmo corpo.
// Marcadores: @@exec@@ (id da execucao), @@agora@@ ('AAAA-MM-DD HH:MM:SS',
// Brasilia), @@limite@@ (agora - 30 min), @@retencao@@ (agora - 7 dias).

export const MENSAGENS = {
  manual: 'A carga de vendas roda só pela rotina automática.',
  interrompida: 'Execução interrompida sem finalizar (tempo limite ou queda do processo)',
  emAndamento: (hhmm) => `Já existe uma sincronização em andamento desde ${hhmm}.`,
};

const FONTE = 'IMP_VENDAS_DASHBOARD_TOTVS_RCA';
const texto = (x) => `TRIM(COALESCE(CAST(${x} AS CHAR), ''))`;
const num = (x) => `CAST(TRIM(CAST(${x} AS CHAR)) AS UNSIGNED)`;

// Quantidade corrigida por linha antes de somar (RN-013).
const QT_LINHA = `CASE
      WHEN COALESCE(I.QT, 0) > 0 THEN I.QT
      WHEN COALESCE(I.VLUNIT, 0) > 0 AND COALESCE(I.TOTAL, 0) <> 0 THEN I.TOTAL / I.VLUNIT
      WHEN COALESCE(I.TOTAL, 0) > 0 THEN 1
      ELSE COALESCE(I.QT, 0) END`;

// Linhas repetidas (pedido + produto + filial) somadas num item so (C-019).
const AGRUPADA = `SELECT CONCAT(${texto('I.NUMPED')}, '|', ${texto('I.CODPROD')}, '|', ${texto('I.CODFILIAL')}) AS CHAVE,
    ${texto('I.NUMPED')} AS NUMPED, MAX(CAST(I.NUMTRANSVENDA AS CHAR)) AS NUMTRANSVENDA, MAX(CAST(I.NUMNOTA AS CHAR)) AS NUMNOTA,
    ${texto('I.CODFILIAL')} AS CODFILIAL, I.CODPROD, MAX(I.DESCRICAO) AS DESCRICAO, MAX(I.COD_RCA) AS COD_RCA,
    MAX(I.CODCLI) AS CODCLI, MAX(${texto('I.CODEPTO')}) AS CODEPTO, MAX(I.DEPARTAMENTO) AS DEPARTAMENTO,
    MAX(${texto('I.CODSEC')}) AS CODSEC, MAX(I.SECAO) AS SECAO,
    SUM(${QT_LINHA}) AS QT, MAX(COALESCE(I.VLUNIT, 0)) AS VLUNIT, SUM(COALESCE(I.TOTAL, 0)) AS TOTAL,
    MAX(${texto('I.DTSAIDA')}) AS DTSAIDA
  FROM ${FONTE} I
  WHERE I.NUMPED IS NOT NULL AND I.CODPROD IS NOT NULL
  GROUP BY ${texto('I.NUMPED')}, I.CODPROD, ${texto('I.CODFILIAL')}`;

const DATA_OK = (d) => `(LENGTH(${d}) = 10 AND SUBSTRING(${d}, 5, 1) = '-' AND SUBSTRING(${d}, 8, 1) = '-'
      AND ${d} >= '1900-01-01' AND ${d} <= '2999-12-31')`;

// Validacao na ordem da spec: o primeiro problema define o tipo (RN-013).
const VALIDADA = `SELECT G.*, C.ID AS CLIENTE_ID, COALESCE(NULLIF(TRIM(C.SEGMENTO), ''), 'WINTHOR') AS SEGMENTO, S.ID AS ID_SECAO,
    CASE
      WHEN NOT ${DATA_OK('G.DTSAIDA')} THEN 'ERRO_DATA'
      WHEN C.ID IS NULL THEN 'ERRO_CLIENTE'
      WHEN G.CODFILIAL = '' THEN 'ERRO_FILIAL'
      WHEN G.CODEPTO = '' THEN 'ERRO_BU'
      WHEN G.CODSEC = '' THEN 'ERRO_SECAO'
      WHEN S.ID IS NULL THEN 'ERRO_SECAO_NAO_MAPEADA'
      ELSE 'ATIVO' END AS STATUS_INGESTAO
  FROM (${AGRUPADA}) G
  LEFT JOIN CLIENTES C ON C.WINTHOR_CODCLI = G.CODCLI
  LEFT JOIN BU B ON ${num('B.CODIGO')} = ${num("NULLIF(G.CODEPTO, '')")}
  LEFT JOIN SECAO S ON S.ID = ${num("NULLIF(G.CODSEC, '')")} AND (S.ID_BU = B.ID OR S.ID_BU IS NULL)`;

const DETALHE = `CASE V.STATUS_INGESTAO
      WHEN 'ERRO_DATA' THEN 'Data de saída inválida no ERP'
      WHEN 'ERRO_CLIENTE' THEN CONCAT('Cliente sem cadastro (código do ERP ', COALESCE(CAST(V.CODCLI AS CHAR), 'vazio'), ')')
      WHEN 'ERRO_FILIAL' THEN 'Filial não informada no ERP'
      WHEN 'ERRO_BU' THEN 'Departamento não informado no ERP'
      WHEN 'ERRO_SECAO' THEN 'Seção não informada no ERP'
      WHEN 'ERRO_SECAO_NAO_MAPEADA' THEN CONCAT('Seção ', V.CODSEC, ' não cadastrada para o departamento ', V.CODEPTO)
      END`;

// Semana operacional sem funcao de dia da semana: 1 + sextas-feiras entre o
// dia 1 (exclusive) e a data; 2000-01-07 foi sexta.
const SEMANA = (d) => `(1 + FLOOR(DATEDIFF(${d}, '2000-01-07') / 7) - FLOOR(DATEDIFF(CONCAT(SUBSTRING(${d}, 1, 8), '01'), '2000-01-07') / 7))`;

const VALIDO = "V.STATUS_INGESTAO = 'ATIVO'";

